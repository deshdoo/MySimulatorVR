// Учебный показ работы прибора (замедленная анимация на данных рабочего датчика).
// Всё, что реализует этот интерфейс, само появляется в окне «?» → «Работа приборов»
// (CabinPanels): новые показы добавляются без правки окна.
public interface IДемонстрацияПрибора
{
    string Название { get; }          // «Доплеровский лаг»
    string Описание { get; }          // одна строка: что показывает
    int Порядок { get; }              // место в списке (меньше — выше)
    bool Показано { get; }
    string Состояние { get; }         // «вид сбоку · ½×» — для строки статуса
    void Переключить();               // показать/скрыть
    void СменитьВид();                // вид со стороны / с борта
    void Пауза();
    void СменитьСкорость();           // 1× → ½× → ¼×
}
