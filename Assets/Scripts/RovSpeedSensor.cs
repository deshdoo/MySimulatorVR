// =============================================================================
// RovSpeedSensor.cs
// -----------------------------------------------------------------------------
// Датчик скорости НПА — ДОПЛЕРОВСКИЙ ЛАГ (DVL, Doppler Velocity Log),
// смоделированный как реальный акустический прибор, а не чтение модуля вектора
// скорости из движка.
//
// КАК ЭТО РАБОТАЕТ. Лаг светит вниз пучками ультразвука в дно и слушает эхо.
// Если аппарат движется, частота отражённого звука смещается — эффект Доплера
// (та же причина, по которой сирена приближающейся машины звучит выше). По
// величине смещения частоты вычисляют скорость ОТНОСИТЕЛЬНО ДНА:
//
//        Δf = 2 · f0 · v / c      =>      v = c · Δf / (2 · f0)
//
//   Δf — сдвиг частоты эха (Гц),  f0 — излучаемая частота,
//   v  — скорость относительно дна,  c — скорость звука в воде (~1500 м/с).
//   Двойка — потому что Доплер срабатывает ДВАЖДЫ: и когда звук уходит к дну,
//   и когда отражённый возвращается к движущемуся приёмнику.
//
// ДВА ГЛАВНЫХ «ХАРАКТЕРА» ЭТОГО ПРИБОРА (чего нет у датчика глубины):
//
// 1. ЗАХВАТ ДНА (bottom lock). Лагу НУЖНО эхо от дна. Пока дно в пределах
//    дальности — прибор «держит захват» и меряет. Ушли высоко над дном (или дна
//    нет) — эхо не возвращается, ЗАХВАТ ТЕРЯЕТСЯ, и прибор перестаёт обновлять
//    скорость: на экране висит ПОСЛЕДНЕЕ показание (устаревает), а не ноль и не
//    правда. Это фундаментальное ограничение доплеровского лага.
//
// 2. ОШИБКА СКОРОСТИ ЗВУКА (аналог калибровки плотности у глубины). Прибор
//    переводит сдвиг частоты в скорость, ДЕЛЯ на скорость звука, ЗАШИТУЮ в его
//    настройки. Если она не совпадает с фактической (c зависит от температуры,
//    солёности, давления) — скорость систематически врёт:
//
//        v_показание = v · (c_прибор / c_факт)
//
//    Настроил прибор на 1500, а звук в этой воде 1520 — все показания скорости
//    занижены на ~1.3%, СКОЛЬКО БЫ раз ни мерил. Ровно как завышение глубины из-за
//    неверной плотности — тот же тип «умной» ошибки, которую нельзя подделать шумом.
//
// Плюс обычные погрешности: смещение нуля, шум, квантование (АЦП), частота опроса.
//
// Величины для наглядного графика:
//   • speedTrue_mps — истина (движок),
//   • speed_mps     — показание лага (шум + масштаб от скорости звука; замирает
//                     при потере захвата дна).
// На графике видно, как при всплытии над дном показание «залипает», а истина
// продолжает меняться — вот оно, ограничение захвата дна.
//
// DefaultExecutionOrder(50): считается ПОСЛЕ RovSystemsSimulator. Без этого
// компонента симулятор оставляет speed_mps = истине (обратная совместимость).
// ВАЖНО: логика неподвижности миссии (InterventionTarget) читает speedTrue_mps —
// ей нужна ПРАВДА, а не показание, которое шумит и залипает без захвата дна.
//
// Настройка: повесить на объект НПА (там же, где RovSystemsSimulator).
// =============================================================================

using UnityEngine;

[DisallowMultipleComponent]
[DefaultExecutionOrder(50)]
public class RovSpeedSensor : MonoBehaviour
{
    [Header("Акустика (скорость звука)")]
    [Tooltip("Фактическая скорость звука в этой воде, м/с. Зависит от температуры/солёности/давления " +
             "(~1450–1540). Именно она создаёт истинный доплеровский сдвиг.")]
    public float СкоростьЗвукаФакт_мс = 1500f;
    [Tooltip("Скорость звука, ЗАШИТАЯ В ПРИБОР, м/с. По ней прибор переводит сдвиг частоты в скорость. " +
             "Не совпала с фактической — скорость систематически врёт (демо: 1500 при фактических 1520).")]
    public float СкоростьЗвукаВПриборе_мс = 1500f;

    [Header("Захват дна")]
    [Tooltip("Максимальная высота над дном для захвата, м. Выше — эхо не возвращается, захват теряется, " +
             "показание замирает на последнем значении.")]
    public float ДальностьЗахватаДна_м = 50f;
    [Tooltip("Есть ли сейчас захват дна (только чтение, для отладки/индикатора).")]
    public bool ЗахватДна { get; private set; }

    [Header("Погрешности прибора")]
    [Tooltip("Смещение нуля, м/с. Небольшой постоянный сдвиг измеренной скорости.")]
    public float СмещениеНуля_мс = 0.0f;
    [Tooltip("СКО шума скорости, м/с (дрожание показаний).")]
    public float ШумСКО_мс = 0.03f;
    [Tooltip("Разрешение АЦП по скорости, м/с: показание кратно этому шагу. 0 — без округления.")]
    public float Разрешение_мс = 0.01f;

    [Header("Опрос")]
    [Tooltip("Частота опроса датчика, Гц. Между опросами показание удерживается. 0 — каждый FixedUpdate.")]
    public float ЧастотаОпроса_Гц = 7f;

    private float _следующийОпрос_с;
    private float _показание_мс;   // держится между опросами и при потере захвата
    private bool  _иниц;

    void FixedUpdate()
    {
        float dt = Time.fixedDeltaTime;
        if (dt <= 0f) return;

        float vИстина = RovSystems.speedTrue_mps;

        if (!_иниц)
        {
            _показание_мс = vИстина;
            _иниц = true;
            RovSystems.speed_mps = _показание_мс;
            return;
        }

        // ЗАХВАТ ДНА: нужно отражение от дна И дно в пределах дальности захвата.
        ЗахватДна = RovSystems.hasBottomEcho && RovSystems.altitudeTrue_m <= ДальностьЗахватаДна_м;

        // Обновляем показание только при захвате и не чаще частоты опроса. Нет
        // захвата → НИЧЕГО не пишем: _показание_мс остаётся прежним (залипло).
        bool опрашиваем = ЧастотаОпроса_Гц <= 0f || Time.time >= _следующийОпрос_с;
        if (ЗахватДна && опрашиваем)
        {
            if (ЧастотаОпроса_Гц > 0f) _следующийОпрос_с = Time.time + 1f / ЧастотаОпроса_Гц;

            // 1. МАСШТАБ ОТ СКОРОСТИ ЗВУКА: прибор делит сдвиг частоты на СВОЮ c.
            //    v_показание = v · (c_прибор / c_факт).
            float cФакт = Mathf.Max(1f, СкоростьЗвукаФакт_мс);
            float масштаб = СкоростьЗвукаВПриборе_мс / cФакт;
            float v = vИстина * масштаб;

            // 2. Погрешности прибора: смещение нуля + шум. Скорость (модуль) ≥ 0.
            v += СмещениеНуля_мс + ГауссовШум() * ШумСКО_мс;
            v = Mathf.Max(0f, v);

            // 3. КВАНТОВАНИЕ (АЦП): округление до кратного разрешению.
            if (Разрешение_мс > 1e-6f)
                v = Mathf.Round(v / Разрешение_мс) * Разрешение_мс;

            _показание_мс = v;
        }

        // Публикуем ПОКАЗАНИЕ. Без захвата дна оно намеренно не обновляется —
        // «залипает» на последнем значении, как настоящий доплеровский лаг.
        RovSystems.speed_mps = _показание_мс;
    }

    static float ГауссовШум()
    {
        float u1 = Mathf.Max(1e-6f, Random.value);
        float u2 = Random.value;
        return Mathf.Sqrt(-2f * Mathf.Log(u1)) * Mathf.Cos(2f * Mathf.PI * u2);
    }
}
