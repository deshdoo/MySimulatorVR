// =============================================================================
// RovSpeedSensor.cs
// -----------------------------------------------------------------------------
// Датчик скорости НПА — ДОПЛЕРОВСКИЙ ЛАГ (DVL, Doppler Velocity Log),
// смоделированный как реальный акустический прибор, а не чтение модуля вектора
// скорости из движка.
//
// КАК ЭТО РАБОТАЕТ. Лаг светит вниз пучками ультразвука в дно и слушает эхо.
// Если аппарат движется, частота отражённого звука смещается — эффект Доплера
// (та же причина, по которой сирена приближающейся машины звучит выше). По
// величине смещения частоты вычисляют скорость ОТНОСИТЕЛЬНО ДНА:
//
//        Δf = 2 · f0 · v / c      =>      v = c · Δf / (2 · f0)
//
//   Δf — сдвиг частоты эха (Гц),  f0 — излучаемая частота,
//   v  — скорость относительно дна,  c — скорость звука в воде (~1500 м/с).
//   Двойка — потому что Доплер срабатывает ДВАЖДЫ: и когда звук уходит к дну,
//   и когда отражённый возвращается к движущемуся приёмнику.
//
// ДВА ГЛАВНЫХ «ХАРАКТЕРА» ЭТОГО ПРИБОРА (чего нет у датчика глубины):
//
// 1. ЗАХВАТ ДНА (bottom lock). Лагу НУЖНО эхо от дна. Пока дно в пределах
//    дальности — прибор «держит захват» и меряет. Ушли высоко над дном (или дна
//    нет) — эхо не возвращается, ЗАХВАТ ТЕРЯЕТСЯ, и прибор перестаёт обновлять
//    скорость: на экране висит ПОСЛЕДНЕЕ показание (устаревает), а не ноль и не
//    правда. Это фундаментальное ограничение доплеровского лага.
//
// 2. ОШИБКА СКОРОСТИ ЗВУКА (аналог калибровки плотности у глубины). Прибор
//    переводит сдвиг частоты в скорость, ДЕЛЯ на скорость звука, ЗАШИТУЮ в его
//    настройки. Если она не совпадает с фактической (c зависит от температуры,
//    солёности, давления) — скорость систематически врёт:
//
//        v_показание = v · (c_прибор / c_факт)
//
//    Настроил прибор на 1500, а звук в этой воде 1520 — все показания скорости
//    занижены на ~1.3%, СКОЛЬКО БЫ раз ни мерил. Ровно как завышение глубины из-за
//    неверной плотности — тот же тип «умной» ошибки, которую нельзя подделать шумом.
//
// Плюс обычные погрешности: смещение нуля, шум, квантование (АЦП), частота опроса.
//
// УСТРОЙСТВО (4 луча «Янус», как у реальных DVL — см. DvlJanus). Каждый опрос:
//   1. каждый луч ищет дно (рейкаст до ДальностьЗахватаДна_м / cos θ);
//   2. луч с эхом даёт РАДИАЛЬНУЮ скорость — проекцию скорости аппарата на луч
//      (это и есть то, что прибор получает из доплеровского сдвига), с масштабом
//      от скорости звука, смещением нуля, шумом и квантованием — у КАЖДОГО луча;
//   3. из ≥3 лучей МНК восстанавливает вектор скорости в осях аппарата
//      (вперёд/вбок/вверх) и «ошибку скорости» по лишнему лучу;
//   4. то же по эху от ВОДЫ на дальности ЯчейкаВоды_м («по воде», water track).
// Сам звук (миллион колебаний в секунду) не моделируется — модель выдаёт ровно
// то, что выдал бы прибор: проекции по лучам и решение, со всеми ошибками.
// Курс в градусах DVL сам не знает: он меряет в осях аппарата. В компасные
// направления его переводит курсоуказатель (RovHeadingSensor → heading_deg).
// Анимация F3 (DopplerInstrumentsVisualizer) рисует именно эти данные.
//
// Величины для наглядного графика:
//   • speedTrue_mps — истина (движок),
//   • speed_mps     — показание лага (шум + масштаб от скорости звука; замирает
//                     при потере захвата дна).
// На графике видно, как при всплытии над дном показание «залипает», а истина
// продолжает меняться — вот оно, ограничение захвата дна.
//
// DefaultExecutionOrder(50): считается ПОСЛЕ RovSystemsSimulator. Без этого
// компонента симулятор оставляет speed_mps = истине (обратная совместимость).
// ВАЖНО: логика неподвижности миссии (InterventionTarget) читает speedTrue_mps —
// ей нужна ПРАВДА, а не показание, которое шумит и залипает без захвата дна.
//
// Настройка: повесить на объект НПА (там же, где RovSystemsSimulator).
// =============================================================================

using UnityEngine;

[DisallowMultipleComponent]
[DefaultExecutionOrder(50)]
public class RovSpeedSensor : MonoBehaviour
{
    public static RovSpeedSensor Instance { get; private set; }

    [Header("Акустика (скорость звука)")]
    [Tooltip("Фактическая скорость звука в этой воде, м/с. Зависит от температуры/солёности/давления " +
             "(~1450–1540). Именно она создаёт истинный доплеровский сдвиг.")]
    public float СкоростьЗвукаФакт_мс = 1500f;
    [Tooltip("Скорость звука, ЗАШИТАЯ В ПРИБОР, м/с. По ней прибор переводит сдвиг частоты в скорость. " +
             "Не совпала с фактической — скорость систематически врёт (демо: 1500 при фактических 1520).")]
    public float СкоростьЗвукаВПриборе_мс = 1500f;
    [Tooltip("Частота излучения, Гц (A50: 1 МГц). Нужна для пересчёта в доплеровский сдвиг на панели.")]
    public float ЧастотаИзлучения_Гц = 1e6f;

    [Header("Лучи")]
    [Tooltip("Угол лучей от вертикали, град (Water Linked A50: 22.5, Teledyne: 30)")]
    public float УголЛуча = 22.5f;
    [Tooltip("Дальность ячейки воды для режима «по воде», м")]
    public float ЯчейкаВоды_м = 3f;

    [Header("Захват дна")]
    [Tooltip("Максимальная высота над дном для захвата, м. Выше — эхо не возвращается, захват теряется, " +
             "показание замирает на последнем значении.")]
    public float ДальностьЗахватаДна_м = 50f;
    [Tooltip("Есть ли сейчас захват дна (≥3 луча с эхом)")]
    public bool ЗахватДна { get; private set; }

    [Header("Погрешности прибора (на каждый луч)")]
    [Tooltip("Смещение нуля радиальной скорости луча, м/с.")]
    public float СмещениеНуля_мс = 0.0f;   // одинаковое у всех лучей → уходит в вертикальную скорость
    [Tooltip("СКО шума радиальной скорости одного луча за опрос, м/с. Горизонтальная скорость из лучей шумит ~в 1/(√2·sin θ) ≈ 1.8 раза сильнее (A50: единицы мм/с).")]
    public float ШумЛучаСКО_мс = 0.005f;
    [Tooltip("Разрешение АЦП по скорости, м/с: радиальная скорость кратна этому шагу. 0 — без округления.")]
    public float РазрешениеЛуча_мс = 0.001f;

    [Header("Усреднение (ансамбль)")]
    [Tooltip("Реальные DVL усредняют несколько пингов («ансамбль») — иначе цифры скачут. " +
             "Время усреднения скорости, с. 0 — без усреднения (сырые пинги).")]
    public float УсреднениеСкорости_с = 1f;
    [Tooltip("Время усреднения течения, с. Течение меняется медленно, а измеряется как РАЗНОСТЬ " +
             "двух шумных скоростей — поэтому усредняем дольше.")]
    public float УсреднениеТечения_с = 3f;
    [Tooltip("Ниже этой скорости течения направление не определяется: шум сравним с самим " +
             "течением, и курс слабого течения прыгает на все 360°. м/с")]
    public float ПорогТечения_мс = 0.03f;

    [Header("Опрос")]
    [Tooltip("Постоянная частота опроса, Гц — только если АдаптивнаяЧастота выключена. 0 — каждый FixedUpdate.")]
    public float ЧастотаОпроса_Гц = 7f;

    [Tooltip("Частота зависит от высоты над дном, как у реального DVL (Water Linked A50: 2–15 Гц). " +
             "Чем дальше дно, тем дольше прибор слушает и накапливает эхо на каждое измерение: " +
             "f = K / h, где K подобрано так, что на пределе дальности f = МинЧастота. " +
             "Выключено — постоянная ЧастотаОпроса_Гц.")]
    public bool АдаптивнаяЧастота = true;
    public float МаксЧастота_Гц = 15f;
    public float МинЧастота_Гц = 2f;

    /// <summary>Фактическая частота измерений сейчас, Гц.</summary>
    public float ТекущаяЧастота_Гц
    {
        get
        {
            if (!АдаптивнаяЧастота) return ЧастотаОпроса_Гц;
            // Без захвата дна прибор «ищет» дно на полной дальности — самый медленный режим.
            float h = ЗахватДна ? Mathf.Max(0.1f, Высота_м) : ДальностьЗахватаДна_м;
            float K = МинЧастота_Гц * ДальностьЗахватаДна_м;   // f(предел) = МинЧастота
            return Mathf.Clamp(K / h, МинЧастота_Гц, МаксЧастота_Гц);
        }
    }
    private float _прошлоеИзмерение_с = -1f;

    // ---- Результаты последнего опроса (читают анимация F3, панели, в будущем автопилот) ----
    public int НомерИзмерения { get; private set; }
    public float ВремяИзмерения { get; private set; }
    public readonly float[] Дальность_м = new float[4];      // вдоль луча до дна (или предел)
    public readonly bool[]  ЭхоОтДна = new bool[4];
    public readonly float[] РадиальнаяДно = new float[4];     // м/с, + = луч сближается с дном
    public readonly float[] РадиальнаяВода = new float[4];    // м/с, относительно воды в ячейке
    public Vector3 СкоростьНадДном { get; private set; }      // м/с, оси аппарата (x вправо, y вверх, z вперёд)
    public Vector3 СкоростьВВоде   { get; private set; }      // м/с, оси аппарата
    // Усреднённые (по ансамблю пингов) — их показывают пульт и анимация F3.
    public Vector3 СкоростьНадДномСредн { get; private set; } // м/с, оси аппарата
    public Vector3 СкоростьВВодеСредн   { get; private set; } // м/с, оси аппарата
    // Течение в ЗЕМНЫХ осях (x — восток, z — север): переведено по ПОКАЗАНИЮ
    // курсоуказателя (так делает реальный DVL со своим компасом). Усредняется в
    // земных осях — иначе при повороте аппарата среднее «размазывалось» бы.
    public Vector3 ТечениеЗемля { get; private set; }
    public bool ТечениеНадёжно => new Vector2(ТечениеЗемля.x, ТечениеЗемля.z).magnitude >= ПорогТечения_мс;
    public float КурсТечения => DvlJanus.Курс(ТечениеЗемля);
    private bool _средИниц;
    public float ОшибкаСкорости { get; private set; }         // м/с, невязка по лишнему лучу
    public bool  ЕстьВода { get; private set; }
    public float Высота_м { get; private set; }               // по лучам: R·cos θ, среднее

    private float _следующийОпрос_с;
    private float _показание_мс;   // модуль скорости для монитора; держится между опросами и при потере захвата
    private bool  _иниц;
    private Rigidbody _rb;
    private RovController _rov;

    void Awake()
    {
        Instance = this;
        _rb = GetComponentInParent<Rigidbody>();
        _rov = GetComponentInParent<RovController>();
    }

    void OnDestroy() { if (Instance == this) Instance = null; }

    void FixedUpdate()
    {
        if (Time.fixedDeltaTime <= 0f || _rb == null) return;

        if (!_иниц)
        {
            _показание_мс = RovSystems.speedTrue_mps;
            _иниц = true;
            RovSystems.speed_mps = _показание_мс;
            return;
        }

        float f = ТекущаяЧастота_Гц;
        bool опрашиваем = f <= 0f || Time.time >= _следующийОпрос_с;
        if (опрашиваем)
        {
            if (f > 0f) _следующийОпрос_с = Time.time + 1f / f;
            Измерить();
        }

        // Публикуем ПОКАЗАНИЕ. Без захвата дна оно намеренно не обновляется —
        // «залипает» на последнем значении, как настоящий доплеровский лаг.
        RovSystems.speed_mps = _показание_мс;
    }

    void Измерить()
    {
        НомерИзмерения++;
        ВремяИзмерения = Time.time;
        Vector3 o = transform.position;
        Vector3 vАппарата = _rb.linearVelocity;
        float cosθ = Mathf.Cos(УголЛуча * Mathf.Deg2Rad);
        // Прибор делит сдвиг частоты на СВОЮ скорость звука: v_показание = v · (c_прибор / c_факт).
        float масштаб = СкоростьЗвукаВПриборе_мс / Mathf.Max(1f, СкоростьЗвукаФакт_мс);

        // 1–2. Лучи «по дну».
        int сЭхом = 0; float высота = 0f;
        for (int i = 0; i < 4; i++)
        {
            Vector3 d = transform.TransformDirection(DvlJanus.Луч(i, УголЛуча, true));
            ЭхоОтДна[i] = DvlJanus.ЛучДоДна(transform, _rb, o, d, ДальностьЗахватаДна_м / cosθ, out float R);
            Дальность_м[i] = R;
            if (!ЭхоОтДна[i]) continue;
            сЭхом++; высота += R * cosθ;
            РадиальнаяДно[i] = ПогрешностиЛуча(Vector3.Dot(vАппарата, d) * масштаб);
        }
        Высота_м = сЭхом > 0 ? высота / сЭхом : ДальностьЗахватаДна_м;

        // 3. Решение «по дну». Меньше 3 лучей — захвата нет, показание залипает.
        ЗахватДна = DvlJanus.Решить(РадиальнаяДно, ЭхоОтДна, УголЛуча, true, out Vector3 vДно, out float ош);
        if (ЗахватДна)
        {
            СкоростьНадДном = vДно;
            ОшибкаСкорости = ош;
            float αС = Доля(УсреднениеСкорости_с);
            СкоростьНадДномСредн = _средИниц ? Vector3.Lerp(СкоростьНадДномСредн, vДно, αС) : vДно;
            _показание_мс = СкоростьНадДномСредн.magnitude;
        }

        // 4. «По воде»: эхо от взвеси в ячейке на ЯчейкаВоды_м — она плывёт с водой.
        var все = new[] { true, true, true, true };
        for (int i = 0; i < 4; i++)
        {
            Vector3 d = transform.TransformDirection(DvlJanus.Луч(i, УголЛуча, true));
            Vector3 p = o + d * ЯчейкаВоды_м;
            Vector3 vВоды = _rov != null && _rov.Течение != null ? _rov.Течение.Скорость(p) : Vector3.zero;
            РадиальнаяВода[i] = ПогрешностиЛуча(Vector3.Dot(vАппарата - vВоды, d) * масштаб);
        }
        ЕстьВода = DvlJanus.Решить(РадиальнаяВода, все, УголЛуча, true, out Vector3 vВода, out _);
        if (ЕстьВода)
        {
            СкоростьВВоде = vВода;
            СкоростьВВодеСредн = _средИниц ? Vector3.Lerp(СкоростьВВодеСредн, vВода, Доля(УсреднениеСкорости_с)) : vВода;
        }

        // 5. Течение = над дном − в воде, в земных осях по курсоуказателю, с долгим усреднением.
        if (ЗахватДна && ЕстьВода)
        {
            Vector3 лок = СкоростьНадДном - СкоростьВВоде;
            Vector3 земля = Quaternion.Euler(0f, RovSystems.heading_deg, 0f) * new Vector3(лок.x, 0f, лок.z);
            ТечениеЗемля = _средИниц ? Vector3.Lerp(ТечениеЗемля, земля, Доля(УсреднениеТечения_с)) : земля;
        }
        _средИниц = true;
        _прошлоеИзмерение_с = Time.time;
    }

    // Доля нового пинга в экспоненциальном среднем: α = 1 − e^(−Δt/τ), Δt — период опроса.
    float Доля(float τ)
    {
        if (τ <= 1e-3f) return 1f;
        // Фактический интервал с прошлого измерения: частота теперь плавает с высотой.
        float Δt = _прошлоеИзмерение_с >= 0f ? Mathf.Max(Time.fixedDeltaTime, Time.time - _прошлоеИзмерение_с) : Time.fixedDeltaTime;
        return 1f - Mathf.Exp(-Δt / τ);
    }

    // Погрешности одного луча: смещение нуля + шум + квантование АЦП.
    float ПогрешностиЛуча(float b)
    {
        b += СмещениеНуля_мс + DvlJanus.Гаусс() * ШумЛучаСКО_мс;
        if (РазрешениеЛуча_мс > 1e-6f) b = Mathf.Round(b / РазрешениеЛуча_мс) * РазрешениеЛуча_мс;
        return b;
    }

    /// <summary>Доплеровский сдвиг частоты эха луча, Гц: Δf = 2·f₀·v/c.</summary>
    public float СдвигЧастоты_Гц(float радиальная) => 2f * ЧастотаИзлучения_Гц * радиальная / Mathf.Max(1f, СкоростьЗвукаВПриборе_мс);
}
