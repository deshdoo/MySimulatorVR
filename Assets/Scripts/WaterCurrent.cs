// =============================================================================
// WaterCurrent.cs
// -----------------------------------------------------------------------------
// Модель морского течения в районе работ.
//
// Это НЕ компонент: настройки живут прямо в RovController (поле «Течение»),
// потому что течение нужно ровно в одном месте — при расчёте сопротивления
// воды. Отдельный объект в сцене создавать не надо.
//
// Течение НЕ прикладывает к аппарату силу напрямую. Оно задаёт скорость самой
// воды, а сила возникает сама — сопротивление считается от ОТНОСИТЕЛЬНОЙ
// скорости v_отн = v_аппарата − v_воды:
//
//     F = −½·ρ·Cx·A·v_отн·|v_отн|
//
// Так получается физически верное поведение, которого не даёт «толчок силой»:
//   - неподвижный в мировых координатах аппарат сносит потоком;
//   - идущий ПО течению почти не встречает сопротивления (v_отн → 0);
//   - идущий ПРОТИВ течения теряет скорость сильнее квадратично;
//   - на удержании автопилот вынужден постоянно парировать снос — аппарат
//     чуть «дышит» около точки, как настоящий ROV в потоке.
//
// Течение — это ПОЛЕ скоростей v(x, t), а не одна скорость «для аппарата»: в
// каждой точке вода движется по-своему. Его же читает взвесь в воде
// (CurrentParticleAdvector), поэтому оператор ВИДИТ течение — как реальный пилот
// ROV оценивает поток по дрейфу частиц в луче прожектора.
//
// Учтены свойства реального течения:
//   0. СЛОИ ПО ГЛУБИНЕ. Толща воды стратифицирована: у поверхности — ветровой
//      (дрейфовый) поток, под слоем скачка плотности (термоклин/пикноклин) —
//      своё, обычно слабое и другого направления течение, у дна — приливное.
//      Между слоями — сдвиг скорости (плавный переход ПереходМеждуСлоями_м).
//      Так устроено и измерение: профилограф течений ADCP меряет поток ячейками
//      по глубине — ровно такими слоями.
//   1. ПУЛЬСАЦИИ. Поток не стационарен: скорость и направление медленно гуляют
//      (шум Перлина — гладкий, без рывков).
//   2. ВИХРИ (мезомасштабная турбулентность). В потоке живут отдельные вихри
//      Лэмба—Озеена конечной длины, которые ПЕРЕНОСЯТСЯ средним потоком («замороженная
//      турбулентность», гипотеза Тейлора): вихрь рождается выше по течению, проплывает
//      мимо аппарата и затухает. Аппарат не трясёт «сам по себе» — его толкает вода,
//      когда через него проходит вихрь, и соседние точки (нос/корма, взвесь рядом)
//      получают разную скорость. Профиль окружной скорости вихря Лэмба—Озеена:
//          v_θ(r) = Γ/(2πr) · (1 − e^(−r²/R²))
//      — твёрдое вращение в ядре (r ≪ R) и затухание 1/r снаружи, без особенности
//      в центре. Ось вихря случайна: вертикальная ось закручивает поток в плане
//      (снос вбок), горизонтальная — даёт восходящие/нисходящие струи (качка по глубине).
//   3. ПРИДОННЫЙ ПОГРАНИЧНЫЙ СЛОЙ. У дна вода тормозится трением, скорость
//      падает по степенному закону 1/7 — стандартная аппроксимация профиля
//      турбулентного пограничного слоя.
//
// Типичные значения для акватории: 0.1-0.3 м/с (0.2-0.6 узла) — спокойно;
// 0.5 м/с — заметно мешает работе; свыше 1 м/с малый ROV уже не удерживается.
// =============================================================================

