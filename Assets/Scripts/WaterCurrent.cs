// =============================================================================
// WaterCurrent.cs
// -----------------------------------------------------------------------------
// Модель морского течения в районе работ.
//
// Это НЕ компонент: настройки живут прямо в RovController (поле «Течение»),
// потому что течение нужно ровно в одном месте — при расчёте сопротивления
// воды. Отдельный объект в сцене создавать не надо.
//
// Течение НЕ прикладывает к аппарату силу напрямую. Оно задаёт скорость самой
// воды, а сила возникает сама — сопротивление считается от ОТНОСИТЕЛЬНОЙ
// скорости v_отн = v_аппарата − v_воды:
//
//     F = −½·ρ·Cx·A·v_отн·|v_отн|
//
// Так получается физически верное поведение, которого не даёт «толчок силой»:
//   - неподвижный в мировых координатах аппарат сносит потоком;
//   - идущий ПО течению почти не встречает сопротивления (v_отн → 0);
//   - идущий ПРОТИВ течения теряет скорость сильнее квадратично;
//   - на удержании автопилот вынужден постоянно парировать снос — аппарат
//     чуть «дышит» около точки, как настоящий ROV в потоке.
//
// Учтено три свойства реального течения:
//   1. ПУЛЬСАЦИИ. Поток не стационарен: скорость и направление медленно гуляют
//      (шум Перлина — гладкий, без рывков).
//   2. МЕЛКОМАСШТАБНАЯ ТУРБУЛЕНТНОСТЬ (вихри). Помимо медленного гуляния среднего
//      потока вода несёт мелкие быстрые вихри, которые непрерывно толкают аппарат
//      по всем трём осям. Именно они не дают ROV висеть идеально неподвижно даже
//      на удержании — он всё время чуть «дышит»/покачивается, как в реальной воде.
//   3. ПРИДОННЫЙ ПОГРАНИЧНЫЙ СЛОЙ. У дна вода тормозится трением, скорость
//      падает по степенному закону 1/7 — стандартная аппроксимация профиля
//      турбулентного пограничного слоя.
//
// Типичные значения для акватории: 0.1-0.3 м/с (0.2-0.6 узла) — спокойно;
// 0.5 м/с — заметно мешает работе; свыше 1 м/с малый ROV уже не удерживается.
// =============================================================================

using UnityEngine;

[System.Serializable]
public class WaterCurrent
{
    [Tooltip("Выключи, чтобы вода была неподвижной")]
    public bool включено = true;

    [Header("Основной поток")]
    [Tooltip("Средняя скорость течения, м/с. 0.1-0.3 — спокойно, 0.5 — мешает работе, >1 — малый ROV не удержится.")]
    public float СредняяСкорость = 0.25f;
    [Tooltip("Направление, КУДА течёт, град по компасу (0 = на север/+Z, 90 = на восток/+X)")]
    public float НаправлениеГрад = 45f;
    [Tooltip("Вертикальная составляющая, м/с. Обычно мала; положительная — восходящий поток. " +
             "Ненулевая заставляет работать интегральное звено ПИДа удержания глубины.")]
    public float ВертикальнаяСкорость = 0f;

    [Header("Пульсации потока")]
    [Tooltip("Насколько гуляет скорость, доля от средней. 0 — идеально стационарный поток (нереалистично).")]
    [Range(0f, 1f)] public float АмплитудаПульсаций = 0.35f;
    [Tooltip("Насколько гуляет направление, град")]
    public float РазбросНаправления = 20f;
    [Tooltip("Характерное время пульсаций, с. Больше = медленнее и плавнее.")]
    public float ПериодПульсаций = 18f;

    [Header("Мелкомасштабная турбулентность (вихри)")]
    [Tooltip("Амплитуда быстрых вихрей поверх среднего потока, м/с. Это то, что не даёт " +
             "аппарату висеть идеально неподвижно на удержании — он всё время чуть " +
             "покачивается. 0 — вихрей нет (вода как «кисель», на автопилоте замирает). " +
             "0.04-0.08 — живое, но спокойное покачивание.")]
    public float АмплитудаТурбулентности = 0.06f;
    [Tooltip("Характерное время вихрей, с. Меньше = мельче и быстрее дрожание; больше = " +
             "ленивое покачивание. Держи заметно короче ПериодаПульсаций.")]
    public float ПериодТурбулентности = 2.5f;
    [Range(0f, 1f)]
    [Tooltip("Доля вертикальной составляющей вихрей от горизонтальной. В придонном потоке " +
             "вертикальные пульсации мельче горизонтальных, поэтому <1. Именно она даёт " +
             "лёгкое покачивание по глубине (иначе ПИД глубины держал бы Y мёртво).")]
    public float ВертикальностьТурбулентности = 0.5f;

    [Header("Придонный пограничный слой")]
    [Tooltip("У дна вода тормозится трением. Выключи, чтобы течение было однородным по глубине.")]
    public bool ОслаблениеУДна = true;
    [Tooltip("Толщина пограничного слоя, м: выше неё течение считается невозмущённым")]
    public float ТолщинаПридонногоСлоя = 6f;

    private float _seed = -1f;

    /// <summary>
    /// Скорость воды в мировых координатах в заданной точке, м/с.
    /// </summary>
    public Vector3 Скорость(Vector3 точка)
    {
        if (!включено) return Vector3.zero;

        // Сид разный от запуска к запуску, чтобы пульсации не повторялись.
        if (_seed < 0f) _seed = Random.value * 100f;

        float t = Time.time / Mathf.Max(0.1f, ПериодПульсаций);

        // Шум Перлина даёт гладкое блуждание без скачков; сдвиг по второй
        // координате делает пульсации скорости и направления независимыми.
        float шумСкорости = Mathf.PerlinNoise(t, _seed) * 2f - 1f;
        float шумНаправления = Mathf.PerlinNoise(t, _seed + 37f) * 2f - 1f;

        float скорость = Mathf.Max(0f, СредняяСкорость * (1f + АмплитудаПульсаций * шумСкорости));

        float курс = (НаправлениеГрад + РазбросНаправления * шумНаправления) * Mathf.Deg2Rad;
        Vector3 напр = new Vector3(Mathf.Sin(курс), 0f, Mathf.Cos(курс));

        Vector3 v = напр * скорость + Vector3.up * ВертикальнаяСкорость;

        if (ОслаблениеУДна && ТолщинаПридонногоСлоя > 0.01f)
            v *= ПрофильУДна();

        // Вихри добавляем ПОВЕРХ среднего потока (после ослабления у дна): это
        // отдельный, всегда присутствующий мелкомасштабный процесс. Именно он даёт
        // «покачивание» на удержании — быстрое возмущение, которое автопилот не
        // успевает погасить полностью.
        v += ВихревоеВозмущение();

        return v;
    }

    /// <summary>
    /// Мелкомасштабная турбулентность: вектор гладко блуждающей скорости из трёх
    /// независимых каналов шума Перлина. Быстрее и мельче основных пульсаций.
    /// Вертикальная составляющая приглушена (ВертикальностьТурбулентности).
    /// </summary>
    Vector3 ВихревоеВозмущение()
    {
        if (АмплитудаТурбулентности <= 0f) return Vector3.zero;

        float tt = Time.time / Mathf.Max(0.05f, ПериодТурбулентности);

        // Три разных сдвига сида -> три независимых (декоррелированных) канала.
        // PerlinNoise даёт [0..1], центрируем в [-1..1].
        float ex = Mathf.PerlinNoise(tt, _seed + 11f) * 2f - 1f;
        float ey = Mathf.PerlinNoise(tt, _seed + 53f) * 2f - 1f;
        float ez = Mathf.PerlinNoise(tt, _seed + 91f) * 2f - 1f;

        return new Vector3(ex, ey * ВертикальностьТурбулентности, ez) * АмплитудаТурбулентности;
    }

    /// <summary>
    /// Множитель скорости в пограничном слое: степенной закон 1/7 —
    /// стандартная аппроксимация профиля турбулентного потока у стенки.
    /// У самого дна ~0, на границе слоя — 1.
    /// </summary>
    float ПрофильУДна()
    {
        if (!RovSystems.hasBottomEcho) return 1f;   // дна не видно — поток невозмущённый

        float отн = Mathf.Clamp01(RovSystems.altitudeAboveBottom_m / ТолщинаПридонногоСлоя);
        return Mathf.Pow(отн, 1f / 7f);
    }
}
