             "лёгкое покачивание по глубине (иначе ПИД глубины держал бы Y мёртво).")]
    public float ВертикальностьТурбулентности = 0.5f;

    [Header("Придонный пограничный слой")]
    [Tooltip("У дна вода тормозится трением. Выключи, чтобы течение было однородным по глубине.")]
    public bool ОслаблениеУДна = true;
    [Tooltip("Толщина пограничного слоя, м: выше неё течение считается невозмущённым")]
    public float ТолщинаПридонногоСлоя = 6f;

    private float _seed = -1f;

    struct Вихрь
    {
        public Vector3 центр, ось;
        public float R, vМакс, возраст, жизнь;
    }
    private Вихрь[] _вихри;
    private float _дноY; private bool _естьДно;
    private Vector3 _центрОбласти;

    // max_r [(R/r)(1 − e^(−r²/R²))] = 0.6382 при r ≈ 1.1209R — нормировка, чтобы
    // СилаВихря была именно максимальной окружной скоростью.
    const float НормаЛО = 0.6382f;

    /// <summary>
    /// Шаг жизни вихрей: перенос средним потоком, старение, замена затухших и
    /// ушедших из области. Вызывается раз в FixedUpdate (RovController).
    /// центр — точка, вокруг которой держим область (аппарат).
    /// </summary>
    public void ОбновитьВихри(Vector3 центр, float dt)
    {
        _естьДно = RovSystems.hasBottomEcho;
        if (_естьДно) _дноY = центр.y - RovSystems.altitudeTrue_m;
        if (!включено || Турбулентность != ВидТурбулентности.ВихриВПотоке) return;
        if (_seed < 0f) _seed = Random.value * 100f;
        _центрОбласти = центр;
        int n = Mathf.Max(0, ЧислоВихрей);
        if (_вихри == null || _вихри.Length != n)
        {
            _вихри = new Вихрь[n];
            for (int i = 0; i < n; i++) _вихри[i] = НовыйВихрь(true);
        }
        float пол = РазмерОбластиВихрей * 0.5f;
        for (int i = 0; i < n; i++)
        {
            ref Вихрь w = ref _вихри[i];
            // Вихрь «вморожен» в поток: центр плывёт со средней скоростью воды.
            w.центр += СреднийПоток(w.центр) * dt;
            w.возраст += dt;
            Vector3 d = w.центр - центр;
            bool вышел = Mathf.Abs(d.x) > пол || Mathf.Abs(d.y) > пол || Mathf.Abs(d.z) > пол;
            if (w.возраст >= w.жизнь || вышел) w = НовыйВихрь(false);
        }
    }

    Вихрь НовыйВихрь(bool вСлучайнойТочке)
    {
        float пол = РазмерОбластиВихрей * 0.5f;
        Vector3 случ = new Vector3(Random.Range(-пол, пол), Random.Range(-пол, пол), Random.Range(-пол, пол));
        Vector3 поток = СреднийПоток(_центрОбласти); поток.y = 0f;
        Vector3 pos = _центрОбласти + случ;
        // Новые вихри рождаются выше по течению — и приплывают к аппарату с потоком.
        // При старте область заполняем целиком, иначе первые полминуты вода без вихрей.
        if (!вСлучайнойТочке && поток.sqrMagnitude > 1e-4f)
        {
            Vector3 u = поток.normalized;
            pos = _центрОбласти + (случ - u * Vector3.Dot(случ, u)) - u * пол * 0.95f;
        }
        Vector3 ось;
        if (Random.value < ДоляГоризонтальныхОсей)
        {
            float a = Random.value * Mathf.PI * 2f;
            ось = new Vector3(Mathf.Cos(a), Random.Range(-0.2f, 0.2f), Mathf.Sin(a)).normalized;
        }
        else ось = new Vector3(Random.Range(-0.3f, 0.3f), 1f, Random.Range(-0.3f, 0.3f)).normalized;
        if (Random.value < 0.5f) ось = -ось;   // направление закрутки
        float жизнь = Random.Range(ЖизньВихря.x, ЖизньВихря.y);
        return new Вихрь
        {
            центр = pos, ось = ось,
            R = Random.Range(РадиусВихря.x, РадиусВихря.y),
            vМакс = Random.Range(СилаВихря.x, СилаВихря.y),
            жизнь = жизнь,
            возраст = вСлучайнойТочке ? Random.value * жизнь : 0f,
        };
    }

    // Суммарная скорость от всех вихрей в точке, м/с.
    Vector3 СкоростьВихрей(Vector3 p)
    {
        if (_вихри == null) return Vector3.zero;
        Vector3 v = Vector3.zero;
        for (int i = 0; i < _вихри.Length; i++)
        {
            Вихрь w = _вихри[i];
            Vector3 d = p - w.центр;
            float осевое = Vector3.Dot(d, w.ось);
            Vector3 rВек = d - w.ось * осевое;
            float r = rВек.magnitude;
            if (r < 1e-4f) continue;
            float x = r / w.R;
            if (x > 6f) continue;   // дальше 6R вклад < 3% — не считаем
            // Лэмб—Озеен, нормированный на максимум окружной скорости.
            float профиль = (1f - Mathf.Exp(-x * x)) / x / НормаЛО;
            // Вихрь конечной длины (~±2R вдоль оси) и плавное рождение/затухание.
            float вдольОси = Mathf.Exp(-(осевое * осевое) / (4f * w.R * w.R));
            float огибающая = Mathf.Sin(Mathf.PI * Mathf.Clamp01(w.возраст / w.жизнь));
            v += Vector3.Cross(w.ось, rВек / r) * (w.vМакс * профиль * вдольОси * огибающая);
        }
        return v;
    }

    /// <summary>
    /// Скорость воды в мировых координатах в заданной точке, м/с.
    /// </summary>
    public Vector3 Скорость(Vector3 точка)
    {
        if (!включено) return Vector3.zero;
        Vector3 v = СреднийПоток(точка);
        // Турбулентность — ПОВЕРХ среднего потока: отдельный, всегда присутствующий
        // процесс. Именно она даёт «покачивание» на удержании — возмущение, которое
        // автопилот не успевает погасить полностью.
        v += Турбулентность == ВидТурбулентности.ВихриВПотоке
            ? СкоростьВихрей(точка) * ПрофильУДна(точка) * Множитель
            : ВихревоеВозмущение() * Множитель;
        return v;
    }

    /// <summary>
    /// Средний (крупномасштабный) поток без вихрей, м/с: пульсации + придонный слой.
    /// Им же переносятся сами вихри.
    /// </summary>
    public Vector3 СреднийПоток(Vector3 точка)
    {
        if (!включено) return Vector3.zero;

        // Сид разный от запуска к запуску, чтобы пульсации не повторялись.
        if (_seed < 0f) _seed = Random.value * 100f;

        float t = Time.time / Mathf.Max(0.1f, ПериодПульсаций);

        if (ИспользоватьСлои && Слои != null && Слои.Count > 0)
        {
            float глубина = RovSystems.уровеньПоверхности_Y - точка.y;
            Vector3 сумма = Vector3.zero; float весВсего = 0f;
            for (int i = 0; i < Слои.Count; i++)
            {
                float w = ВесСлоя(i, глубина);
                if (w <= 1e-4f) continue;
                сумма += ПотокСлоя(Слои[i].Скорость, Слои[i].НаправлениеГрад, t, _seed + 13f * i) * w;
                весВсего += w;
            }
            Vector3 vСлоёв = весВсего > 1e-4f ? сумма / весВсего : Vector3.zero;
            return (vСлоёв + Vector3.up * ВертикальнаяСкорость) * ПрофильУДна(точка) * Множитель;
        }

        // Шум Перлина даёт гладкое блуждание без скачков; сдвиг по второй
        // координате делает пульсации скорости и направления независимыми.
        float шумСкорости = Mathf.PerlinNoise(t, _seed) * 2f - 1f;
        float шумНаправления = Mathf.PerlinNoise(t, _seed + 37f) * 2f - 1f;

        float скорость = Mathf.Max(0f, СредняяСкорость * (1f + АмплитудаПульсаций * шумСкорости));

        float курс = (НаправлениеГрад + РазбросНаправления * шумНаправления) * Mathf.Deg2Rad;
        Vector3 напр = new Vector3(Mathf.Sin(курс), 0f, Mathf.Cos(курс));

        Vector3 v = напр * скорость + Vector3.up * ВертикальнаяСкорость;

        return v * ПрофильУДна(точка) * Множитель;
    }

    // Средний поток одного слоя с собственными (независимыми) пульсациями.
    Vector3 ПотокСлоя(float скоростьСредняя, float направлениеГрад, float t, float сид)
    {
        float шС = Mathf.PerlinNoise(t, сид) * 2f - 1f;
        float шН = Mathf.PerlinNoise(t, сид + 37f) * 2f - 1f;
        float скорость = Mathf.Max(0f, скоростьСредняя * (1f + АмплитудаПульсаций * шС));
        float курс = (направлениеГрад + РазбросНаправления * шН) * Mathf.Deg2Rad;
        return new Vector3(Mathf.Sin(курс), 0f, Mathf.Cos(курс)) * скорость;
    }

    // «Принадлежность» глубины слою с плавными краями (smoothstep шириной перехода).
    // Верхняя граница первого и нижняя последнего слоя — открытые.
    float ВесСлоя(int i, float глубина)
    {
        var с = Слои[i];
        float h = Mathf.Max(0.01f, ПереходМеждуСлоями_м * 0.5f);
        float низВерх = i == 0 ? 1f : Mathf.SmoothStep(0f, 1f, Mathf.InverseLerp(с.Верх_м - h, с.Верх_м + h, глубина));
        float верхНиз = i == Слои.Count - 1 ? 1f : 1f - Mathf.SmoothStep(0f, 1f, Mathf.InverseLerp(с.Низ_м - h, с.Низ_м + h, глубина));
        return низВерх * верхНиз;
    }

    /// <summary>Слой, в котором лежит точка (для подписей/цвета визуализации), или null.</summary>
    public СлойТечения СлойВТочке(Vector3 точка)
    {
        if (!ИспользоватьСлои || Слои == null) return null;
        float глубина = RovSystems.уровеньПоверхности_Y - точка.y;
        for (int i = 0; i < Слои.Count; i++)
            if (глубина < Слои[i].Низ_м || i == Слои.Count - 1) return Слои[i];
        return null;
    }

    /// <summary>
    /// Мелкомасштабная турбулентность: вектор гладко блуждающей скорости из трёх
    /// независимых каналов шума Перлина. Быстрее и мельче основных пульсаций.
    /// Вертикальная составляющая приглушена (ВертикальностьТурбулентности).
    /// </summary>
    Vector3 ВихревоеВозмущение()
    {
        if (АмплитудаТурбулентности <= 0f) return Vector3.zero;

        float tt = Time.time / Mathf.Max(0.05f, ПериодТурбулентности);

        // Три разных сдвига сида -> три независимых (декоррелированных) канала.
        // PerlinNoise даёт [0..1], центрируем в [-1..1].
        float ex = Mathf.PerlinNoise(tt, _seed + 11f) * 2f - 1f;
        float ey = Mathf.PerlinNoise(tt, _seed + 53f) * 2f - 1f;
        float ez = Mathf.PerlinNoise(tt, _seed + 91f) * 2f - 1f;

        return new Vector3(ex, ey * ВертикальностьТурбулентности, ez) * АмплитудаТурбулентности;
    }

    /// <summary>
    /// Множитель скорости в пограничном слое: степенной закон 1/7 —
    /// стандартная аппроксимация профиля турбулентного потока у стенки.
    /// У самого дна ~0, на границе слоя — 1.
    /// </summary>
    float ПрофильУДна(Vector3 точка)
    {
        if (!ОслаблениеУДна || ТолщинаПридонногоСлоя <= 0.01f) return 1f;
        if (!_естьДно) return 1f;   // дна не видно — поток невозмущённый

        // Пограничный слой — это физика потока, ей нужна ИСТИННАЯ высота над дном,
        // а не показание эхолота (оно шумит и врёт на ошибке скорости звука).
        // Высота считается для самой точки: дно под аппаратом принимаем локально
        // ровным (Y дна = Y аппарата − истинная высота над дном).
        float отн = Mathf.Clamp01((точка.y - _дноY) / ТолщинаПридонногоСлоя);
        return Mathf.Pow(отн, 1f / 7f);
    }
