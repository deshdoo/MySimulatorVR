    [Tooltip("ВихриВПотоке — вихри Лэмба—Озеена, переносимые течением (поле в пространстве). " +
             "ШумВоВремени — старая модель: однородное дрожание скорости по всей воде.")]
    public ВидТурбулентности Турбулентность = ВидТурбулентности.ВихриВПотоке;
    [Tooltip("Сколько вихрей одновременно живёт в области вокруг аппарата")]
    public int ЧислоВихрей = 10;
    [Tooltip("Размер области вокруг аппарата, где живут вихри, м (сторона куба)")]
    public float РазмерОбластиВихрей = 30f;
    [Tooltip("Радиус ядра вихря R, м: мин/макс")]
    public Vector2 РадиусВихря = new Vector2(1.5f, 4f);
    [Tooltip("Максимальная окружная скорость вихря, м/с: мин/макс")]
    public Vector2 СилаВихря = new Vector2(0.04f, 0.12f);
