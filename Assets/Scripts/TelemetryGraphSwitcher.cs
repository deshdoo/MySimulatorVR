// =============================================================================
// TelemetryGraphSwitcher.cs
// -----------------------------------------------------------------------------
// Переключатель страниц одного графика телеметрии.
//
// Почему страницы, а не несколько панелей: держать 5-6 отдельных TelemetryGraph
// и включать по одному — это 5-6 объектов в сцене, каждый со своим списком серий
// и своими настройками масштаба. Страница описывает то же самое одной строкой в
// инспекторе, а панель остаётся одна.
//
// Переключение вешается на физическую кнопку пульта: у RovPokeButton есть
// UnityEvent onPressed — выбери там TelemetryGraphSwitcher.Следующая().
// Для теста в редакторе без VR есть клавиша (по умолчанию G).
//
// Набор страниц по умолчанию заполняется при добавлении компонента (Reset) —
// ненужные удаляй, свои добавляй кнопкой «+».
//
// Настройка: повесить на тот же объект, где TelemetryGraph (или рядом, указав
// ссылку в поле График).
// =============================================================================

using System.Collections.Generic;
using UnityEngine;
using UnityEngine.InputSystem;

[DisallowMultipleComponent]
public class TelemetryGraphSwitcher : MonoBehaviour
{
    [System.Serializable]
    public class Страница
    {
        [Tooltip("Название страницы — уходит в заголовок графика")]
        public string заголовок = "";
        public List<TelemetryGraph.Серия> серии = new List<TelemetryGraph.Серия>();

        [Header("Масштаб этой страницы")]
        public TelemetryGraph.РежимМасштаба режимМасштаба = TelemetryGraph.РежимМасштаба.АвтоСтупенями;
        [Tooltip("Границы для режима «Фиксированный»")]
        public float минY = 0f;
        public float максY = 100f;
        [Tooltip("Минимальный размах в авторежиме — не даёт шуму растянуться на всю панель")]
        public float минимальныйРазмах = 1f;
    }

    [Header("Куда выводим")]
    [Tooltip("График. Пусто — возьмётся с этого же объекта.")]
    public TelemetryGraph График;

    [Header("Страницы")]
    public List<Страница> Страницы = new List<Страница>();

    [Header("Показ номера страницы")]
    [Tooltip("Дописывать «2/5» к заголовку — видно, что страниц несколько")]
    public bool показыватьНомер = true;

    [Header("Гидролокатор")]
    [Tooltip("Включать экран гидролокатора в перелистывание страниц (G). Выкл (по умолчанию) — " +
             "гидролокатор только своей кнопкой пульта / клавишей B, чтобы не выскакивал при листании.")]
    public bool гидролокаторВЛистании = false;
    [Tooltip("Клавиша показа/скрытия экрана гидролокатора (как кнопка пульта «Гидролокатор»).")]
    public Key клавишаГидролокатора = Key.B;

    // Экран гидролокатора поверх графиков — переключается кнопкой пульта (ToggleSonar) или клавишей.
    public static bool ГидролокаторНаЭкране { get; private set; }
    public static void ПереключитьГидролокатор()
    {
        ГидролокаторНаЭкране = !ГидролокаторНаЭкране;
        Debug.Log($"[Гидролокатор] экран {(ГидролокаторНаЭкране ? "ВКЛ" : "ВЫКЛ")} (шкала — H)");
    }
    bool _показанГидролокатор;

    [Header("Тест клавишей (в редакторе, без VR)")]
    public Key клавишаВперёд = Key.G;

    private int _текущая;
    private SonarMonitor _гидролокатор;

    int Всего => Страницы.Count + (гидролокаторВЛистании ? 1 : 0);

    void Awake()
    {
        if (График == null) График = GetComponent<TelemetryGraph>();
    }

    void Start()
    {
        if (График == null)
        {
            Debug.LogError($"[TelemetryGraphSwitcher] на «{name}»: не задан График — переключать нечего.", this);
            enabled = false;
            return;
        }
        if (Страницы.Count == 0)
        {
            Debug.LogWarning($"[TelemetryGraphSwitcher] на «{name}»: список Страницы пуст — график оставлен как есть.", this);
            return;
        }
        Показать(_текущая);
    }

    void Update()
    {
        if (клавишаВперёд != Key.None && Keyboard.current != null && Keyboard.current[KeyBindings.K(клавишаВперёд)].wasPressedThisFrame)
            Следующая();
        if (клавишаГидролокатора != Key.None && Keyboard.current != null && Keyboard.current[KeyBindings.K(клавишаГидролокатора)].wasPressedThisFrame)
            ПереключитьГидролокатор();
        // Кнопка пульта «Гидролокатор»: экран поверх текущей страницы графиков.
        if (ГидролокаторНаЭкране != _показанГидролокатор)
        {
            _показанГидролокатор = ГидролокаторНаЭкране;
            if (_показанГидролокатор) ПоказатьГидролокатор(true);
            else Показать(_текущая == Страницы.Count ? 0 : _текущая);
        }
    }

    /// <summary>Следующая страница по кругу. Вешать на onPressed кнопки пульта.</summary>
    public void Следующая()
    {
        if (Всего == 0) return;
        Показать((_текущая + 1) % Всего);
    }

    /// <summary>Предыдущая страница по кругу.</summary>
    public void Предыдущая()
    {
        if (Всего == 0) return;
        Показать((_текущая - 1 + Всего) % Всего);
    }

    /// <summary>Конкретная страница по номеру (с нуля).</summary>
    public void Показать(int индекс)
    {
        if (График == null || Всего == 0) return;

        _текущая = Mathf.Clamp(индекс, 0, Всего - 1);
        bool сонар = (гидролокаторВЛистании && _текущая == Страницы.Count) || ГидролокаторНаЭкране;
        ПоказатьГидролокатор(сонар);
        if (сонар && (_текущая >= Страницы.Count || Страницы.Count == 0)) return;
        if (сонар) return;   // экран гидролокатора поверх: страница сменилась «под ним», покажется при его выключении
        var с = Страницы[_текущая];

        График.Серии = с.серии;
        График.режимМасштаба = с.режимМасштаба;
        График.минY = с.минY;
        График.максY = с.максY;
        График.минимальныйРазмах = с.минимальныйРазмах;
        // Одна кривая — хватает голого числа. Две и больше — без имени непонятно,
        // где что, поэтому подписываем.
        График.имяПередЗначением = с.серии.Count > 1;
        График.заголовок = показыватьНомер
            ? $"{с.заголовок}   {_текущая + 1}/{Всего}"
            : с.заголовок;

        // Подписи строятся под конкретный набор серий — без этого на новой
        // странице остались бы значения от старой.
        График.Перестроить();
    }

    // Экран гидролокатора занимает место графика: график прячем, экран показываем.
    void ПоказатьГидролокатор(bool да)
    {
        if (да && _гидролокатор == null)
        {
            _гидролокатор = gameObject.AddComponent<SonarMonitor>();
            _гидролокатор.Построить((RectTransform)transform);   // окно на весь монитор
        }
        if (_гидролокатор != null) _гидролокатор.Показать(да);
        // Окно гидролокатора перекрывает монитор целиком — график под ним не прячем.
    }

    // Набор по умолчанию: заполняется при добавлении компонента в инспекторе.
    void Reset()
    {
        Страницы = new List<Страница>
        {
            // 1. Контур глубины: уставка и факт на одном поле — по этой картинке
            // читаются перерегулирование и время переходного процесса.
            new Страница
            {
                заголовок = "Глубина",
                режимМасштаба = TelemetryGraph.РежимМасштаба.АвтоСтупенями,
                минимальныйРазмах = 2f,
                серии = new List<TelemetryGraph.Серия>
                {
                    Серия(TelemetryChannel.Глубина,        Циан,   "факт"),
                    Серия(TelemetryChannel.УставкаГлубины, Жёлтый, "уставка"),
                }
            },

            // 2. Работа регулятора: ошибка и управляющее воздействие.
            // Диапазон жёсткий −1..1 — видно, когда управление упирается в предел.
            new Страница
            {
                заголовок = "Регулятор глубины",
                режимМасштаба = TelemetryGraph.РежимМасштаба.Фиксированный,
                минY = -1f, максY = 1f,
                серии = new List<TelemetryGraph.Серия>
                {
                    Серия(TelemetryChannel.ОшибкаРегулирования, Красный, "ошибка e, м"),
                    Серия(TelemetryChannel.УправлениеВертикаль, Зелёный, "управление u"),
                }
            },

            // 3. Разложение выхода ПИД на звенья — главная «внутренность» регулятора.
            // Сумма трёх кривых = управляющее воздействие u со страницы 2.
            new Страница
            {
                заголовок = "Составляющие ПИД",
                режимМасштаба = TelemetryGraph.РежимМасштаба.АвтоСтупенями,
                минимальныйРазмах = 0.4f,
                серии = new List<TelemetryGraph.Серия>
                {
                    Серия(TelemetryChannel.ВкладП, Циан,    "П"),
                    Серия(TelemetryChannel.ВкладИ, Жёлтый,  "И"),
                    Серия(TelemetryChannel.ВкладД, Зелёный, "Д"),
                }
            },

            // 4. Выравнивание горизонта: второй контур автопилота (момент на Rigidbody).
            // Обе кривые должны сходиться к нулю после включения удержания.
            new Страница
            {
                заголовок = "Положение",
                режимМасштаба = TelemetryGraph.РежимМасштаба.Фиксированный,
                минY = -45f, максY = 45f,
                серии = new List<TelemetryGraph.Серия>
                {
                    Серия(TelemetryChannel.Тангаж, Циан,   "тангаж"),
                    Серия(TelemetryChannel.Крен,   Жёлтый, "крен"),
                }
            },
        };

        // Намеренно НЕ добавлены страницы про заряд, ток и нагрев: эти величины
        // уже выведены цифрами на панели систем, а их кривые — медленно ползущие
        // линии, по которым нечего прочитать. График оправдан там, где важна
        // ДИНАМИКА (как система приходит к цели), а не текущее значение.
        // Если понадобятся — каналы никуда не делись, добавляются кнопкой «+».
    }

    static readonly Color Циан    = new Color(0.30f, 0.85f, 1.00f);
    static readonly Color Жёлтый  = new Color(1.00f, 0.80f, 0.25f);
    static readonly Color Зелёный = new Color(0.45f, 1.00f, 0.55f);
    static readonly Color Красный = new Color(1.00f, 0.45f, 0.45f);

    static TelemetryGraph.Серия Серия(TelemetryChannel канал, Color цвет, string подпись)
        => new TelemetryGraph.Серия { канал = канал, цвет = цвет, толщина = 2f, подпись = подпись };
}
