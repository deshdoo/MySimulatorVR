// =============================================================================
// RovSonar.cs
// -----------------------------------------------------------------------------
// Гидролокатор кругового обзора «Марлина-350» (паспорт: 900 кГц, сектор 360°,
// дальность до 60 м) — механически сканирующий: акустическая антенна на шаговом
// моторе поворачивается шагами и в каждом положении посылает импульс.
//
// КАК ЭТО РАБОТАЕТ.
//   • В одном положении антенна излучает узкий по горизонтали (≈2°) и широкий по
//     вертикали (≈30°) луч — «веер», наклонённый вниз. Всё, что попало в веер, отражает
//     звук. Приёмник записывает силу эха по времени: эхо, пришедшее через t, отражено
//     на дальности  r = c·t/2  (путь туда и обратно). Получается строка «сила эха по
//     дальности» для одного направления.
//   • Мотор поворачивает антенну на шаг (1,8°) — следующая строка. За оборот
//     складывается круговая картинка вокруг аппарата: металл трубы и крана отражает
//     сильно (яркие отметки), ил и песок — слабо; за ближним препятствием — тень.
//   • Следующий импульс нельзя послать, пока не вернулось эхо с предельной дальности:
//     время шага ≥ 2R/c. Поэтому на 60 м оборот длится ~18 с, на 10 м — ~5 с.
//     Картинка строится в осях АППАРАТА (нос — вверх): если аппарат поворачивается во
//     время оборота, изображение «смазывается», как у настоящего прибора.
//   • Дальность прибор считает по ЗАШИТОЙ скорости звука (1500 м/с). В воде с другой
//     скоростью звука все расстояния растянуты/сжаты — та же ошибка среды, что у
//     эхолота и доплеровского лага.
//
// ЧТО МОДЕЛИРУЕТСЯ: поворот антенны, время шага, веер лучей (первое отражение →
// тень), сила эха (отражающая способность × cos угла падения), шум, ошибка скорости
// звука, ширина луча. Не моделируются: многолучевость, реверберация от поверхности,
// боковые лепестки.
//
// Картинка — текстура ИзображениеЭхо (для монитора пульта, SonarMonitor). Ставится на
// НПА (RovController.Start добавляет сам).
// =============================================================================
using UnityEngine;

public class RovSonar : MonoBehaviour
{
    public static RovSonar Instance { get; private set; }

    [Header("Прибор (паспорт «Марлин-350»)")]
    [Tooltip("Рабочая частота, Гц (паспорт: 900 кГц). Определяет поглощение звука и ширину луча.")]
    public float Частота_Гц = 900e3f;
    [Tooltip("Выбираемые шкалы дальности, м (паспорт: до 60 м).")]
    public float[] Шкалы_м = { 10f, 20f, 30f, 60f };
    [Tooltip("Номер текущей шкалы в списке.")]
    public int НомерШкалы = 2;
    [Tooltip("Шаг поворота антенны, град.")]
    public float Шаг_град = 1.8f;
    [Tooltip("Ширина луча по вертикали, град (веер).")]
    public float ШиринаВертикаль_град = 30f;
    [Tooltip("Наклон оси луча вниз, град — чтобы веер ложился на дно и трубу.")]
    public float НаклонВниз_град = 15f;
    [Tooltip("Лучей в веере (дискретизация вертикальной ширины).")]
    public int ЛучейВВеере = 9;
    [Tooltip("Время обработки на шаг (помимо ожидания эха), с.")]
    public float ВремяОбработки_с = 0.01f;

    [Header("Звук в воде")]
    [Tooltip("Фактическая скорость звука, м/с (ставит PhysicsSettings по солёности/температуре).")]
    public float СкоростьЗвукаФакт_мс = 1500f;
    [Tooltip("Скорость звука, зашитая в прибор, м/с (калибровка на морскую воду).")]
    public float СкоростьЗвукаВПриборе_мс = 1500f;

    [Header("Изображение")]
    [Tooltip("Ячеек дальности в строке.")]
    public int ЯчеекДальности = 200;
    [Tooltip("Размер текстуры изображения, пикс.")]
    public int РазмерКартинки = 512;
    [Tooltip("СКО шума приёмника (доля полной яркости).")]
    public float Шум = 0.02f;

    public Texture2D ИзображениеЭхо { get; private set; }
    public float Дальность_м => Шкалы_м[Mathf.Clamp(НомерШкалы, 0, Шкалы_м.Length - 1)];
    public float УголАнтенны_град => _угол;                // относительно носа, по часовой
    public float ВремяОборота_с => 360f / Шаг_град * ВремяШага();
    public event System.Action ШкалаИзменена;

    // Последний импульс — для учебной анимации (F2): откуда, куда смотрели лучи веера,
    // где каждый луч отразился (или нет), измеренная дальность и сила эха.
    public struct Отражение { public bool есть; public Vector3 точка; public float дальность, сила; public string что; }
    public Vector3 ИсточникИмпульса { get; private set; }
    public Vector3[] НаправленияЛучей { get; private set; } = new Vector3[0];
    public Отражение[] ОтраженияИмпульса { get; private set; } = new Отражение[0];
    public float УголИмпульса_град { get; private set; }
    public float ВремяШага_с => ВремяШага();

    Transform _головка;
    Rigidbody _rb;
    float _угол, _таймер;
    Color32[] _пиксели;
    float[] _строка;
    bool _грязно;
    float _следЗаливка;

    void Awake() { Instance = this; }
    void OnDestroy() { if (Instance == this) Instance = null; }

    void Start()
    {
        _rb = GetComponent<Rigidbody>();
        foreach (var t in GetComponentsInChildren<Transform>(true))
            if (t.name == "ГоловкаГидролокатора") { _головка = t; break; }

        int N = РазмерКартинки;
        ИзображениеЭхо = new Texture2D(N, N, TextureFormat.RGBA32, false) { wrapMode = TextureWrapMode.Clamp, filterMode = FilterMode.Bilinear, name = "Гидролокатор" };
        _пиксели = new Color32[N * N];
        for (int i = 0; i < _пиксели.Length; i++) _пиксели[i] = new Color32(0, 0, 0, 255);
        ИзображениеЭхо.SetPixels32(_пиксели); ИзображениеЭхо.Apply();
        _строка = new float[ЯчеекДальности];
    }

    public void СледующаяШкала()
    {
        НомерШкалы = (НомерШкалы + 1) % Шкалы_м.Length;
        // Новая шкала — новый масштаб картинки: старое изображение стираем.
        for (int i = 0; i < _пиксели.Length; i++) _пиксели[i] = new Color32(0, 0, 0, 255);
        _грязно = true;
        ШкалаИзменена?.Invoke();
    }

    // Время шага: ждём эхо с предельной дальности по ЗАШИТОЙ скорости звука (прибор не
    // знает настоящую) + обработка.
    float ВремяШага() => 2f * Дальность_м / Mathf.Max(100f, СкоростьЗвукаВПриборе_мс) + ВремяОбработки_с;

    void Update()
    {
        if (ИзображениеЭхо == null) return;
        _таймер += Time.deltaTime;
        float шаг = ВремяШага();
        int сделано = 0;
        while (_таймер >= шаг && сделано < 8)
        {
            _таймер -= шаг; сделано++;
            Импульс();
            _угол = Mathf.Repeat(_угол + Шаг_град, 360f);
        }
        // Заливка картинки в видеокарту — не чаще 10 раз в секунду (512×512 ≈ 1 МБ за раз).
        if (_грязно && Time.unscaledTime >= _следЗаливка)
        {
            ИзображениеЭхо.SetPixels32(_пиксели); ИзображениеЭхо.Apply(false);
            _грязно = false; _следЗаливка = Time.unscaledTime + 0.1f;
        }
    }

    // Один импульс в текущем направлении антенны → строка «сила эха по дальности».
    void Импульс()
    {
        System.Array.Clear(_строка, 0, _строка.Length);
        float R = Дальность_м;
        Vector3 o = _головка != null ? _головка.position : transform.position + transform.up * 0.4f;
        if (НаправленияЛучей.Length != ЛучейВВеере) { НаправленияЛучей = new Vector3[ЛучейВВеере]; ОтраженияИмпульса = new Отражение[ЛучейВВеере]; }
        ИсточникИмпульса = o; УголИмпульса_град = _угол;
        // Сколько реально пробежит звук за окно приёма: окно рассчитано прибором на R при
        // зашитой скорости; в «быстрой» воде звук успевает дальше.
        float Rфакт = R * СкоростьЗвукаФакт_мс / СкоростьЗвукаВПриборе_мс;
        float k = СкоростьЗвукаВПриборе_мс / СкоростьЗвукаФакт_мс;   // измеренная = истинная · c_прибор / c_факт

        for (int j = 0; j < ЛучейВВеере; j++)
        {
            float накл = НаклонВниз_град + (ЛучейВВеере > 1 ? (j / (ЛучейВВеере - 1f) - 0.5f) * ШиринаВертикаль_град : 0f);
            Vector3 d = transform.rotation * (Quaternion.Euler(0f, _угол, 0f) * Quaternion.Euler(накл, 0f, 0f) * Vector3.forward);
            НаправленияЛучей[j] = d; ОтраженияИмпульса[j] = default;
            if (!ПервоеОтражение(o, d, Rфакт, out RaycastHit h)) continue;
            float r = h.distance * k;
            if (r >= R) continue;
            float cosПад = Mathf.Abs(Vector3.Dot(-d, h.normal));
            float отр = ОтражающаяСпособность(h.collider);
            float сила = отр * (0.25f + 0.75f * cosПад);
            ОтраженияИмпульса[j] = new Отражение { есть = true, точка = h.point, дальность = r, сила = сила,
                что = h.collider is TerrainCollider ? "грунт" : отр >= 0.99f ? "металл (труба/кран)" : "предмет" };
            // Пятно луча на цели растянуто по дальности на несколько ячеек.
            float ячейка = r / R * ЯчеекДальности;
            for (int b = -2; b <= 2; b++)
            {
                int idx = Mathf.FloorToInt(ячейка) + b;
                if (idx < 0 || idx >= ЯчеекДальности) continue;
                _строка[idx] = Mathf.Max(_строка[idx], сила * Mathf.Exp(-0.5f * b * b / 1.2f));
            }
        }
        Нарисовать(_строка);
    }

    bool ПервоеОтражение(Vector3 o, Vector3 d, float макс, out RaycastHit лучший)
    {
        лучший = default; float R = макс; bool есть = false;
        int n = Physics.RaycastNonAlloc(o, d, DvlJanus.Буфер, макс, ~0, QueryTriggerInteraction.Ignore);
        for (int i = 0; i < n; i++)
        {
            var h = DvlJanus.Буфер[i];
            if (h.collider.transform.IsChildOf(transform)) continue;                               // свой корпус
            if (h.rigidbody != null && h.rigidbody != _rb && !h.rigidbody.isKinematic) continue;   // подвижные тела
            if (h.collider.GetComponentInParent<UmbilicalCable>() != null) continue;              // свой кабель
            if (h.distance < R) { R = h.distance; лучший = h; есть = true; }
        }
        return есть;
    }

    // Отражающая способность: сталь (труба, кран, рама) — сильно, грунт — слабо.
    static float ОтражающаяСпособность(Collider c)
    {
        if (c is TerrainCollider) return 0.30f + 0.10f * Random.value;   // ил/песок, неровный
        string n = c.transform.root.name.ToLowerInvariant();
        if (n.Contains("pipe") || n.Contains("труб") || n.Contains("кран") || n.Contains("valve") || n.Contains("фланец")) return 1.0f;
        return 0.65f;
    }

    // Строка эха — в картинку: луч от центра под углом антенны (нос аппарата — вверх).
    // Шаг 1,8° на краю картинки шире пикселя — рисуем несколько подлучей, чтобы не было щелей.
    void Нарисовать(float[] строка)
    {
        int N = РазмерКартинки; float c = (N - 1) * 0.5f;
        const int подлучей = 3;
        for (int s = 0; s < подлучей; s++)
        {
            float a = (_угол + (s / (float)подлучей - 0.5f) * Шаг_град) * Mathf.Deg2Rad;
            float sx = Mathf.Sin(a), sy = Mathf.Cos(a);
            for (int i = 0; i < ЯчеекДальности; i++)
            {
                float v = Mathf.Clamp01(строка[i] + Mathf.Abs(DvlJanus.Гаусс()) * Шум);
                // Пиксели, накрываемые ячейкой i по радиусу.
                float r0 = i / (float)ЯчеекДальности * c, r1 = (i + 1) / (float)ЯчеекДальности * c;
                for (float r = r0; r < r1; r += 0.7f)
                {
                    int x = Mathf.RoundToInt(c + sx * r), y = Mathf.RoundToInt(c + sy * r);
                    if (x < 0 || y < 0 || x >= N || y >= N) continue;
                    _пиксели[y * N + x] = Палитра(v);
                }
            }
        }
        _грязно = true;
    }

    // Классическая палитра гидролокатора: чёрный → тёмно-коричневый → оранжевый → жёлтый.
    static Color32 Палитра(float v)
    {
        v = Mathf.Pow(v, 0.8f);
        float r = Mathf.Clamp01(v * 1.6f), g = Mathf.Clamp01(v * 1.2f - 0.15f), b = Mathf.Clamp01(v * 0.6f - 0.35f);
        return new Color32((byte)(r * 255), (byte)(g * 255), (byte)(b * 255), 255);
    }
}
