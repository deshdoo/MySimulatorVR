using UnityEngine;

// Помечает физическое положение пункта управления (кабины/диспетчерской)
// в общих мировых координатах. Нужен из-за того, что кабина (сцена Cabin.unity)
// и сам НПА (сцена Main.unity) — два разных файла сцены, которые соединяются
// только во время игры через аддитивную загрузку (Additive — «добавить вторую
// сцену поверх первой во время выполнения», а не статически в редакторе).
// Из-за этого нельзя перетащить Transform кабины прямо в поле "База" у
// RovSystemsSimulator через инспектор — Unity не сохраняет такие ссылки
// между независимыми файлами сцен. Поэтому позиция передаётся через общую
// статическую переменную RovSystems.basePosition (по аналогии с DroneInput).
//
// Поместите этот компонент на объект в Cabin.unity, который физически
// соответствует месту, откуда уходит умбиликальный кабель (например, на
// сам пульт/кабину), и при необходимости подвиньте объект в нужную точку.
public class ControlPointMarker : MonoBehaviour
{
    void Awake()
    {
        RovSystems.basePosition = transform.position;
    }

    void LateUpdate()
    {
        RovSystems.basePosition = transform.position;
    }
}
