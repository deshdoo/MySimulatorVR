// RovCurrentSensor.cs
// -----------------------------------------------------------------------------
// Датчик тока нагрузки НПА (шунт или датчик Холла), смоделированный как реальный
// прибор, а не чтение точного тока из движка.
//
// КАК МЕРЯЮТ ТОК. Напрямую «посчитать электроны» нельзя. Ток измеряют косвенно:
//   • ШУНТ — включают в цепь маленькое точное сопротивление R и меряют падение
//     напряжения на нём: U = I · R  =>  I = U / R (закон Ома). Знаем R и U — знаем I.
//   • ДАТЧИК ХОЛЛА — меряет магнитное поле вокруг провода (ток создаёт поле),
//     поле пропорционально току. Бесконтактный способ.
// В обоих случаях на выходе — напряжение, которое АЦП превращает в число. Значит,
// прибор наследует все обычные болячки: смещение нуля, шум, ступеньки, предел.
//
// Это САМЫЙ ПРОСТОЙ из наших датчиков — «умной» ошибки (как дрейф у курса или
// неразличимость ускорения у наклона) здесь нет. Только пять базовых погрешностей:
//   • смещение нуля (bias) — прибор показывает ненулевой ток при нулевом (сбитый ноль);
//   • ошибка масштаба (gain) — измеренный ток = (1+k)·истинный (неточные R или чувствительность Холла);
//   • шум — дрожание последней цифры;
//   • насыщение — выше предела прибора показание упирается в максимум;
//   • квантование (АЦП) и частота опроса.
//
// ВАЖНО ПРО ЭНЕРГОБАЛАНС. АКБ разряжается ИСТИННЫМ током (currentDrawTrue_A), а не
// показанием: физику батареи нельзя «обмануть» неточным амперметром. Прибор лишь
// формирует ПОКАЗАНИЕ currentDraw_A для экрана и графиков — как и положено датчику.
//
// Величины для графика «истина vs прибор»:
//   • currentDrawTrue_A — истина (движок),
//   • currentDraw_A     — показание (смещение + масштаб + шум + ступеньки).
//
// DefaultExecutionOrder(50): считается ПОСЛЕ RovSystemsSimulator (тот уже посчитал
// истинный ток). Без этого компонента симулятор оставляет currentDraw_A = истине.
//
// Настройка: повесить на объект НПА (там же, где RovSystemsSimulator).
// =============================================================================

using UnityEngine;

[DisallowMultipleComponent]
[DefaultExecutionOrder(50)]
public class RovCurrentSensor : MonoBehaviour
{
    [Header("Погрешности прибора")]
    [Tooltip("Смещение нуля (bias), А. Прибор показывает этот ток даже при нулевом реальном (сбитый ноль АЦП/Холла).")]
    public float СмещениеНуля_А = 0.05f;
    [Tooltip("Ошибка масштаба (gain), доля: показание = (1+k)·истинный ток. Неточное сопротивление шунта " +
             "или чувствительность Холла. 0.02 = завышает на 2%.")]
    public float ОшибкаМасштаба = 0.01f;
    [Tooltip("СКО шума тока, А (дрожание показаний).")]
    public float ШумСКО_А = 0.1f;
    [Tooltip("Разрешение АЦП по току, А: показание кратно этому шагу. 0 — без округления.")]
    public float Разрешение_А = 0.05f;

    [Header("Диапазон")]
    [Tooltip("Верхний предел прибора по току, А. Выше — насыщение (показание упирается). " +
             "Ставь с запасом над рабочим током (T200 ~17 А × число движителей + прожекторы).")]
    public float ПределТока_А = 100f;

    [Header("Опрос")]
    [Tooltip("Частота опроса датчика, Гц. Между опросами показание удерживается. 0 — каждый FixedUpdate.")]
    public float ЧастотаОпроса_Гц = 10f;

    private float _следующийОпрос_с;
    private float _показание_А;

    void FixedUpdate()
    {
        float Iистина = RovSystems.currentDrawTrue_A;

        bool опрашиваем = ЧастотаОпроса_Гц <= 0f || Time.time >= _следующийОпрос_с;
        if (опрашиваем)
        {
            if (ЧастотаОпроса_Гц > 0f) _следующийОпрос_с = Time.time + 1f / ЧастотаОпроса_Гц;

            // 1. МАСШТАБ + СМЕЩЕНИЕ + ШУМ.
            float I = (1f + ОшибкаМасштаба) * Iистина + СмещениеНуля_А + ГауссовШум() * ШумСКО_А;

            // 2. НАСЫЩЕНИЕ: не ниже нуля и не выше предела прибора.
            I = Mathf.Clamp(I, 0f, ПределТока_А);

            // 3. КВАНТОВАНИЕ (АЦП): округление до кратного разрешению.
            if (Разрешение_А > 1e-6f)
                I = Mathf.Round(I / Разрешение_А) * Разрешение_А;

            _показание_А = I;
        }

        // Публикуем ПОКАЗАНИЕ — его видят панель и графики. Разряд АКБ и просадка
        // напряжения в симуляторе идут от ИСТИННОГО тока, не отсюда.
        RovSystems.currentDraw_A = _показание_А;
    }

    static float ГауссовШум()
    {
        float u1 = Mathf.Max(1e-6f, Random.value);
        float u2 = Random.value;
        return Mathf.Sqrt(-2f * Mathf.Log(u1)) * Mathf.Cos(2f * Mathf.PI * u2);
    }
}
