// =============================================================================
// RovAltimeterSensor.cs
// -----------------------------------------------------------------------------
// Датчик высоты над дном НПА — ЭХОЛОТ (акустический альтиметр), смоделированный
// как реальный прибор, а не чтение длины рейкаста из движка.
//
// КАК ЭТО РАБОТАЕТ. Эхолот излучает вниз короткий импульс звука и засекает, через
// сколько вернётся эхо от дна. Зная скорость звука в воде c, переводит время в
// расстояние. Звук идёт до дна и обратно — путь двойной, поэтому делим на два:
//
//        h = c · t / 2
//
//   t — время пробега «туда-обратно» (с),  c — скорость звука в воде (~1500 м/с),
//   h — высота над дном (м). Это тот же принцип, что у медицинского УЗИ и у
//   рыбацкого эхолота.
//
// «ХАРАКТЕРЫ» ЭТОГО ПРИБОРА:
//
// 1. ОШИБКА СКОРОСТИ ЗВУКА (снова калибровка, как у глубины и лага). Прибор
//    считает расстояние по ЗАШИТОЙ в него скорости звука. Реальная c зависит от
//    температуры/солёности/давления. Не совпали — дальность врёт систематически:
//
//        h_показание = h · (c_прибор / c_факт)
//
//    Один и тот же тип «умной» ошибки повторяется у всех акустических приборов —
//    на защите это удобно показать как общую закономерность.
//
// 2. МЁРТВАЯ ЗОНА (blanking). Сразу после излучения приёмник «оглушён» собственным
//    импульсом и не слышит эхо. Поэтому у самого дна (ближе минимальной дальности)
//    эхолот НЕ МЕРЯЕТ — показание замирает. Реальное ограничение всех эхолотов.
//
// 3. ПРЕДЕЛ ДАЛЬНОСТИ и потеря эха. Дно дальше дальности прибора — эха нет
//    (hasBottomEcho=false, это решает геометрия в RovSystemsSimulator). Тогда
//    показание не обновляется.
//
// Плюс обычные погрешности: смещение нуля, шум, квантование (АЦП), частота опроса.
//
// Величины для графика «истина vs прибор»:
//   • altitudeTrue_m         — истина (геометрия движка),
//   • altitudeAboveBottom_m  — показание (масштаб c + шум + ступеньки; замирает в
//                              мёртвой зоне и без эха).
//
// DefaultExecutionOrder(50): считается ПОСЛЕ RovSystemsSimulator (тот уже сделал
// рейкаст и знает истинную высоту и наличие эха). Без этого компонента показание =
// истине. Придонный слой течения (WaterCurrent) использует altitudeTrue_m — физике
// нужна правда, а не показание прибора.
//
// Настройка: повесить на объект НПА (там же, где RovSystemsSimulator).
// =============================================================================

using UnityEngine;

[DisallowMultipleComponent]
[DefaultExecutionOrder(50)]
public class RovAltimeterSensor : MonoBehaviour
{
    [Header("Акустика (скорость звука)")]
    [Tooltip("Фактическая скорость звука в этой воде, м/с. Создаёт истинное время пробега эха.")]
    public float СкоростьЗвукаФакт_мс = 1500f;
    [Tooltip("Скорость звука, ЗАШИТАЯ В ПРИБОР, м/с. По ней прибор переводит время в дальность. " +
             "Не совпала с фактической — высота систематически врёт (демо: 1500 при фактических 1520).")]
    public float СкоростьЗвукаВПриборе_мс = 1500f;

    [Header("Мёртвая зона и опрос")]
    [Tooltip("Минимальная измеряемая высота, м (мёртвая зона). Ближе к дну эхолот оглушён своим " +
             "импульсом и не меряет — показание замирает.")]
    public float МёртваяЗона_м = 0.3f;
    [Tooltip("Частота опроса (пингов), Гц. Между пингами показание удерживается. 0 — каждый FixedUpdate.")]
    public float ЧастотаОпроса_Гц = 5f;

    [Header("Погрешности прибора")]
    [Tooltip("Смещение нуля, м. Постоянный сдвиг дальности (задержки электроники).")]
    public float СмещениеНуля_м = 0.0f;
    [Tooltip("СКО шума высоты, м (дрожание показаний из-за неровности дна и шума приёмника).")]
    public float ШумСКО_м = 0.05f;
    [Tooltip("Разрешение по высоте, м: показание кратно этому шагу (дискретность отсчёта времени). 0 — без округления.")]
    public float Разрешение_м = 0.05f;

    [Header("Состояние")]
    [Tooltip("Есть ли достоверное измерение сейчас: эхо от дна И вне мёртвой зоны (только чтение).")]
    public bool ЕстьИзмерение { get; private set; }

    private float _следующийОпрос_с;
    private float _показание_м;
    private bool  _иниц;

    void FixedUpdate()
    {
        float hИстина = RovSystems.altitudeTrue_m;

        if (!_иниц)
        {
            _показание_м = hИстина;
            _иниц = true;
            RovSystems.altitudeAboveBottom_m = _показание_м;
            return;
        }

        // Достоверное измерение: есть эхо от дна (геометрия) И дно не в мёртвой зоне.
        ЕстьИзмерение = RovSystems.hasBottomEcho && hИстина >= МёртваяЗона_м;

        bool опрашиваем = ЧастотаОпроса_Гц <= 0f || Time.time >= _следующийОпрос_с;
        if (ЕстьИзмерение && опрашиваем)
        {
            if (ЧастотаОпроса_Гц > 0f) _следующийОпрос_с = Time.time + 1f / ЧастотаОпроса_Гц;

            // 1. МАСШТАБ ОТ СКОРОСТИ ЗВУКА: h_показание = h · (c_прибор / c_факт).
            float cФакт = Mathf.Max(1f, СкоростьЗвукаФакт_мс);
            float масштаб = СкоростьЗвукаВПриборе_мс / cФакт;
            float h = hИстина * масштаб;

            // 2. Смещение нуля + шум. Высота ≥ 0.
            h += СмещениеНуля_м + ГауссовШум() * ШумСКО_м;
            h = Mathf.Max(0f, h);

            // 3. КВАНТОВАНИЕ: округление до кратного разрешению.
            if (Разрешение_м > 1e-6f)
                h = Mathf.Round(h / Разрешение_м) * Разрешение_м;

            _показание_м = h;
        }

        // Публикуем ПОКАЗАНИЕ. В мёртвой зоне и без эха оно не обновляется —
        // замирает на последнем значении. Флаг hasBottomEcho ведёт симулятор.
        RovSystems.altitudeAboveBottom_m = _показание_м;
    }

    static float ГауссовШум()
    {
        float u1 = Mathf.Max(1e-6f, Random.value);
        float u2 = Random.value;
        return Mathf.Sqrt(-2f * Mathf.Log(u1)) * Mathf.Cos(2f * Mathf.PI * u2);
    }
}
