using UnityEngine;

// Силовая модель движения НПА.
// Вход — DroneInput (-1..1 по каждой оси), который пишут рычаги пульта
// (LeverController) — угол рычага напрямую превращается в нормированную
// команду тяги (как реальный пропорциональный джойстик/рычаг управления
// тягой движителей, а не команда положения/скорости).
//
// Тяга задаётся в ньютонах по паспортным значениям малых ROV-движителей
// (ориентир — Blue Robotics T200: ~20Н тяги на один движитель в воде):
//   thrustForward  — 4 движителя продольной тяги  (≈4×20Н)
//   thrustVertical — 2 вертикальных движителя      (≈2×20Н)
//   torqueYaw      — дифференциальная тяга 2 движителей на плече ~0.25м
//
// Сопротивление воды — квадратичное по скорости (а не линейное демпфирование
// Unity), как и должно быть при характерных для ROV числах Рейнольдса:
//   F_сопр = -½·ρ_воды·Cx·A·v·|v|
// считается отдельно по продольной, вертикальной и поперечной осям корпуса,
// т.к. площадь сечения по каждому направлению разная.
//
// Вращательное (рысканье/yaw) сопротивление — тоже квадратичное по угловой
// скорости плюс небольшая линейная добавка (Unity Angular Drag): в реальной
// гидродинамике именно так и устроено сопротивление по числу Рейнольдса —
// при малых угловых скоростях преобладает вязкое (линейное) сопротивление,
// при больших — сопротивление давления (квадратичное). Без квадратичного
// члена момент в Н·м, рассчитанный из паспортной тяги движителей (см. ниже),
// раскручивал корпус до неестественно высокой угловой скорости — почти
// оборот в 3 секунды при моменте 10 Н·м и моменте инерции корпуса ~1.7 кг·м².
[RequireComponent(typeof(Rigidbody))]
public class RovController : MonoBehaviour
{
    [Header("Тяга движителей, Н")]
    public float thrustForward = 80f;
    public float thrustVertical = 40f;
    public float torqueYaw = 10f;
    [Tooltip("Боковая тяга (лаг), Н. У векторной схемы горизонтальные движители стоят " +
             "под углом, поэтому вбок аппарат тянет слабее, чем вперёд. 0 — боковой тяги нет.")]
    public float thrustLateral = 50f;

    [Header("Потеря тяги при повреждении движителей")]
    [Tooltip("Множитель тяги при лёгком повреждении (thrusterDamage=1). 1 — без потери.")]
    [Range(0f, 1f)] public float ТягаПриЛёгкомУроне = 0.6f;
    [Tooltip("Множитель тяги при тяжёлом повреждении (thrusterDamage=2)")]
    [Range(0f, 1f)] public float ТягаПриТяжёломУроне = 0.2f;

    [Header("Гидродинамическое сопротивление (поступательное)")]
    [Tooltip("Плотность воды, кг/м³")]
    public float ПлотностьВоды = 1025f;
    [Tooltip("Коэффициент сопротивления при движении вперёд/назад (обтекание носом). " +
             "У корпуса-«короба» ~1.1; форма по носу обычно наиболее обтекаемая из трёх.")]
    public float CxНос = 1.1f;
    [Tooltip("Коэффициент сопротивления при движении вверх/вниз (обтекание плоским низом/верхом). " +
             "Плоская тупая поверхность тормозит сильнее, чем нос — ~1.3.")]
    public float CxВерх = 1.3f;
    [Tooltip("Коэффициент сопротивления при боковом сносе (обтекание бортом) — ~1.2.")]
    public float CxБорт = 1.2f;
    [Tooltip("Площадь сечения по носу — для движения вперёд/назад, м²")]
    public float ПлощадьНос = 0.07f;
    [Tooltip("Площадь сечения сверху/снизу — для движения вверх/вниз, м²")]
    public float ПлощадьВерх = 0.12f;
    [Tooltip("Площадь сечения с борта — для бокового сноса/течения, м²")]
    public float ПлощадьБорт = 0.10f;

    [Header("Плавучесть (сила Архимеда)")]
    [Tooltip("Чистая положительная плавучесть, Н (вверх). Реальные ROV делают слегка " +
             "положительно плавучими — при потере питания аппарат медленно всплывает сам " +
             "(пассивная безопасность). 0 — идеально нейтральная плавучесть (как было раньше). " +
             "1 Н на корпус ~10 кг даёт установившуюся скорость всплытия ~0.1 м/с — её парирует " +
             "автопилот удержания глубины или лёгкий ход вниз рычагом. gravity у Rigidbody " +
             "выключен намеренно: вес и Архимед уравновешены, задаём только их разницу.")]
    public float ЧистаяПоложительнаяПлавучесть_Н = 1f;

    [Header("Присоединённая масса воды (Фоссен)")]
    [Tooltip("Ускоряясь, аппарат разгоняет и прилегающий слой воды — это добавочная " +
             "инерция (added mass), у ROV она сопоставима с собственной массой и разная по осям. " +
             "Задаётся долей от массы Rigidbody. Реализована ЯВНОЙ силой (не изменением массы), " +
             "поэтому пороги повреждений E=½mv² не затрагиваются. Значения по умолчанию " +
             "занижены ради устойчивости солвера; физический потолок по вертикали/борту ~1.0 — " +
             "поднимать с проверкой в Play Mode.")]
    [Range(0f, 1.5f)] public float ПрисМассаПродольная = 0.1f;
    [Range(0f, 1.5f)] public float ПрисМассаВертикальная = 0.5f;
    [Range(0f, 1.5f)] public float ПрисМассаБоковая = 0.4f;

    [Header("Сопротивление вращению (квадратичное)")]
    [Tooltip("Коэффициент квадратичного сопротивления вращению, Н·м·с². " +
             "Подобран так, чтобы установившаяся скорость рыскания при полном " +
             "моменте torqueYaw была реалистичной для малого ROV (≈20-25°/с), " +
             "а не неестественно быстрой, как при чисто линейном демпфировании Unity.")]
    public float КоэффСопротивленияВращению = 62.5f;

    [Header("Течение")]
    [Tooltip("Скорость воды в районе работ. Действует не силой, а через относительную " +
             "скорость в формуле сопротивления — поэтому снос зависит от того, куда и " +
             "как быстро идёт сам аппарат.")]
    public WaterCurrent Течение = new WaterCurrent();

    [Header("Метацентрическая устойчивость (восстановление крена/тангажа)")]
    [Tooltip("У реального ROV центр плавучести (точка приложения силы Архимеда) находится " +
             "выше центра тяжести — это создаёт момент, который сам возвращает корпус в " +
             "горизонт после толчка (как у ванька-встаньки), независимо от управления. " +
             "Без этого момента после удара (например, о дно) крен/тангаж гасится только " +
             "сопротивлением воды — медленно, что ощущается как раскачивание/дрожание.")]
    public float ВосстанавливающийМомент = 25f;

    private Rigidbody _rb;
    private int _contactCount = 0; // сколько коллайдеров касается корпуса прямо сейчас
    private Vector3 _prevVLocal;   // скорость в связанных осях на прошлом шаге — для присоединённой массы

    void Awake()
    {
        _rb = GetComponent<Rigidbody>();
        _rb.useGravity = false;      // вес и Архимед почти уравновешены; их РАЗНИЦУ (слабо положительную плавучесть) задаём явно в ПрименитьПлавучесть()
        _rb.linearDamping = 0f;      // встроенное линейное демпфирование Unity отключено — сопротивление считаем явно и квадратично
        _rb.angularDamping = 0.5f;   // небольшая линейная добавка к вращательному сопротивлению (вязкий режим при малых угловых скоростях)
    }

    // Восстанавливающий момент тянет корпус к строго горизонтальному положению,
    // что верно только в свободной воде. Если корпус лежит на склоне дна,
    // этот момент бесконечно "спорит" с реальным контактным наклоном —
    // отсюда незатухающая качка. Поэтому момент включается только когда
    // корпус ничего не касается (свободно плавает).
    void OnCollisionEnter(Collision c) { _contactCount++; }
    void OnCollisionExit(Collision c)  { _contactCount = Mathf.Max(0, _contactCount - 1); }

    void FixedUpdate()
    {
        // Повреждённые движители теряют тягу: удар по движителям (thrusterDamage)
        // теперь не только зажигает индикатор, но и реально режет усилие —
        // аппарат становится вялым, как с частично отказавшей движительной установкой.
        float тягаFactor = RovSystems.thrusterDamage >= 2 ? ТягаПриТяжёломУроне
                         : RovSystems.thrusterDamage == 1 ? ТягаПриЛёгкомУроне
                         : 1f;

        _rb.AddRelativeForce(new Vector3(
            DroneInput.lateral * thrustLateral,
            DroneInput.vertical * thrustVertical,
            DroneInput.forward * thrustForward
        ) * тягаFactor, ForceMode.Force);

        _rb.AddRelativeTorque(
            Vector3.up * DroneInput.yaw * torqueYaw * тягаFactor,
            ForceMode.Force
        );

        ПрименитьСопротивлениеВоды();
        ПрименитьСопротивлениеВращению();
        ПрименитьПлавучесть();
        ПрименитьПрисоединённуюМассу();

        if (_contactCount == 0)
            ПрименитьВосстанавливающийМомент();
    }

    // Чистая положительная плавучесть: у Rigidbody выключена гравитация (вес и
    // Архимед считаются уравновешенными), поэтому задаём только их РАЗНИЦУ —
    // небольшую результирующую силу вверх. Действует всегда, в том числе на
    // грунте (там просто уменьшает силу реакции опоры). При потере управления
    // аппарат медленно всплывает — это и есть штатная пассивная безопасность ROV.
    void ПрименитьПлавучесть()
    {
        if (ЧистаяПоложительнаяПлавучесть_Н != 0f)
            _rb.AddForce(Vector3.up * ЧистаяПоложительнаяПлавучесть_Н, ForceMode.Force);
    }

    // Присоединённая масса воды (added mass, модель Фоссена): при ускорении
    // аппарат разгоняет прилегающий слой воды, что проявляется как добавочная
    // инерция, разная по осям корпуса. Реализовано ЯВНОЙ силой, противоположной
    // ускорению: F_a = −m_a·a, где ускорение берётся конечной разностью скорости
    // между шагами физики (a = Δv/Δt) в СВЯЗАННЫХ осях. Это стандартный явный
    // способ; коэффициенты заданы как доля массы Rigidbody и намеренно занижены
    // ради устойчивости решателя (явная схема на прошлом ускорении). Массу самого
    // Rigidbody не трогаем — иначе поехал бы критерий повреждений E=½mv².
    void ПрименитьПрисоединённуюМассу()
    {
        float dt = Time.fixedDeltaTime;
        Vector3 vLocal = transform.InverseTransformDirection(_rb.linearVelocity);
        Vector3 aLocal = (vLocal - _prevVLocal) / dt;
        _prevVLocal = vLocal;

        Vector3 addedForceLocal = new Vector3(
            -ПрисМассаБоковая      * _rb.mass * aLocal.x,
            -ПрисМассаВертикальная * _rb.mass * aLocal.y,
            -ПрисМассаПродольная   * _rb.mass * aLocal.z
        );
        _rb.AddRelativeForce(addedForceLocal, ForceMode.Force);
    }

    void ПрименитьСопротивлениеВоды()
    {
        // Сопротивление зависит от скорости аппарата ОТНОСИТЕЛЬНО ВОДЫ, а не
        // относительно мира. Отсюда само собой получается всё поведение в течении:
        // стоящий на месте аппарат сносит потоком, идущий по течению почти не
        // встречает сопротивления, идущий против — теряет ход. Прикладывать
        // «силу течения» напрямую было бы неверно: тогда снос не зависел бы от
        // скорости самого аппарата.
        Vector3 vВоды = Течение != null ? Течение.Скорость(transform.position) : Vector3.zero;

        // Публикуем для приборов: скорость течения зависит от точки (придонный
        // слой), и нужна она именно в точке аппарата.
        RovSystems.currentSpeed_mps = vВоды.magnitude;

        Vector3 vLocal = transform.InverseTransformDirection(_rb.linearVelocity - vВоды);

        float Fx = -0.5f * ПлотностьВоды * CxБорт * ПлощадьБорт * vLocal.x * Mathf.Abs(vLocal.x);
        float Fy = -0.5f * ПлотностьВоды * CxВерх * ПлощадьВерх * vLocal.y * Mathf.Abs(vLocal.y);
        float Fz = -0.5f * ПлотностьВоды * CxНос  * ПлощадьНос  * vLocal.z * Mathf.Abs(vLocal.z);

        _rb.AddRelativeForce(new Vector3(Fx, Fy, Fz), ForceMode.Force);
    }

    void ПрименитьСопротивлениеВращению()
    {
        Vector3 wLocal = transform.InverseTransformDirection(_rb.angularVelocity);

        Vector3 dragTorque = new Vector3(
            -КоэффСопротивленияВращению * wLocal.x * Mathf.Abs(wLocal.x),
            -КоэффСопротивленияВращению * wLocal.y * Mathf.Abs(wLocal.y),
            -КоэффСопротивленияВращению * wLocal.z * Mathf.Abs(wLocal.z)
        );

        _rb.AddRelativeTorque(dragTorque, ForceMode.Force);
    }

    // Метацентрический восстанавливающий момент: момент пропорционален
    // sin(угла наклона) между текущим "верхом" корпуса и мировым "верхом" —
    // это и есть стандартная физика остойчивости (как у судна/буя), она не
    // зависит от рысканья (поворот вокруг своей вертикальной оси не меняет
    // наклон), поэтому управлению по рысканью не мешает.
    void ПрименитьВосстанавливающийМомент()
    {
        Vector3 currentUp = transform.up;
        Vector3 restoringAxis = Vector3.Cross(currentUp, Vector3.up);
        _rb.AddTorque(restoringAxis * ВосстанавливающийМомент, ForceMode.Force);
    }
}
