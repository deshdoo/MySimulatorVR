using UnityEngine;
using UnityEngine.InputSystem;

// Силовая модель движения НПА.
// Вход — DroneInput (-1..1 по каждой оси), который пишут рычаги пульта
// (LeverController) — угол рычага напрямую превращается в нормированную
// команду тяги (как реальный пропорциональный джойстик/рычаг управления
// тягой движителей, а не команда положения/скорости).
//
// Тяга задаётся в ньютонах по паспортным значениям малых ROV-движителей
// (ориентир — Blue Robotics T200: ~20Н тяги на один движитель в воде):
//   thrustForward  — 4 движителя продольной тяги  (≈4×20Н)
//   thrustVertical — 2 вертикальных движителя      (≈2×20Н)
//   torqueYaw      — дифференциальная тяга 2 движителей на плече ~0.25м
//
// Сопротивление воды — квадратичное по скорости (а не линейное демпфирование
// Unity), как и должно быть при характерных для ROV числах Рейнольдса:
//   F_сопр = -½·ρ_воды·Cx·A·v·|v|
// считается отдельно по продольной, вертикальной и поперечной осям корпуса,
// т.к. площадь сечения по каждому направлению разная.
//
// Вращательное (рысканье/yaw) сопротивление — тоже квадратичное по угловой
// скорости плюс небольшая линейная добавка (Unity Angular Drag): в реальной
// гидродинамике именно так и устроено сопротивление по числу Рейнольдса —
// при малых угловых скоростях преобладает вязкое (линейное) сопротивление,
// при больших — сопротивление давления (квадратичное). Без квадратичного
// члена момент в Н·м, рассчитанный из паспортной тяги движителей (см. ниже),
// раскручивал корпус до неестественно высокой угловой скорости — почти
// оборот в 3 секунды при моменте 10 Н·м и моменте инерции корпуса ~1.7 кг·м².
[RequireComponent(typeof(Rigidbody))]
public class RovController : MonoBehaviour
{
    [Header("Тяга движителей, Н")]
    public float thrustForward = 80f;
    public float thrustVertical = 40f;
    public float torqueYaw = 10f;
    [Tooltip("Боковая тяга (лаг), Н. У векторной схемы горизонтальные движители стоят " +
             "под углом, поэтому вбок аппарат тянет слабее, чем вперёд. 0 — боковой тяги нет.")]
    public float thrustLateral = 50f;

    [Header("Потеря тяги при повреждении движителей")]
    [Tooltip("Множитель тяги при лёгком повреждении (thrusterDamage=1). 1 — без потери.")]
    [Range(0f, 1f)] public float ТягаПриЛёгкомУроне = 0.6f;
    [Tooltip("Множитель тяги при тяжёлом повреждении (thrusterDamage=2)")]
    [Range(0f, 1f)] public float ТягаПриТяжёломУроне = 0.2f;

    [Header("Гидродинамическое сопротивление (поступательное)")]
    [Tooltip("Плотность воды, кг/м³")]
    public float ПлотностьВоды = 1025f;
    [Tooltip("Коэффициент сопротивления при движении вперёд/назад (обтекание носом). " +
             "У корпуса-«короба» ~1.1; форма по носу обычно наиболее обтекаемая из трёх.")]
    public float CxНос = 1.1f;
    [Tooltip("Коэффициент сопротивления при движении вверх/вниз (обтекание плоским низом/верхом). " +
             "Плоская тупая поверхность тормозит сильнее, чем нос — ~1.3.")]
    public float CxВерх = 1.3f;
    [Tooltip("Коэффициент сопротивления при боковом сносе (обтекание бортом) — ~1.2.")]
    public float CxБорт = 1.2f;
    [Tooltip("Площадь сечения по носу — для движения вперёд/назад, м²")]
    public float ПлощадьНос = 0.07f;
    [Tooltip("Площадь сечения сверху/снизу — для движения вверх/вниз, м²")]
    public float ПлощадьВерх = 0.12f;
    [Tooltip("Площадь сечения с борта — для бокового сноса/течения, м²")]
    public float ПлощадьБорт = 0.10f;

    [Header("Плавучесть (сила Архимеда)")]
    [Tooltip("Чистая положительная плавучесть, Н (вверх). Реальные ROV делают слегка " +
             "положительно плавучими — при потере питания аппарат медленно всплывает сам " +
             "(пассивная безопасность). 0 — идеально нейтральная плавучесть (как было раньше). " +
             "1 Н на корпус ~10 кг даёт установившуюся скорость всплытия ~0.1 м/с — её парирует " +
             "автопилот удержания глубины или лёгкий ход вниз рычагом. gravity у Rigidbody " +
             "выключен намеренно: вес и Архимед уравновешены, задаём только их разницу.")]
    public float ЧистаяПоложительнаяПлавучесть_Н = 1f;

    [Header("Присоединённая масса воды (Фоссен)")]
    [Tooltip("Ускоряясь, аппарат разгоняет и прилегающий слой воды — это добавочная " +
             "инерция (added mass), у ROV она сопоставима с собственной массой и разная по осям. " +
             "Задаётся долей от массы Rigidbody. Реализована ЯВНОЙ силой (не изменением массы), " +
             "поэтому пороги повреждений E=½mv² не затрагиваются. Значения по умолчанию " +
             "занижены ради устойчивости солвера; физический потолок по вертикали/борту ~1.0 — " +
             "поднимать с проверкой в Play Mode.")]
    [Range(0f, 1.5f)] public float ПрисМассаПродольная = 0.1f;
    [Range(0f, 1.5f)] public float ПрисМассаВертикальная = 0.5f;
    [Range(0f, 1.5f)] public float ПрисМассаБоковая = 0.4f;

    [Header("Сопротивление вращению (квадратичное)")]
    [Tooltip("Коэффициент квадратичного сопротивления вращению, Н·м·с². " +
             "Подобран так, чтобы установившаяся скорость рыскания при полном " +
             "моменте torqueYaw была реалистичной для малого ROV (≈20-25°/с), " +
             "а не неестественно быстрой, как при чисто линейном демпфировании Unity.")]
    public float КоэффСопротивленияВращению = 62.5f;

    [Header("Течение")]
    [Tooltip("Скорость воды в районе работ. Действует не силой, а через относительную " +
             "скорость в формуле сопротивления — поэтому снос зависит от того, куда и " +
             "как быстро идёт сам аппарат.")]
    public WaterCurrent Течение = new WaterCurrent();
    [Tooltip("Тест-клавиша: вкл/выкл снос от течения (удобно при отладке хвата вентиля и удержания).")]
    public Key клавишаТечение = Key.O;

    [Header("Заморозка сноса (тест-режим точного хода)")]
    [Tooltip("Клавиша: вкл/выкл гашение любого сноса (от шнура, течения, остаточного). " +
             "В режиме аппарат не «несёт» — легче наводить рычагами. Течение при этом тоже игнорируется.")]
    public Key клавишаЗаморозки = Key.Digit0;
    [Tooltip("Сила гашения сноса в режиме заморозки (по всем осям). Больше = жёстче стоит на месте " +
             "и не всплывает, но рычаги двигают медленнее. Рычаги при этом всё равно работают.")]
    public float СилаЗаморозкиСноса = 4f;

    [Header("Метацентрическая устойчивость (восстановление крена/тангажа)")]
    [Tooltip("У реального ROV центр плавучести (точка приложения силы Архимеда) находится " +
             "выше центра тяжести — это создаёт момент, который сам возвращает корпус в " +
             "горизонт после толчка (как у ванька-встаньки), независимо от управления. " +
             "Без этого момента после удара (например, о дно) крен/тангаж гасится только " +
             "сопротивлением воды — медленно, что ощущается как раскачивание/дрожание.")]
    public float ВосстанавливающийМомент = 25f;

    private Rigidbody _rb;
    private int _contactCount = 0; // сколько коллайдеров касается корпуса прямо сейчас
    private Vector3 _prevVLocal;   // скорость в связанных осях на прошлом шаге (история для сброса после переноса)
    private Vector3 _силыЛок;      // сумма известных сил этого шага в связанных осях — для присоединённой массы
    private bool _заморозкаСноса;  // тест-режим: гасим любой горизонтальный снос

    void Awake()
    {
        _rb = GetComponent<Rigidbody>();
        _rb.useGravity = false;      // вес и Архимед почти уравновешены; их РАЗНИЦУ (слабо положительную плавучесть) задаём явно в ПрименитьПлавучесть()
        _rb.linearDamping = 0f;      // встроенное линейное демпфирование Unity отключено — сопротивление считаем явно и квадратично
        _rb.angularDamping = 0.5f;   // небольшая линейная добавка к вращательному сопротивлению (вязкий режим при малых угловых скоростях)
        // Интерполяция сглаживает позу между шагами физики — камера на аппарате перестаёт
        // «дрожать», особенно после ударов о дно/трубу (кадр рендера ≠ шаг FixedUpdate).
        _rb.interpolation = RigidbodyInterpolation.Interpolate;
        ВыровнятьИнерцию();
    }

    // Восстанавливающий момент тянет корпус к строго горизонтальному положению,
    // что верно только в свободной воде. Если корпус лежит на склоне дна,
    // этот момент бесконечно "спорит" с реальным контактным наклоном —
    // отсюда незатухающая качка. Поэтому момент включается только когда
    // корпус ничего не касается (свободно плавает).
    // Для испытательных манёвров (RovManeuverTests): касается ли корпус чего-нибудь,
    // режим заморозки сноса и сброс истории скорости после переноса аппарата —
    // иначе присоединённая масса увидела бы «ускорение» скачка и дёрнула корпус.
    public bool Касается => _contactCount > 0;
    public bool ЗаморозкаСноса { get => _заморозкаСноса; set => _заморозкаСноса = value; }
    public void СброситьИсториюСкорости()
    {
        _prevVLocal = transform.InverseTransformDirection(_rb.linearVelocity);
        _contactCount = 0;
    }

    void OnCollisionEnter(Collision c) { _contactCount++; }
    void OnCollisionExit(Collision c)  { _contactCount = Mathf.Max(0, _contactCount - 1); }

    void Update()
    {
        if (Keyboard.current == null) return;

        if (клавишаТечение != Key.None && Течение != null &&
            Keyboard.current[KeyBindings.K(клавишаТечение)].wasPressedThisFrame)
        {
            Течение.включено = !Течение.включено;
            Debug.Log($"[Течение] снос от течения {(Течение.включено ? "ВКЛ" : "ВЫКЛ")}");
        }

        if (клавишаЗаморозки != Key.None &&
            Keyboard.current[KeyBindings.K(клавишаЗаморозки)].wasPressedThisFrame)
        {
            _заморозкаСноса = !_заморозкаСноса;
            Debug.Log($"[Снос] заморозка сноса {(_заморозкаСноса ? "ВКЛ — аппарат не несёт, рычаги точнее" : "ВЫКЛ")}");
        }
    }

    // Взвесь в воде (UnderwaterParticles в сцене) переносится тем же полем течения —
    // так течение видно глазом. Компонент добавляется сам, настраивать ничего не надо.
    void Start()
    {
        if (Течение != null && Течение.ПереноситьВзвесь && GetComponent<CurrentParticleAdvector>() == null)
            gameObject.AddComponent<CurrentParticleAdvector>();
        // Линии тока и профиль течения по слоям — по клавише F9.
        // Доплеровский лаг: F3 — анимация на данных рабочего датчика, F6 — вид, F7/F8 — пауза/скорость.
        if (GetComponent<DopplerInstrumentsVisualizer>() == null)
            gameObject.AddComponent<DopplerInstrumentsVisualizer>();
        if (GetComponent<CurrentFieldVisualizer>() == null)
            gameObject.AddComponent<CurrentFieldVisualizer>();
        // Муть со дна от струи движителей при работе ниже ~1 м над грунтом.
        if (GetComponent<RovSiltStirring>() == null)
            gameObject.AddComponent<RovSiltStirring>();
        // Звук борта: фон, гул движителей, удары, сигнал фиксации дефекта.
        if (GetComponent<RovAudio>() == null)
            gameObject.AddComponent<RovAudio>();
        // Вся телеметрия миссии — в CSV (Excel/Python, графики для ВКР).
        if (GetComponent<TelemetryCsvLogger>() == null)
            gameObject.AddComponent<TelemetryCsvLogger>();
        // Винты модели «Марлин-350» крутятся по командам движителей (без модели — ничего не делает).
        if (GetComponent<RovThrusterVisuals>() == null)
            gameObject.AddComponent<RovThrusterVisuals>();
        // Захват «Марлина» по кнопке захвата; старая клешня Blueye прячется.
        if (GetComponent<RovMarlinGripper>() == null)
            gameObject.AddComponent<RovMarlinGripper>();
        // Три камеры «Марлина» на одном видеоканале: курсовая / коннектор / захват (клавиша C).
        if (GetComponent<RovCameraRig>() == null)
            gameObject.AddComponent<RovCameraRig>();
        // Гидролокатор кругового обзора (паспорт «Марлина»: 900 кГц, 360°, до 60 м).
        if (GetComponent<RovSonar>() == null)
            gameObject.AddComponent<RovSonar>();
        // F2 — учебная анимация гидролокатора на данных рабочего прибора.
        if (GetComponent<SonarInstrumentVisualizer>() == null)
            gameObject.AddComponent<SonarInstrumentVisualizer>();
    }

    void FixedUpdate()
    {
        // Вихри живут в области вокруг аппарата и плывут со средним потоком.
        if (Течение != null) Течение.ОбновитьВихри(transform.position, Time.fixedDeltaTime);

        // Повреждённые движители теряют тягу: удар по движителям (thrusterDamage)
        // теперь не только зажигает индикатор, но и реально режет усилие —
        // аппарат становится вялым, как с частично отказавшей движительной установкой.
        float тягаFactor = RovSystems.thrusterDamage >= 2 ? ТягаПриТяжёломУроне
                         : RovSystems.thrusterDamage == 1 ? ТягаПриЛёгкомУроне
                         : 1f;
        // Питание по кабелю: при упоре в предел мощности (3 кВт) блок управления урезает
        // тягу всех движителей одинаково; при обрыве кабеля питания движителей нет вовсе.
        тягаFactor *= Mathf.Clamp01(RovSystems.powerLimitFactor);

        _силыЛок = new Vector3(
            DroneInput.lateral * thrustLateral,
            DroneInput.vertical * thrustVertical,
            DroneInput.forward * thrustForward
        ) * тягаFactor;
        _rb.AddRelativeForce(_силыЛок, ForceMode.Force);

        float моментРыскания = DroneInput.yaw * torqueYaw * тягаFactor;
        _rb.AddRelativeTorque(Vector3.up * моментРыскания, ForceMode.Force);

        // Порядок важен: сопротивлению (неявная схема) нужна сумма прочих сил шага,
        // присоединённой массе — сумма всех сил, включая сопротивление.
        ПрименитьПлавучесть();
        ПрименитьЗаморозкуСноса();
        ПрименитьСопротивлениеВоды();
        ПрименитьСопротивлениеВращению(new Vector3(0f, моментРыскания, 0f));
        ПрименитьПрисоединённуюМассу();

        if (_contactCount == 0)
            ПрименитьВосстанавливающийМомент();
    }

    // Тест-режим точного хода: гасим снос по ВСЕМ осям, откуда бы он ни шёл (шнур тянет
    // суставом, течение, остаточная инерция) И компенсируем положительную плавучесть —
    // иначе аппарат, не двигаясь вбок, медленно ВСПЛЫВАЛ. Итог: висит на месте, его легко
    // наводить рычагами (рычаги по-прежнему двигают — просто без самопроизвольного дрейфа/всплытия).
    void ПрименитьЗаморозкуСноса()
    {
        if (!_заморозкаСноса) return;
        Vector3 гашение = -_rb.linearVelocity * СилаЗаморозкиСноса * _rb.mass;
        if (ЧистаяПоложительнаяПлавучесть_Н != 0f)
            гашение += Vector3.down * ЧистаяПоложительнаяПлавучесть_Н;   // гасим всплытие
        _rb.AddForce(гашение, ForceMode.Force);
        _силыЛок += transform.InverseTransformDirection(гашение);
    }

    // Чистая положительная плавучесть: у Rigidbody выключена гравитация (вес и
    // Архимед считаются уравновешенными), поэтому задаём только их РАЗНИЦУ —
    // небольшую результирующую силу вверх. Действует всегда, в том числе на
    // грунте (там просто уменьшает силу реакции опоры). При потере управления
    // аппарат медленно всплывает — это и есть штатная пассивная безопасность ROV.
    void ПрименитьПлавучесть()
    {
        if (ЧистаяПоложительнаяПлавучесть_Н == 0f) return;
        Vector3 F = Vector3.up * ЧистаяПоложительнаяПлавучесть_Н;
        _rb.AddForce(F, ForceMode.Force);
        _силыЛок += transform.InverseTransformDirection(F);
    }

    // Присоединённая масса воды (added mass, модель Фоссена): при ускорении
    // аппарат разгоняет прилегающий слой воды, что проявляется как добавочная
    // инерция, разная по осям корпуса: (m + m_a)·a = ΣF, т.е. F_a = −m_a·a.
    //
    // Раньше ускорение брали конечной разностью скорости ПРОШЛОГО шага (явная схема).
    // Испытания показали запаздывание: в момент включения/выключения тяги прошлое
    // ускорение ещё нулевое, и первый шаг аппарат разгонялся/тормозил «без воды» —
    // время разгона −4 %, выбег по вертикали (m_a = 0,5·m) до −6 %.
    //
    // Теперь — без запаздывания: ускорение этого шага известно из суммы известных сил
    // ΣF (тяга, сопротивление, плавучесть, гашение сноса), a = ΣF/(m + m_a), откуда
    //     F_a = −m_a/(m + m_a)·ΣF = −k/(1 + k)·ΣF,   k = m_a/m (доли по осям).
    // Точно и безусловно устойчиво. Массу самого Rigidbody не трогаем — иначе поехал
    // бы критерий повреждений E = ½mv².
    void ПрименитьПрисоединённуюМассу()
    {
        _prevVLocal = transform.InverseTransformDirection(_rb.linearVelocity);

        // На КОНТАКТЕ (удар о дно/трубу) скорость меняется рывком → конечная разность
        // даёт огромное «ускорение», а сила присоединённой массы направлена по скорости
        // (против торможения) и вгоняет корпус обратно в поверхность — положительная
        // обратная связь, отсюда дрожание/тряска после удара. В контакте эту явную силу
        // не прикладываем: added mass — модель разгона воды в СВОБОДНОМ потоке, не удара.
        if (_contactCount > 0) return;

        static float Доля(float k) => k / (1f + Mathf.Max(0f, k));
        Vector3 addedForceLocal = new Vector3(
            -Доля(ПрисМассаБоковая)      * _силыЛок.x,
            -Доля(ПрисМассаВертикальная) * _силыЛок.y,
            -Доля(ПрисМассаПродольная)   * _силыЛок.z
        );
        _rb.AddRelativeForce(addedForceLocal, ForceMode.Force);
    }

    void ПрименитьСопротивлениеВоды()
    {
        // Сопротивление зависит от скорости аппарата ОТНОСИТЕЛЬНО ВОДЫ, а не
        // относительно мира. Отсюда само собой получается всё поведение в течении:
        // стоящий на месте аппарат сносит потоком, идущий по течению почти не
        // встречает сопротивления, идущий против — теряет ход. Прикладывать
        // «силу течения» напрямую было бы неверно: тогда снос не зависел бы от
        // скорости самого аппарата.
        // В режиме заморозки сноса воду считаем неподвижной — течение не участвует.
        Vector3 vВоды = (Течение != null && !_заморозкаСноса) ? Течение.Скорость(transform.position) : Vector3.zero;

        // Публикуем для приборов: скорость течения зависит от точки (придонный
        // слой), и нужна она именно в точке аппарата.
        RovSystems.currentSpeed_mps = vВоды.magnitude;

        Vector3 vLocal = transform.InverseTransformDirection(_rb.linearVelocity - vВоды);

        // F = −k·v·|v|, k = ½·ρ·Cx·S — по НЕЯВНОЙ (линеаризованной) схеме, как и
        // сопротивление вращению: сила берётся по скорости КОНЦА шага.
        //   a  = Δt·k·|v|/m',   m' = m·(1 + kₐ) — масса с присоединённой водой;
        //   F  = −(k·v·|v| + a·F₀)/(1 + a),  F₀ — прочие силы шага по оси (тяга, плавучесть…)
        //   ⇒  v' = (v + Δt·F₀/m')/(1 + a).
        // Явная схема (по скорости начала шага) на выбеге каждый шаг чуть завышала
        // торможение: испытания показали пути выбега короче теории на 2–8 %. Неявная
        // устойчива при любой массе (ограничитель «погасить за шаг» больше не нужен),
        // даёт точную установившуюся скорость, а выбег 1/v' = 1/v + Δt·k/m' совпадает
        // с точным решением m'·dv/dt = −k·v².
        float dt = Time.fixedDeltaTime, ρ = ПлотностьВоды, m = _rb.mass;
        float Неявно(float v, float k, float kA, float F0)
        {
            float mЭф = m * (1f + Mathf.Max(0f, kA));
            float a = dt * k * Mathf.Abs(v) / mЭф;
            return -(k * v * Mathf.Abs(v) + a * F0) / (1f + a);
        }
        float Fx = Неявно(vLocal.x, 0.5f * ρ * CxБорт * ПлощадьБорт, ПрисМассаБоковая,      _силыЛок.x);
        float Fy = Неявно(vLocal.y, 0.5f * ρ * CxВерх * ПлощадьВерх, ПрисМассаВертикальная, _силыЛок.y);
        float Fz = Неявно(vLocal.z, 0.5f * ρ * CxНос  * ПлощадьНос,  ПрисМассаПродольная,   _силыЛок.z);

        _rb.AddRelativeForce(new Vector3(Fx, Fy, Fz), ForceMode.Force);
        _силыЛок += new Vector3(Fx, Fy, Fz);
    }

    // Сопротивление вращению M = −c·ω·|ω| — по НЕЯВНОЙ (линеаризованной) схеме.
    //
    // Почему не явной. Корпус по курсу лёгкий (Iyy ≈ 0,6 кг·м²), а c велико, поэтому
    // постоянная времени вращения I/(c·|ω|) ≈ 0,012 с — меньше шага физики 0,02 с
    // («жёсткая» ось). Явная схема, считающая момент по скорости НАЧАЛА шага, за один
    // шаг гасила почти всю скорость: на испытаниях угол выбега после разворота
    // получался на 25 % меньше теоретического.
    //
    // Неявная схема берёт сопротивление по скорости КОНЦА шага, линеаризуя квадрат
    // по текущей |ω| (a = Δt·c·|ω|/I):
    //     ω' = (ω + Δt·τ/I) / (1 + a)   ⇒   M = −(c·ω·|ω| + a·τ) / (1 + a),
    // где τ — прочий момент по этой оси за шаг (у рыскания — момент движителей;
    // без него сместилась бы установившаяся скорость). Свойства: устойчива при любом
    // шаге и массе (ограничитель «погасить за шаг» больше не нужен — |M| ≤ I·|ω|/Δt
    // выполняется сам), установившаяся скорость точная (c·ω² = τ), а свободный выбег
    // 1/ω' = 1/ω + Δt·c/I совпадает с точным решением dω/dt = −c·ω²/I.
    void ПрименитьСопротивлениеВращению(Vector3 прочийМомент)
    {
        Vector3 wLocal = transform.InverseTransformDirection(_rb.angularVelocity);
        float dt = Time.fixedDeltaTime, c = КоэффСопротивленияВращению;

        float Неявно(float w, float τ, float I)
        {
            float a = dt * c * Mathf.Abs(w) / Mathf.Max(1e-4f, I);
            return -(c * w * Mathf.Abs(w) + a * τ) / (1f + a);
        }

        Vector3 dragTorque = new Vector3(
            Неявно(wLocal.x, прочийМомент.x, МоментИнерции(Vector3.right)),
            Неявно(wLocal.y, прочийМомент.y, МоментИнерции(Vector3.up)),
            Неявно(wLocal.z, прочийМомент.z, МоментИнерции(Vector3.forward)));

        _rb.AddRelativeTorque(dragTorque, ForceMode.Force);
    }


    // Тензор инерции — в осях аппарата. Unity вычисляет его сам по форме коллайдеров,
    // и у несимметричной 3D-модели главные оси выходят повёрнутыми на 5–7° относительно
    // осей корпуса: тогда разворот «перетекает» в крен/тангаж, и рысканье ведёт себя
    // не как ось аппарата (испытания: угол выбега −8 %). Реальный ROV проектируют
    // симметричным, поэтому главные моменты (их величины от Unity сохраняются) кладём
    // на оси корпуса. Вызывается и после смены массы (PhysicsSettings) — тензор
    // пересчитывается под новую массу.
    public void ВыровнятьИнерцию()
    {
        if (_rb == null) _rb = GetComponent<Rigidbody>();
        _rb.ResetInertiaTensor();
        Vector3 I = _rb.inertiaTensor;
        _rb.inertiaTensor = I;
        _rb.inertiaTensorRotation = Quaternion.identity;
    }

    // Эффективный момент инерции корпуса относительно оси (связанные оси), кг·м²:
    // во что превращается момент вдоль этой оси — Iэф = 1/(e·I⁻¹·e). Тензор Unity задан
    // в главных осях, повёрнутых на inertiaTensorRotation; если главные оси корпуса не
    // совпадают с осями аппарата (несимметричный корпус), проекция e·I·e дала бы не то.
    float МоментИнерции(Vector3 осьЛокально) => МоментИнерции(_rb, осьЛокально);

    public static float МоментИнерции(Rigidbody rb, Vector3 осьЛокально)
    {
        Vector3 e = Quaternion.Inverse(rb.inertiaTensorRotation) * осьЛокально.normalized;
        Vector3 I = rb.inertiaTensor;
        float обр = e.x * e.x / Mathf.Max(1e-6f, I.x) + e.y * e.y / Mathf.Max(1e-6f, I.y) + e.z * e.z / Mathf.Max(1e-6f, I.z);
        return 1f / Mathf.Max(1e-9f, обр);
    }

    // Метацентрический восстанавливающий момент: момент пропорционален
    // sin(угла наклона) между текущим "верхом" корпуса и мировым "верхом" —
    // это и есть стандартная физика остойчивости (как у судна/буя), она не
    // зависит от рысканья (поворот вокруг своей вертикальной оси не меняет
    // наклон), поэтому управлению по рысканью не мешает.
    void ПрименитьВосстанавливающийМомент()
    {
        Vector3 currentUp = transform.up;
        Vector3 restoringAxis = Vector3.Cross(currentUp, Vector3.up);
        _rb.AddTorque(restoringAxis * ВосстанавливающийМомент, ForceMode.Force);
    }
