using UnityEngine;

// «Помощь пилоту» — то, чем пилот настоящего ROV пользуется постоянно: автоглубина и
// автокурс, которые сами включаются, когда рычаг канала в нейтрали (паспорт «Марлин-350»:
// стабилизация курса ±5° и глубины ±0,5 м). Физика аппарата не меняется ни на ньютон —
// помощь двигает те же движители, что и рычаги, по показаниям тех же приборов
// (глубина — фильтр автопилота «датчик давления + акселерометр», курс — курсоуказатель).
//
//   • Вертикаль. Рычаг в нейтрали — держим глубину, на которой его отпустили (ПИД с
//     настройкой автопилота со стенда). И-звено само находит постоянную «подгрузку»
//     против запаса плавучести; пока пилот тянет рычаг, эта подгрузка прибавляется к его
//     команде, поэтому малый ход вниз не съедается всплытием.
//   • Курс. Рычаг поворота в нейтрали — гасим остаточное вращение и держим курс (ПД).
//   • Ход вперёд и лаг — только от пилота: без доплеровского лага скорость над дном
//     мерить нечем (снос гасит лишь автопилот с лагом).
//
// Выключается в меню (Настройки → Физика → «Помощь пилоту») — тогда чистые рычаги.
// Молчит, пока включён автопилот «Удержание» (он сам ведёт все каналы), на стенде
// испытаний (там проверяется голая модель) и пока аппарат держится захватом за вентиль.
//
// Рычаги пишут DroneInput в Update, а помощь меняет его в FixedUpdate перед RovController.
// Чтобы не принять свою же команду за команду пилота, команды рычагов снимаются в
// LateUpdate: если значение канала отличается от записанного помощью — его написал рычаг.
[RequireComponent(typeof(Rigidbody))]
[DefaultExecutionOrder(-45)]   // после автопилота и стенда испытаний (−50), до RovController (0)
public class RovPilotAssist : MonoBehaviour
{
    public static RovPilotAssist Instance { get; private set; }

    [Tooltip("Рычаг ближе к нейтрали, чем эта доля хода, считается отпущенным.")]
    public float нейтраль = 0.02f;

    [Header("Глубина")]
    [Tooltip("Предел команды удержания глубины (доля полной тяги) — как у автопилота.")]
    public float пределВертикали = 0.55f;
    [Tooltip("Отпустил рычаг на ходу — уставка берётся с упреждением: текущая глубина + " +
             "вертикальная скорость × это время, с. Аппарат не отскакивает назад к точке отпускания.")]
    public float упреждение_с = 0.6f;
    [Tooltip("Скорость нарастания команды удержания (как у автопилота). Меньше — мягче.")]
    public float плавность = 2.5f;

    [Header("Курс")]
    [Tooltip("П: команда рысканья на 1° ошибки курса.")]
    public float курсKp = 0.05f;
    [Tooltip("Д: команда рысканья на 1 °/с скорости поворота (гасит вращение после отпускания рычага).")]
    public float курсKd = 0.06f;
    [Tooltip("Предел команды рысканья помощи (доля полной).")]
    public float курсПредел = 0.5f;
    [Tooltip("После отпускания рычага курс фиксируется, когда скорость поворота упала ниже этой, °/с.")]
    public float курсФиксироватьПри = 3f;

    // Для приборов/HUD: работает ли помощь сейчас и что держит.
    public bool Активна { get; private set; }
    public bool ДержитГлубину => Активна && _естьГлубина;
    public bool ДержитКурс => Активна && _естьКурс;
    public float УставкаГлубины_м => _глубина;
    public float УставкаКурса_град => _курс;

    readonly RovAutopilot.Pid _pid = new RovAutopilot.Pid { kp = 2f, ki = 0.15f, kd = 2f, integralClamp = 4f, антиНасыщение = true };
    Rigidbody _rb;
    Vector4 _пилот;       // команды рычагов: вперёд, вертикаль, лаг, рысканье
    Vector4 _вывод;       // что помощь записала в DroneInput на последнем шаге
    bool _естьВывод, _сказано;
    bool _естьГлубина, _естьКурс, _естьКурсПрошлый;
    float _глубина, _курс, _курсПрошлый, _верт;

    void Awake()
    {
        Instance = this;
        _rb = GetComponent<Rigidbody>();
    }

    void OnDestroy() { if (Instance == this) Instance = null; }

    // Регулятор глубины — тот же, что у автопилота (его настройка со стенда «ЗАПОМНИТЬ»).
    void Start()
    {
        var ап = RovAutopilot.Instance;
        if (ап == null) return;
        _pid.kp = ап.depthPid.kp; _pid.ki = ап.depthPid.ki; _pid.kd = ап.depthPid.kd;
        _pid.integralClamp = ап.depthPid.integralClamp; _pid.антиНасыщение = ап.depthPid.антиНасыщение;
        пределВертикали = ап.maxAuthority;
    }

    void LateUpdate()
    {
        if (!_естьВывод || DroneInput.forward  != _вывод.x) _пилот.x = DroneInput.forward;
        if (!_естьВывод || DroneInput.vertical != _вывод.y) _пилот.y = DroneInput.vertical;
        if (!_естьВывод || DroneInput.lateral  != _вывод.z) _пилот.z = DroneInput.lateral;
        if (!_естьВывод || DroneInput.yaw      != _вывод.w) _пилот.w = DroneInput.yaw;
    }

    void FixedUpdate()
    {
        float dt = Time.fixedDeltaTime;
        var ап = RovAutopilot.Instance;
        bool можно = GameSettings.ПомощьПилоту && !RovManeuverTests.Идут && !_rb.isKinematic
                  && RovSystems.telemetryValid && !(ап != null && ап.Engaged);
        if (!можно)
        {
            // Уступаем управление: возвращаем каналам команды рычагов и забываем уставки.
            if (_естьВывод && !(ап != null && ап.Engaged) && !RovManeuverTests.Идут)
            {
                DroneInput.forward = _пилот.x; DroneInput.vertical = _пилот.y;
                DroneInput.lateral = _пилот.z; DroneInput.yaw = _пилот.w;
            }
            _естьВывод = false; Активна = false;
            _естьГлубина = _естьКурс = _естьКурсПрошлый = false;
            _pid.Reset();
            return;
        }

        // --- Вертикаль ---
        float h  = ап != null ? ап.ГлубинаРегулятора_m     : RovSystems.depth_m;
        float vh = ап != null ? ап.ВертСкоростьОценка_mps : -_rb.linearVelocity.y;   // + = погружается
        float верт;
        if (Mathf.Abs(_пилот.y) > нейтраль)
        {
            // Пилот ведёт сам; подгрузка И-звена против плавучести остаётся с ним.
            _естьГлубина = false;
            верт = Mathf.Clamp(_пилот.y + _pid.ВкладИ, -1f, 1f);
            _верт = верт;
        }
        else
        {
            if (!_естьГлубина) { _глубина = h + vh * упреждение_с; _естьГлубина = true; }
            // Ошибка в «вертикальных» знаках, как у автопилота: глубже уставки → тяга вверх (+).
            float u = Mathf.Clamp(_pid.Update(h - _глубина, vh, dt, пределВертикали), -пределВертикали, пределВертикали);
            _верт = Mathf.Lerp(_верт, u, 1f - Mathf.Exp(-плавность * dt));
            верт = _верт;
        }

        // --- Курс ---
        float курс = RovSystems.heading_deg;
        float скорость = _естьКурсПрошлый && dt > 0f ? Mathf.DeltaAngle(_курсПрошлый, курс) / dt : 0f;
        _курсПрошлый = курс; _естьКурсПрошлый = true;
        float рыск;
        if (Mathf.Abs(_пилот.w) > нейтраль)
        {
            _естьКурс = false;
            рыск = _пилот.w;
        }
        else
        {
            // Сначала гасим вращение (Д), курс фиксируем, когда поворот почти остановился —
            // иначе аппарат возвращался бы к курсу, на котором отпустили рычаг.
            if (!_естьКурс && Mathf.Abs(скорость) < курсФиксироватьПри) { _курс = курс; _естьКурс = true; }
            float ошибка = _естьКурс ? Mathf.DeltaAngle(курс, _курс) : 0f;
            рыск = Mathf.Clamp(курсKp * ошибка - курсKd * скорость, -курсПредел, курсПредел);
        }

        _вывод = new Vector4(_пилот.x, верт, _пилот.z, рыск);
        DroneInput.forward = _вывод.x; DroneInput.vertical = _вывод.y;
        DroneInput.lateral = _вывод.z; DroneInput.yaw = _вывод.w;
        _естьВывод = true;
        if (!_сказано) Debug.Log("[Помощь пилоту] Включена: рычаг в нейтрали — аппарат держит глубину и курс (меню: Настройки → Физика)");
        _сказано = true;
        Активна = true;
    }
}
