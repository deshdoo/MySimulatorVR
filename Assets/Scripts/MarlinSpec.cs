using UnityEngine;

// ТТХ аппарата «Марлин-350» (АО «Тетис Про») и его комплектации — единое место, откуда
// движок берёт параметры НПА. Применяются при старте миссии (PhysicsSettings.Применить)
// поверх значений в сцене, поэтому сцена не может «увести» аппарат от паспорта.
//
// Паспорт (tetis-pro.ru): масса 60 кг, габариты 980×590×450 мм, рабочая глубина 350 м,
// скорость 1 м/с вперёд и 0,5 м/с лагом/по вертикали, 4 горизонтальных + 2 вертикальных
// движителя, питание 220 В / 3 кВт с судна по оптоэлектрическому кабелю 450 м,
// стабилизация курса ±5° и глубины ±0,5 м, гидролокатор кругового обзора 900 кГц / 360° /
// до 60 м, две цветные камеры на наклонной платформе, два светильника, манипулятор «схват».
// Всё, чего в паспорте нет (тяги в ньютонах, площади, присоединённые массы), выведено из
// паспортных скоростей и габаритов — расчёт в комментариях.
public static class MarlinSpec
{
    public enum Комплектация { Базовая = 0, Поисковая = 1, Рабочая = 2 }

    public static readonly string[] НазванияКомплектаций =
        { "базовая (паспорт)", "поисковая: + лаг", "рабочая: + лаг, инструмент" };

    // Масса в воздухе, кг: паспорт 60 кг (базовая); доплеровский лаг ≈ 3 кг, инструмент
    // закручивания класса 1 с поплавком ≈ 5 кг. Балласт/поплавки под каждую комплектацию
    // подбираются так, чтобы запас плавучести оставался тем, что выставлен в меню.
    public static float Масса(Комплектация к) => к == Комплектация.Базовая ? 60f : к == Комплектация.Поисковая ? 63f : 68f;
    public static bool ЕстьЛаг(Комплектация к) => к != Комплектация.Базовая;
    public static bool ЕстьИнструмент(Комплектация к) => к == Комплектация.Рабочая;

    public const float РабочаяГлубина_м = 350f;
    public const float Ширина_м = 0.59f, Высота_м = 0.45f, Длина_м = 0.98f;

    // Сопротивление открытой рамы F = ½ρCxS·v²; тяга по оси = сопротивлению на паспортной скорости.
    public const float CxНос = 0.9f,  ПлощадьНос = 0.27f;    // 590×450 мм
    public const float CxБорт = 1.0f, ПлощадьБорт = 0.44f;   // 980×450 мм
    public const float CxВерх = 1.1f, ПлощадьВерх = 0.58f;   // 980×590 мм
    public const float ТягаВперёд_Н = 125f;     // ½·1025·0,9·0,27·1,0²  → 1,0 м/с
    public const float ТягаЛаг_Н = 56f;         // ½·1025·1,0·0,44·0,5²  → 0,5 м/с
    public const float ТягаВертикаль_Н = 82f;   // ½·1025·1,1·0,58·0,5²  → 0,5 м/с
    public const float МоментРысканья_Нм = 20f; // 4 винта × ~44 Н × плечо ~0,11 м (векторная схема 45°)
    public const float СопротивлениеВращению = 75f;
    public const float ПрисМассаПродольная = 0.3f, ПрисМассаБоковая = 0.6f, ПрисМассаВертикальная = 0.8f;
    public const float ВосстанавливающийМомент_Нм = 30f;   // ≈ m·g·BG, BG ≈ 5 см

    // Применить ТТХ к аппарату и бортовым системам. тяга — доля 0..1 (износ движителей).
    public static void Применить(RovController rov, RovSystemsSimulator сим, Комплектация к, float тяга)
    {
        if (rov != null)
        {
            rov.CxНос = CxНос; rov.ПлощадьНос = ПлощадьНос;
            rov.CxБорт = CxБорт; rov.ПлощадьБорт = ПлощадьБорт;
            rov.CxВерх = CxВерх; rov.ПлощадьВерх = ПлощадьВерх;
            rov.thrustForward = ТягаВперёд_Н * тяга;
            rov.thrustLateral = ТягаЛаг_Н * тяга;
            rov.thrustVertical = ТягаВертикаль_Н * тяга;
            rov.torqueYaw = МоментРысканья_Нм * тяга;
            rov.КоэффСопротивленияВращению = СопротивлениеВращению;
            rov.ПрисМассаПродольная = ПрисМассаПродольная;
            rov.ПрисМассаБоковая = ПрисМассаБоковая;
            rov.ПрисМассаВертикальная = ПрисМассаВертикальная;
            rov.ВосстанавливающийМомент = ВосстанавливающийМомент_Нм;

            var rb = rov.GetComponent<Rigidbody>();
            if (rb != null) { rb.mass = Масса(к); rov.ВыровнятьИнерцию(); }

            // Инструмент закручивания виден и работает только в рабочей комплектации.
            foreach (var t in rov.GetComponentsInChildren<Transform>(true))
                if (t.name == "Узел_инструмент") t.gameObject.SetActive(ЕстьИнструмент(к));
        }
        if (сим != null)
        {
            сим.МаксГлубина = РабочаяГлубина_м;
            // Мощнее/слабее движители — мощность P ∝ T^1.5 (модель питания симулятора).
            сим.МощностьДвижителяМакс_Вт = 400f * Mathf.Pow(тяга, 1.5f);
        }
        RovSystems.toolInstalled = ЕстьИнструмент(к);
    }
}
