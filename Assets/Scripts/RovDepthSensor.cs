// =============================================================================
// RovDepthSensor.cs
// -----------------------------------------------------------------------------
// Датчик глубины НПА, смоделированный как РЕАЛЬНЫЙ прибор, а не как чтение
// координаты из движка.
//
// В жизни у аппарата НЕТ прибора, который «меряет глубину» напрямую. Есть
// датчик ДАВЛЕНИЯ. Он меряет, как сильно вода давит на мембрану, а глубину
// уже ВЫЧИСЛЯЕТ из давления по формуле гидростатики:
//
//        P = ρ · g · h        =>        h = P / (ρ · g)
//
//   P — давление воды (Па),  ρ — плотность воды (кг/м³),
//   g — ускорение свободного падения (9.81 м/с²),  h — глубина (м).
//
// Механизм измерения (что происходит с числом по дороге от воды к экрану):
//
//   ИСТИНА (движок знает точно)
//      │   h_истина  →  P_истина = ρ_факт · g · h_истина
//      ▼
//   ДАТЧИК портит показание, как любой реальный прибор:
//      + смещение нуля (bias)   — прибор откалиброван неидеально
//      + случайный шум (σ)      — дрожание последней цифры (нормальное распределение)
//      × насыщение (диапазон)   — выше предела прибор «упирается»
//      × квантование (АЦП)      — показание кратно шагу разрешения
//      × частота опроса         — обновляется не каждый кадр, между опросами держит
//      ▼
//   P_показание  →  h_показание = P_показание / (ρ_прибор · g)
//
// Тонкость, которая даёт СИСТЕМАТИЧЕСКУЮ ошибку: прибор делит на ту плотность,
// что зашита в его прошивку (ρ_прибор). Если она не совпадает с фактической
// плотностью воды (ρ_факт) — например, прибор настроен на пресную воду 1000,
// а аппарат в солёной 1025 — глубина будет систематически врать на несколько
// процентов, СКОЛЬКО БЫ раз мы ни измеряли. Это реальный эффект, о котором
// хорошо рассказать на защите.
//
// Куда идут результаты: показание пишется в RovSystems.depth_m и
// RovSystems.hullPressure_kPa — их читают HUD и графики. Истина остаётся в
// RovSystems.depthTrue_m / hullPressureTrue_kPa, поэтому на одном графике можно
// нарисовать ДВЕ линии (истина и показание) и наглядно увидеть работу датчика:
// шумовую дорожку, смещение, ступеньки квантования.
//
// DefaultExecutionOrder(50): датчик считается ПОСЛЕ RovSystemsSimulator
// (порядок 0) — сначала движок кладёт истину, потом прибор её измеряет.
//
// Настройка: повесить на объект НПА (там же, где RovSystemsSimulator).
// Без этого компонента симулятор просто оставляет depth_m = истине — как было
// до появления датчика (ничего не ломается).
// =============================================================================

using UnityEngine;

[DisallowMultipleComponent]
[DefaultExecutionOrder(50)]
public class RovDepthSensor : MonoBehaviour
{
    [Header("Физика среды")]
    [Tooltip("Плотность воды, в которой аппарат НА САМОМ ДЕЛЕ, кг/м³. " +
             "Морская ~1025, пресная ~1000. Именно она создаёт истинное давление на датчик.")]
    public float ПлотностьВодыФакт = 1025f;
    [Tooltip("Плотность, ЗАШИТАЯ В ПРОШИВКУ прибора, кг/м³. По ней прибор пересчитывает " +
             "давление обратно в глубину. Если не совпадает с фактической — глубина " +
             "систематически врёт (демонстрация: поставь 1000 при фактической 1025).")]
    public float ПлотностьВодыВПриборе = 1025f;
    [Tooltip("Ускорение свободного падения, м/с²")]
    public float g = 9.81f;

    [Header("Погрешности прибора")]
    [Tooltip("Смещение нуля (bias), кПа. Постоянный сдвиг из-за неидеальной калибровки. " +
             "10 кПа ≈ 1 м по глубине.")]
    public float СмещениеНуля_кПа = 0.3f;
    [Tooltip("СКО случайного шума, кПа (среднеквадратичное отклонение дрожания показаний). " +
             "0 — идеальный бесшумный прибор.")]
    public float ШумСКО_кПа = 0.5f;
    [Tooltip("Разрешение АЦП, кПа: показание округляется до кратного этому шагу " +
             "(дискретность отсчёта). 0 — без округления.")]
    public float Разрешение_кПа = 0.2f;

    [Header("Диапазон")]
    [Tooltip("Верхний предел прибора по давлению, кПа. Выше — насыщение (показание упирается). " +
             "≈ ρ·g·h_макс: 4000 кПа ≈ 400 м морской воды.")]
    public float ПределДавления_кПа = 4000f;

    [Header("Опрос")]
    [Tooltip("Частота опроса датчика, Гц. Между опросами показание удерживается (реальный " +
             "прибор обновляется не мгновенно). 0 — пересчёт каждый FixedUpdate.")]
    public float ЧастотаОпроса_Гц = 5f;

    private float _следующийОпрос_с;      // время следующего опроса
    private float _показаниеДавления_кПа; // последнее показание, держится между опросами

    void FixedUpdate()
    {
        // 1. ИСТИНА → истинное давление. Движок знает истинную глубину точно;
        //    физически на датчик давит P = ρ_факт · g · h_истина.
        float h_истина_м = RovSystems.depthTrue_m;
        float P_истина_кПа = ПлотностьВодыФакт * g * h_истина_м * 0.001f;   // Па → кПа

        // Опрос не мгновенный: обновляем показание не чаще ЧастотаОпроса_Гц,
        // между опросами прибор показывает прежнее число.
        bool опрашиваем = ЧастотаОпроса_Гц <= 0f || Time.time >= _следующийОпрос_с;
        if (опрашиваем)
        {
            if (ЧастотаОпроса_Гц > 0f) _следующийОпрос_с = Time.time + 1f / ЧастотаОпроса_Гц;

            // 2. ПОГРЕШНОСТИ: измеренное давление = истина + смещение нуля + шум.
            //    Шум нормальный (гауссов), σ = ШумСКО_кПа.
            float P = P_истина_кПа + СмещениеНуля_кПа + ГауссовШум() * ШумСКО_кПа;

            // 3. НАСЫЩЕНИЕ: реальный прибор не показывает больше своего предела
            //    и не уходит ниже нуля (абсолютное давление у поверхности ≥ 0).
            P = Mathf.Clamp(P, 0f, ПределДавления_кПа);

            // 4. КВАНТОВАНИЕ (АЦП): округляем до кратного разрешению —
            //    показание не бывает «бесконечно точным».
            if (Разрешение_кПа > 1e-6f)
                P = Mathf.Round(P / Разрешение_кПа) * Разрешение_кПа;

            _показаниеДавления_кПа = P;
        }

        // 5. ОБРАТНЫЙ РАСЧЁТ глубины из измеренного давления по плотности ИЗ ПРИБОРА:
        //    h = P / (ρ_прибор · g). Если ρ_прибор ≠ ρ_факт — глубина систематически
        //    смещена в отношении ρ_факт / ρ_прибор.
        float ρg = Mathf.Max(1e-3f, ПлотностьВодыВПриборе * g);
        float h_показание_м = (_показаниеДавления_кПа * 1000f) / ρg;   // кПа → Па, затем /(ρg)

        // Публикуем ПОКАЗАНИЯ прибора — их видят HUD и графики телеметрии.
        RovSystems.hullPressure_kPa = _показаниеДавления_кПа;
        RovSystems.depth_m = Mathf.Max(0f, h_показание_м);
    }

    // Гауссов (нормальный) шум методом Бокса—Мюллера. Встроенный Random.value
    // даёт РАВНОМЕРНОЕ распределение [0,1), а погрешность прибора распределена
    // НОРМАЛЬНО (колокол): большинство отсчётов близко к истине, крупные выбросы
    // редки. Пара равномерных → одно нормальное с нулевым средним и σ=1.
    static float ГауссовШум()
    {
        float u1 = Mathf.Max(1e-6f, Random.value);   // защита от log(0)
        float u2 = Random.value;
        return Mathf.Sqrt(-2f * Mathf.Log(u1)) * Mathf.Cos(2f * Mathf.PI * u2);
    }
}
