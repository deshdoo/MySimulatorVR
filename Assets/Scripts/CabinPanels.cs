using System.Collections;
using System.Collections.Generic;
using TMPro;
using Unity.XR.CoreUtils;
using UnityEngine;
using UnityEngine.SceneManagement;

// Две служебные иконки кабины — круглые VR-кнопки, висящие в воздухе вертикально
// (всегда повёрнуты к оператору), и их VR-окна (в стиле меню и стенда испытаний, VrPanel):
//
//   «?» — висит посередине того места, где появится окно (слева от мониторов); пока
//         окно открыто, иконка спрятана (окно закрывается кнопкой «Закрыть»). Окно «Справка»
//         (там же, где панель испытаний) с вкладками:
//           «Среда» — течение вкл/выкл, сила, направление, пульсации, вихри, слои по глубине
//             (условия ЭТОЙ миссии; солёность, температура, плотность — в меню «Физика»);
//           «Работа приборов» — учебные показы приборов на главном экране (доплеровский лаг,
//             гидролокатор…, раньше только горячие клавиши F2/F3); новые появятся сами.
//
//   «Дверь» (иконка открытой двери) — перед дверью кабины на уровне глаз. Окно: «Сохранить
//         и выйти в меню», «Сохранить и выйти из игры», «Выйти в меню без сохранения»
//         (все три — двойным нажатием), «Отмена».
//         Сохранение — тем же путём, что «Завершить миссию»: итоги и состояние для
//         «Продолжить» пишутся в архив, затем выход.
//
// Иконки нарисованы кодом (белосерый круг, тёмный знак), нажимаются пальцем и лучом
// контроллера, при наведении чуть увеличиваются. Создаются при загрузке кабины.
public class CabinPanels : MonoBehaviour
{
    public static bool СредаОткрыта { get; private set; }
    public static bool ВыходОткрыт { get; private set; }
    static CabinPanels _я;

    public static void ПереключитьСреду() { if (_я != null) _я.Среда(!СредаОткрыта); }
    public static void ПереключитьВыход() { if (_я != null) _я.Выход(!ВыходОткрыт); }

    VrPanel _среда, _выход;
    RectTransform _средаЭкран, _выходЭкран;
    float _подтвердитьДо = -1f; string _чтоПодтвердить;


    [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.AfterSceneLoad)]
    static void Подписаться()
    {
        SceneManager.sceneLoaded += (s, _) => Создать();
        Создать();
    }

    static void Создать()
    {
        if (_я != null) return;
        var дисплей = FindFirstObjectByType<SystemStatusDisplay>(FindObjectsInactive.Include);
        if (дисплей == null) return;   // не кабина
        var go = new GameObject("Иконки кабины");
        SceneManager.MoveGameObjectToScene(go, дисплей.gameObject.scene);
        _я = go.AddComponent<CabinPanels>();
        _я.Построить(дисплей);
    }

    void OnDestroy()
    {
        if (_я == this) { _я = null; СредаОткрыта = ВыходОткрыт = false; }
        if (_иконкаСправки != null) Destroy(_иконкаСправки.gameObject);
        if (_иконкаДвери != null) Destroy(_иконкаДвери.gameObject);
        _среда?.Уничтожить(); _выход?.Уничтожить();
    }

    // ------------------------------------------------------------ иконки
    ИконкаКабины _иконкаСправки, _иконкаДвери;

    void Построить(SystemStatusDisplay дисплей)
    {
        var риг = FindFirstObjectByType<XROrigin>();
        var голова = Голова();
        float глаза = голова != null ? голова.position.y : (риг != null ? риг.transform.position.y + 1.6f : 1.6f);

        // «?» — посередине места, где откроется окно «Справка» (чуть ближе к оператору).
        if (ПозаУМониторов(ОкноW, ОкноH, out var центрОкна, out var поворотОкна, out _))
        {
            Vector3 поз = центрОкна - поворотОкна * Vector3.forward * 0.03f;
            _иконкаСправки = ИконкаКабины.Создать("Иконка «?»", поз, ИконкаКабины.Знак.Вопрос, () => Среда(!СредаОткрыта), () => СредаОткрыта, gameObject.scene);
        }

        // «Дверь» — перед дверью кабины, на уровне глаз.
        Transform дверь = null;
        foreach (var t in FindObjectsByType<Transform>(FindObjectsInactive.Exclude, FindObjectsSortMode.None))
            if (t.name.ToLowerInvariant().Contains("door") && t.gameObject.scene == дисплей.gameObject.scene) { дверь = t; break; }
        if (дверь != null && риг != null)
        {
            Bounds g = new Bounds(дверь.position, Vector3.zero);
            foreach (var r in дверь.GetComponentsInChildren<Renderer>()) g.Encapsulate(r.bounds);
            Vector3 вКабину = Vector3.ProjectOnPlane(риг.transform.position - g.center, Vector3.up).normalized;
            Vector3 поз = new Vector3(g.center.x, глаза, g.center.z) + вКабину * 0.45f;
            _иконкаДвери = ИконкаКабины.Создать("Иконка «Выход»", поз, ИконкаКабины.Знак.Дверь, () => Выход(!ВыходОткрыт), () => ВыходОткрыт, gameObject.scene);
        }
        Debug.Log("[Кабина] иконки: «?» (справка) " + (_иконкаСправки != null ? "есть" : "НЕТ") +
                  ", «выход» " + (_иконкаДвери != null ? "есть" : "НЕТ (дверь не найдена)"));
    }

    void Update()
    {
        // В режиме испытаний справки о среде нет — иконку «?» прячем.
        if (_иконкаСправки != null)
        {
            bool видна = !RovManeuverTests.Идут && !СредаОткрыта;
            if (_иконкаСправки.gameObject.activeSelf != видна) _иконкаСправки.gameObject.SetActive(видна);
        }
        _среда?.Обновить();
        _выход?.Обновить();
        if (_подтвердитьДо > 0f && Time.unscaledTime > _подтвердитьДо) { _подтвердитьДо = -1f; if (ВыходОткрыт) ПостроитьВыход(); }
    }

    // ------------------------------------------------------------ окно «Среда»
    const float ОкноW = 1000f, ОкноH = 640f;

    void Среда(bool открыть)
    {
        СредаОткрыта = открыть;
        // Иконка стоит посреди окна — пока окно открыто, прячем её (закрытие — «Закрыть»).
        if (_иконкаСправки != null) _иконкаСправки.gameObject.SetActive(!открыть);
        if (!открыть) { _среда?.Корень.SetActive(false); return; }
        if (_среда == null)
        {
            _среда = new VrPanel("ОкноСреда", 1000, 640, 0.85f, gameObject.scene, Шрифт(), false);
            if (!ПоставитьУМониторов(_среда)) ПередГлазами(_среда, -0.85f);
            _среда.Прямоугольник(_среда.Rt, 0, 0, 1000, 640, _среда.ЦветФона);
            _среда.Прямоугольник(_среда.Rt, 0, 0, 1000, 4, _среда.ЦветАкцент);
            _средаЭкран = _среда.Контейнер(_среда.Rt, "Экран");
        }
        _среда.Корень.SetActive(true);
        ПостроитьСреду();
    }

    WaterCurrent Течение => FindFirstObjectByType<RovController>()?.Течение;
    float _базаНаправления = float.NaN; List<float> _базаСлоёв;

    enum Вкладка { Среда, Приборы }
    Вкладка _вкладка = Вкладка.Среда;

    // Окно «?»: заголовок, вкладки «Среда» | «Работа приборов», содержимое вкладки, «Закрыть».
    void ПостроитьСреду()
    {
        var p = _среда; VrPanel.Очистить(_средаЭкран);
        var з = p.Текст(_средаЭкран, 32, 28, 440, 44, 32, p.ЦветТекста, перенос: false); з.fontStyle = FontStyles.Bold;
        з.text = _вкладка == Вкладка.Среда ? "Среда" : "Работа приборов";
        p.Кнопка(_средаЭкран, 520, 24, 200, 52, "<b>СРЕДА</b>", p.ЦветАкцент, () => { _вкладка = Вкладка.Среда; ПостроитьСреду(); },
                 () => _вкладка == Вкладка.Среда, 20);
        p.Кнопка(_средаЭкран, 736, 24, 232, 52, "<b>РАБОТА ПРИБОРОВ</b>", p.ЦветАкцент, () => { _вкладка = Вкладка.Приборы; ПостроитьСреду(); },
                 () => _вкладка == Вкладка.Приборы, 20);
        if (_вкладка == Вкладка.Среда) ВкладкаСреда(); else ВкладкаПриборы();
        p.Кнопка(_средаЭкран, 1000 - 232, 640 - 76, 200, 52, "<b>ЗАКРЫТЬ</b>", p.ЦветВтор, () => Среда(false), кегль: 22);
    }

    void ВкладкаСреда()
    {
        var p = _среда;
        var т = Течение;
        if (т == null)
        {
            p.Текст(_средаЭкран, 32, 130, 900, 40, 22, p.ЦветПлохо).text = "Течение не найдено (нет аппарата в сцене).";
            return;
        }
        if (float.IsNaN(_базаНаправления))
        {
            _базаНаправления = т.НаправлениеГрад;
            _базаСлоёв = new List<float>(); foreach (var с in т.Слои) _базаСлоёв.Add(с.НаправлениеГрад);
        }

        // Левая колонка — течение.
        Переключатель(_средаЭкран, 32, 110, "Течение", () => т.включено, v => т.включено = v);
        p.Регулятор(_средаЭкран, 32, 220, 440, "Сила течения", 0f, 1.5f, 0.1f, () => т.Множитель, v => т.Множитель = v,
                    v => Mathf.RoundToInt(v * 100f) + " %");
        p.Регулятор(_средаЭкран, 32, 320, 440, "Поворот направления", -180f, 180f, 15f, () => Сдвиг(т), v => ЗадатьСдвиг(т, v),
                    v => (v > 0 ? "+" : "") + v.ToString("0") + "°");
        p.Регулятор(_средаЭкран, 32, 420, 440, "Пульсации потока", 0f, 1f, 0.1f, () => т.АмплитудаПульсаций, v => т.АмплитудаПульсаций = v,
                    v => Mathf.RoundToInt(v * 100f) + " %");
        // Правая колонка — структура потока.
        Переключатель(_средаЭкран, 528, 110, "Вихри (турбулентность)", () => !т.БезВихрей, v => т.БезВихрей = !v);
        Переключатель(_средаЭкран, 528, 220, "Слои по глубине", () => т.ИспользоватьСлои, v => т.ИспользоватьСлои = v);
        p.Текст(_средаЭкран, 528, 330, 440, 160, 17, p.ЦветВтор).text =
            "Течение сносит аппарат и кабель, вихри раскачивают его, слои дают разное течение на разной глубине. " +
            "Изменения действуют сразу и только в этой миссии.";
    }

    // Приборы, для которых учебный показ ещё в разработке — строки-заготовки в списке.
    static readonly (string имя, string описание)[] ВРазработке =
    {
        ("Датчик глубины", "давление воды → глубина; ошибка плотности воды"),
        ("Курсоуказатель", "гироскоп уплывает, компас подтягивает"),
        ("Тангаж и крен", "акселерометр путает наклон с разгоном"),
        ("Эхолот", "высота над дном по времени эха"),
        ("Датчик тока", "ток в кабеле и предел мощности 3 кВт"),
    };

    // Вкладка «Работа приборов»: учебные показы (раньше — только горячие клавиши F2/F3).
    // Список строится из всех компонентов с IДемонстрацияПрибора — новый показ появится сам.
    void ВкладкаПриборы()
    {
        var p = _среда;
        p.Текст(_средаЭкран, 32, 76, 900, 24, 16, p.ЦветВтор, перенос: false).text =
            "замедленная анимация на данных рабочего прибора · показ идёт на большом экране";
        var показы = new List<IДемонстрацияПрибора>();
        foreach (var mb in FindObjectsByType<MonoBehaviour>(FindObjectsSortMode.None))
            if (mb is IДемонстрацияПрибора д) показы.Add(д);
        показы.Sort((a, b) => a.Порядок.CompareTo(b.Порядок));

        float y = 110f; const float строка = 64f;
        IДемонстрацияПрибора активный = null;
        foreach (var д in показы)
        {
            if (д.Показано) активный = д;
            var имя = p.Текст(_средаЭкран, 32, y, 700, 30, 22, д.Показано ? p.ЦветАкцент : p.ЦветТекста, перенос: false);
            имя.fontStyle = FontStyles.Bold; имя.text = д.Название;
            p.Текст(_средаЭкран, 32, y + 30, 720, 24, 15, p.ЦветВтор, перенос: false).text =
                д.Показано ? "идёт показ · " + д.Состояние : д.Описание;
            var этот = д;
            p.Кнопка(_средаЭкран, 1000 - 232, y + 4, 200, 52, этот.Показано ? "<b>СКРЫТЬ</b>" : "<b>ПОКАЗАТЬ</b>",
                     этот.Показано ? p.ЦветСредне : p.ЦветХорошо, () => ПоказатьПрибор(этот, показы), кегль: 20);
            y += строка;
        }
        // Заготовки: приборы, чей показ ещё не сделан (не дублируем уже готовые).
        foreach (var (имя, описание) in ВРазработке)
        {
            bool есть = false;
            foreach (var д in показы) if (д.Название.StartsWith(имя)) есть = true;
            if (есть || y > 640 - 150) continue;
            p.Текст(_средаЭкран, 32, y, 700, 30, 20, new Color(1f, 1f, 1f, 0.35f), перенос: false).text = имя;
            p.Текст(_средаЭкран, 32, y + 28, 720, 24, 15, new Color(1f, 1f, 1f, 0.25f), перенос: false).text = описание + " · в разработке";
            y += строка - 6f;
        }
        // Управление идущим показом (то же, что клавиши F7/F8; вид F6 — только с клавиатуры).
        if (активный != null)
        {
            float bx = 32f, by = 640 - 76;
            p.Кнопка(_средаЭкран, bx, by, 180, 52, "<b>ПАУЗА</b>", p.ЦветВтор, () => { активный.Пауза(); ПостроитьСреду(); }, кегль: 20);
            p.Кнопка(_средаЭкран, bx + 196, by, 200, 52, "<b>СКОРОСТЬ</b>", p.ЦветВтор, () => { активный.СменитьСкорость(); ПостроитьСреду(); }, кегль: 20);
        }
    }

    // Показ одновременно один (оба забирают большой экран): включая один, гасим остальные.
    void ПоказатьПрибор(IДемонстрацияПрибора д, List<IДемонстрацияПрибора> все)
    {
        bool включить = !д.Показано;
        foreach (var другой in все) if (другой != д && другой.Показано) другой.Переключить();
        if (д.Показано != включить) д.Переключить();
        ПостроитьСреду();
    }

    float Сдвиг(WaterCurrent т) => Mathf.DeltaAngle(_базаНаправления, т.НаправлениеГрад);
    void ЗадатьСдвиг(WaterCurrent т, float сдвиг)
    {
        т.НаправлениеГрад = _базаНаправления + сдвиг;
        for (int i = 0; i < т.Слои.Count && i < _базаСлоёв.Count; i++) т.Слои[i].НаправлениеГрад = _базаСлоёв[i] + сдвиг;
    }

    // Пара кнопок ВКЛ/ВЫКЛ под подписью (выбранная горит).
    void Переключатель(RectTransform р, float x, float y, string подпись, System.Func<bool> получить, System.Action<bool> задать)
    {
        var p = _среда;
        p.Текст(р, x, y, 440, 28, 21, p.ЦветТекста, перенос: false).text = подпись;
        p.Кнопка(р, x, y + 34, 200, 52, "<b>ВКЛ</b>", p.ЦветХорошо, () => { задать(true); ПостроитьСреду(); }, () => получить(), 22);
        p.Кнопка(р, x + 216, y + 34, 200, 52, "<b>ВЫКЛ</b>", p.ЦветПлохо, () => { задать(false); ПостроитьСреду(); }, () => !получить(), 22);
    }

    // ------------------------------------------------------------ окно «Выход»
    void Выход(bool открыть)
    {
        ВыходОткрыт = открыть;
        _подтвердитьДо = -1f;
        if (!открыть) { _выход?.Корень.SetActive(false); return; }
        if (_выход == null)
        {
            _выход = new VrPanel("ОкноВыход", 800, 500, 0.6f, gameObject.scene, Шрифт(), false);
            _выход.Прямоугольник(_выход.Rt, 0, 0, 800, 500, _выход.ЦветФона);
            _выход.Прямоугольник(_выход.Rt, 0, 0, 800, 4, _выход.ЦветАкцент);
            _выходЭкран = _выход.Контейнер(_выход.Rt, "Экран");
        }
        // Окно — перед иконкой двери, лицом к оператору; без иконки — перед глазами.
        var голова = Голова();
        if (_иконкаДвери != null && голова != null)
        {
            Vector3 к = голова.position - _иконкаДвери.transform.position;
            Vector3 поз = _иконкаДвери.transform.position + Vector3.ProjectOnPlane(к, Vector3.up).normalized * 0.2f - Vector3.up * 0.05f;
            _выход.Корень.transform.SetPositionAndRotation(поз, Quaternion.LookRotation(поз - голова.position, Vector3.up));
        }
        else ПередГлазами(_выход, 0f);
        _выход.Корень.SetActive(true);
        ПостроитьВыход();
    }

    void ПостроитьВыход()
    {
        var p = _выход; VrPanel.Очистить(_выходЭкран);
        var з = p.Текст(_выходЭкран, 32, 24, 700, 40, 32, p.ЦветТекста, перенос: false); з.fontStyle = FontStyles.Bold; з.text = "Выход";
        p.Текст(_выходЭкран, 32, 70, 736, 50, 17, p.ЦветВтор).text =
            "С сохранением итоги и состояние миссии пишутся в архив — её можно будет продолжить из меню «Результаты».";
        bool ждёмМеню = _подтвердитьДо > 0f && _чтоПодтвердить == "меню";
        bool ждёмИгру = _подтвердитьДо > 0f && _чтоПодтвердить == "игра";
        p.Кнопка(_выходЭкран, 32, 140, 736, 64, ждёмМеню ? "<b>НАЖМИТЕ ЕЩЁ РАЗ</b>" : "<b>СОХРАНИТЬ И ВЫЙТИ В МЕНЮ</b>", p.ЦветАкцент,
                 () => Подтвердить("меню"), кегль: 24);
        p.Кнопка(_выходЭкран, 32, 220, 736, 64, ждёмИгру ? "<b>НАЖМИТЕ ЕЩЁ РАЗ</b>" : "<b>СОХРАНИТЬ И ВЫЙТИ ИЗ ИГРЫ</b>", p.ЦветПлохо,
                 () => Подтвердить("игра"), кегль: 24);
        bool ждёмБез = _подтвердитьДо > 0f && _чтоПодтвердить == "без";
        p.Кнопка(_выходЭкран, 32, 300, 736, 64, ждёмБез ? "<b>НАЖМИТЕ ЕЩЁ РАЗ — ПРОГРЕСС ПРОПАДЁТ</b>" : "<b>ВЫЙТИ В МЕНЮ БЕЗ СОХРАНЕНИЯ</b>", p.ЦветСредне,
                 () => Подтвердить("без"), кегль: 24);
        p.Кнопка(_выходЭкран, 32, 400, 736, 64, "<b>ОТМЕНА</b>", p.ЦветВтор, () => Выход(false), кегль: 24);
    }

    // Двойное нажатие: первое — просьба подтвердить (3 с), второе — действие.
    void Подтвердить(string что)
    {
        if (_подтвердитьДо > 0f && _чтоПодтвердить == что)
        {
            _подтвердитьДо = -1f;
            if (что == "без") ВыйтиБезСохранения();
            else StartCoroutine(СохранитьИВыйти(что == "игра"));
            return;
        }
        _чтоПодтвердить = что; _подтвердитьДо = Time.unscaledTime + 3f;
        ПостроитьВыход();
    }

    // Без сохранения: миссия не завершается и в архив ничего не пишется — сразу меню.
    static void ВыйтиБезСохранения()
    {
        Time.timeScale = 1f;
        AudioListener.pause = false;
        SceneManager.LoadScene(0);
    }

    IEnumerator СохранитьИВыйти(bool изИгры)
    {
        // Сохранение — тем же путём, что «Завершить миссию»: досрочное завершение → окно итогов
        // пишет отчёт и состояние в архив. Ждём записи (не дольше 5 с), затем выходим.
        var менеджер = MissionManager.Instance;
        if (менеджер != null)
        {
            менеджер.ЗавершитьДосрочно();
            float до = Time.unscaledTime + 5f;
            while (Time.unscaledTime < до)
            {
                var итоги = FindFirstObjectByType<MissionDebriefPanel>();
                if (итоги != null && итоги.ОтчётСохранён) break;
                yield return null;
            }
        }
        AudioListener.pause = false;
        if (изИгры)
        {
#if UNITY_EDITOR
            UnityEditor.EditorApplication.isPlaying = false;
#else
            Application.Quit();
#endif
        }
        else SceneManager.LoadScene(0);   // перезагрузка → главное меню
    }

    // ------------------------------------------------------------ размещение
    static TMP_FontAsset Шрифт()
    {
        var hud = FindFirstObjectByType<MissionHudDisplay>(FindObjectsInactive.Include);
        return hud != null ? hud.шрифт : null;
    }

    static Transform Голова()
    {
        var риг = FindFirstObjectByType<XROrigin>();
        return риг != null && риг.Camera != null ? риг.Camera.transform : Camera.main != null ? Camera.main.transform : null;
    }

    static void ПередГлазами(VrPanel п, float вбок)
    {
        var г = Голова(); if (г == null) return;
        Vector3 f = Vector3.ProjectOnPlane(г.forward, Vector3.up).normalized; if (f.sqrMagnitude < 0.01f) f = Vector3.forward;
        Vector3 вправо = Vector3.Cross(Vector3.up, f);
        Vector3 поз = г.position + f * 1.0f + вправо * вбок + Vector3.up * 0.05f;
        п.Корень.transform.SetPositionAndRotation(поз, Quaternion.LookRotation(поз - г.position, Vector3.up));
    }

    // Как панель испытаний: слева от левого нижнего монитора («Состояние НПА»), правым краем
    // у монитора, в пол-оборота к креслу; если до стены мало места — панель уменьшается.
    static bool ПоставитьУМониторов(VrPanel п)
    {
        if (!ПозаУМониторов(п.W, п.H, out var центр, out var поворот, out float ширина)) return false;
        п.Rt.localScale = Vector3.one * (ширина / п.W);
        п.Корень.transform.SetPositionAndRotation(центр, поворот);
        return true;
    }

    // Где встанет окно у мониторов: центр, поворот и ширина в метрах.
    static bool ПозаУМониторов(float W, float H, out Vector3 центр, out Quaternion поворот, out float ширина)
    {
        const float Зазор_м = 0.67f, НазадОтЭкрана_м = -0.15f, Наклон_град = 60f, ОтступОтСтены_м = 0.08f, МинШирина_м = 0.55f;
        центр = Vector3.zero; поворот = Quaternion.identity; ширина = 0.85f;
        var дисплей = FindFirstObjectByType<SystemStatusDisplay>(FindObjectsInactive.Include);
        var холст = дисплей != null ? дисплей.GetComponentInParent<Canvas>(true) : null;
        var риг = FindFirstObjectByType<XROrigin>();
        if (холст == null || риг == null) return false;
        var углы = new Vector3[4];
        ((RectTransform)холст.transform).GetWorldCorners(углы);
        Vector3 центрЭкрана = (углы[0] + углы[1] + углы[2] + углы[3]) * 0.25f;
        Vector3 кПилоту = Vector3.ProjectOnPlane(риг.transform.position - центрЭкрана, Vector3.up).normalized;
        if (кПилоту.sqrMagnitude < 0.01f) return false;
        Vector3 вправо = Vector3.Cross(Vector3.up, -кПилоту);
        float левыйКрай = float.PositiveInfinity, низ = float.PositiveInfinity;
        foreach (var у in углы) { левыйКрай = Mathf.Min(левыйКрай, Vector3.Dot(у - центрЭкрана, вправо)); низ = Mathf.Min(низ, у.y); }
        Vector3 петля = центрЭкрана + вправо * (левыйКрай - Зазор_м) - кПилоту * НазадОтЭкрана_м;
        петля.y = низ + 0.13f;
        Vector3 вдоль = Quaternion.AngleAxis(-Наклон_град, Vector3.up) * -вправо;
        float доСтены = float.PositiveInfinity;
        foreach (var h in Physics.RaycastAll(петля + Vector3.up * 0.3f, -вправо, 2.5f, ~0, QueryTriggerInteraction.Ignore))
        {
            if (h.collider.GetComponentInParent<ИконкаКабины>() != null) continue;   // своя иконка — не стена
            доСтены = float.IsPositiveInfinity(доСтены) ? h.distance : Mathf.Max(доСтены, h.distance);
        }
        if (!float.IsPositiveInfinity(доСтены))
            ширина = Mathf.Clamp((доСтены - ОтступОтСтены_м) / Vector3.Dot(вдоль, -вправо), МинШирина_м, ширина);
        float высота = ширина * H / W;
        центр = петля + вдоль * (ширина * 0.5f) + Vector3.up * (высота * 0.5f);
        поворот = Quaternion.LookRotation(Vector3.Cross(Vector3.up, вдоль), Vector3.up);
        return true;
    }
