using UnityEngine;

// Автопилот стабилизации ("Удержание") НПА.
// По включению приводит аппарат к ровному, "как при запуске" состоянию и держит его:
//   - ВЫРАВНИВАНИЕ ГОРИЗОНТА: тангаж и крен -> 0 (корпус встаёт прямо);
//   - удержание КУРСА, на котором включили (ПД по рысканью по курсоуказателю —
//     гироскоп + компас). Паспорт «Марлин-350»: стабилизация по курсу ±5°;
//   - удержание глубины (ПИД по вертикали). Паспорт: стабилизация по глубине ±0,5 м;
//   - гашение продольного и бокового сноса — ТОЛЬКО если установлен доплеровский
//     лаг (дополнительное оборудование, в паспорте его нет). Без лага скорость над
//     дном мерить нечем, и аппарат, как серийный, дрейфует с течением.
//
// Удержание — «живое», не мёртвое: держим не точку, а узкую ЗОНУ (мёртвые зоны по
// глубине и сносу). В пределах зоны регулятор молчит, и аппарат свободно
// покачивается в вихрях течения (WaterCurrent, вихри в потоке) — как настоящий
// ROV, который «дышит» около точки. Парируется лишь заметный уход за зону. Без
// этого аппарат висел бы идеально неподвижно, будто выключили физику.
//
// Почему выравнивание — прямым моментом, а не через DroneInput: команды тяги
// (DroneInput) управляют только продольным/вертикальным движением и рысканьем —
// наклоном (тангаж/крен) они не управляют вовсе. Поэтому крен/тангаж выравниваем
// напрямую моментом на Rigidbody: тянем "верх" корпуса к мировому "верху".
// Ось этого момента = Cross(up, worldUp) — она горизонтальна и НЕ содержит
// компоненты рыскания, поэтому курс остаётся свободным (как и требуется).
//
// Когда включён — пишет вертикаль/снос в DroneInput (перекрывая рычаги, за счёт
// DefaultExecutionOrder(-50) перед RovController) и прикладывает момент выравнивания.
// Выключен — не вмешивается, управление у рычагов.
//
// ОБРАТНАЯ СВЯЗЬ ПО ГЛУБИНЕ — ОТ ПРИБОРА, А НЕ ОТ ИСТИНЫ. У реального аппарата
// нет «истинной координаты»: автопилот держит глубину по датчику давления
// (RovDepthSensor → RovSystems.depth_m), со всеми его погрешностями. Поэтому шум,
// квантование и редкий опрос датчика прямо видны в качестве удержания — слой
// моделей приборов влияет на поведение аппарата, а не только на цифры на панели.
//
// Но датчик давления медленный (опрос 5 Гц), шумный и ступенчатый (АЦП). Просто
// сгладить его нельзя: фильтр добавляет запаздывание, и ПИД, настроенный на
// точную глубину, уходит в автоколебания (аппарат «прыгает» вверх-вниз). Поэтому,
// как в реальных автопилотах (ArduSub/ArduPilot, AP_InertialNav), глубина и
// вертикальная скорость ОЦЕНИВАЮТСЯ комплементарным фильтром 3-го порядка,
// который комплексирует два прибора с противоположными свойствами:
//   акселерометр — быстрый, без запаздывания, но при интегрировании «уплывает»
//                  (смещение нуля → ошибка скорости растёт линейно, глубины — квадратично);
//   датчик давления — медленный и шумный, зато без накопления ошибки.
// Уравнения (e — невязка между показанием датчика и оценкой, T — постоянная времени):
//   e  = h_датчик − ĥ
//   b̂ += k3·e·dt                      — поправка на смещение нуля акселерометра (→ −смещение)
//   v̂ += (a_изм + b̂ + k2·e)·dt        — вертикальная скорость
//   ĥ += (v̂ + k1·e)·dt                — глубина
//   k1 = 3/T, k2 = 3/T², k3 = 1/T³   (тройной полюс −1/T — без перерегулирования)
// На низких частотах оценка следует датчику давления, на высоких — акселерометру.
// В ПИД идёт ĥ, а Д-звено берёт v̂ (дифференцирование ПО ОЦЕНКЕ СКОРОСТИ, а не
// разностью шумного показания). Режим «Истина» оставлен для сравнения на графике.
//
// Ставится на объект НПА (там же, где RovController/Rigidbody), сцена Main.
// Доступ из Cabin (кнопка) — через статический Instance.
[RequireComponent(typeof(Rigidbody))]
[DefaultExecutionOrder(-50)]
public class RovAutopilot : MonoBehaviour
{
    public static RovAutopilot Instance { get; private set; }

    [System.Serializable]
    public class Pid
    {
        public float kp = 1f;
        public float ki = 0f;
        public float kd = 0f;
        [Tooltip("Предел накопленного интеграла (анти-виндап)")]
        public float integralClamp = 1f;
        [Tooltip("Защита от интегрального насыщения (условное интегрирование): пока выход " +
                 "упёрся в предел тяги и ошибка тянет дальше в ту же сторону, интеграл не копится. " +
                 "Без неё при долгом ходе на пределе И-звено набирает «запас» и даёт проскок уставки.")]
        public bool антиНасыщение = false;

        float _integral, _prevError;
        bool _hasPrev;

        // Вклад каждого звена в последний посчитанный выход — для графиков.
        // Именно по ним видно, кто из трёх звеньев за что отвечает:
        // П тянет к уставке пропорционально ошибке, И добивает статическую
        // ошибку (например, остаточную плавучесть), Д гасит скорость подхода.
        public float ВкладП { get; private set; }
        public float ВкладИ { get; private set; }
        public float ВкладД { get; private set; }

        public void Reset()
        {
            _integral = 0f; _prevError = 0f; _hasPrev = false;
            ВкладП = ВкладИ = ВкладД = 0f;
        }

        // Вариант с внешней производной: Д-звено берёт готовую оценку скорости
        // изменения ошибки (от наблюдателя), а не численную разность — разность
        // шумного/ступенчатого сигнала даёт выбросы.
        public float Update(float error, float derivative, float dt, float предел = float.PositiveInfinity)
        {
            float новый = Mathf.Clamp(_integral + error * dt, -integralClamp, integralClamp);
            float выход = kp * error + ki * новый + kd * derivative;
            // В насыщении и ошибка «тянет дальше» — не копим (условное интегрирование).
            if (!(антиНасыщение && Mathf.Abs(выход) > предел && выход * error > 0f)) _integral = новый;
            _prevError = error;
            _hasPrev = true;

            ВкладП = kp * error;
            ВкладИ = ki * _integral;
            ВкладД = kd * derivative;
            return ВкладП + ВкладИ + ВкладД;
        }

        public float Update(float error, float dt)
        {
            _integral = Mathf.Clamp(_integral + error * dt, -integralClamp, integralClamp);
            float deriv = _hasPrev && dt > 0f ? (error - _prevError) / dt : 0f;
            _prevError = error;
            _hasPrev = true;

            ВкладП = kp * error;
            ВкладИ = ki * _integral;
            ВкладД = kd * deriv;
            return ВкладП + ВкладИ + ВкладД;
        }
    }

    [Header("Выравнивание горизонта (курс НЕ трогается)")]
    [Tooltip("Сила выравнивания КРЕНА — заваленный вбок горизонт. Больше = резче.")]
    public float rollStrength = 4f;
    [Tooltip("Сила выравнивания ТАНГАЖА — нос вверх/вниз (вертикальная плоскость). Больше = резче.")]
    public float pitchStrength = 4f;
    [Tooltip("Демпфирование колебаний при выравнивании. Больше = плавнее, без перелёта.")]
    public float levelDamping = 2.5f;

    [Header("Удержание курса (по курсоуказателю)")]
    [Tooltip("Держать курс, на котором включили автопилот (паспорт «Марлин-350»: ±5°).")]
    public bool держатьКурс = true;
    [Tooltip("П-коэффициент по курсу: команда рысканья на 1° ошибки.")]
    public float курсKp = 0.05f;
    [Tooltip("Д-коэффициент по курсу: команда рысканья на 1 °/с скорости поворота (гасит перелёт).")]
    public float курсKd = 0.06f;
    [Tooltip("Мёртвая зона по курсу, град: внутри неё рысканье не командуется (аппарат «дышит» в вихрях).")]
    public float курсМёртваяЗона_град = 0.5f;
    [Tooltip("Предел команды рысканья автопилота (доля полной).")]
    public float курсПредел = 0.5f;

    [Header("ПИД глубины (вертикаль)")]
    // ki/integralClamp подняты специально: у корпуса есть ПОСТОЯННАЯ положительная
    // плавучесть (_RovController_.ЧистаяПоложительнаяПлавучесть_Н, ~1 Н вверх). Чтобы
    // висеть ровно, вертикальная тяга должна ПОСТОЯННО чуть поддавливать вниз, а
    // постоянную составляющую даёт только интегральное звено. Слабый И (или большая
    // мёртвая зона, гасящая его вход) не успевает набрать это давление — и аппарат
    // потихоньку всплывает, «сводится наверх». Поэтому И сделан сильнее и с большим
    // запасом накопления.
    // Настройка подобрана на стенде испытаний (RovManeuverTests, ступенька +2 м, 2026-10-01):
    //   исходная 1.2 / 0.25 / 0.6 без защиты — перерегулирование 37,6 %, установление 13,2 с;
    //   итоговая 2.0 / 0.15 / 2.0 с защитой от насыщения — 2 %, 4,8 с.
    // Тогда аппарат был условный: 10 кг, вертикальная тяга 40 Н. У «Марлина» 60 кг и 82 Н
    // (вверх — задний ход, 64 Н), присоединённая масса и сопротивление по вертикали больше,
    // поэтому разгон по вертикали в 3,5 раза слабее. Перенастройка под 60 кг (2026-10-26) —
    // расчётом контура глубины по тем же уравнениям, что в движке (датчик 5 Гц с шумом,
    // фильтр, мёртвая зона, сглаживание, защита интеграла); на старом аппарате расчёт дал
    // 38 % / 13,3 с и 2,7 % / 5,0 с — совпадает со стендом. Ступенька 2 м при пределе 0,55:
    //   2.0 / 0.15 / 2.0 — 2,5 %, 6,8 с; при плавучести −10 Н проскок 5,5 %;
    //   3.0 / 0.25 / 3.0 — 2,0 %, 6,7 с; при −10 Н 3,4 %, при тяге 60 % быстрее на 0,3 с.
    // Быстрее 6,5 с не выходит никакими коэффициентами: ход упирается в предел тяги
    // (0,4 м/с вниз), а не в регулятор. Ускорить можно только пределом maxAuthority.
    // Значения задаются в Awake (НастройкаМарлина), а не в сцене: сцена хранила старые.
    public Pid depthPid = new Pid { kp = 3f, ki = 0.25f, kd = 3f, integralClamp = 4f, антиНасыщение = true };

    public enum ИсточникГлубины { Датчик, Истина }
    public enum ИсточникСноса { ДоплеровскийЛаг, Истина }

    [Header("Обратная связь по глубине")]
    [Tooltip("Датчик — показание датчика давления (RovSystems.depth_m), как у реального аппарата. " +
             "Истина — точная глубина из движка (идеальный датчик), только для сравнения.")]
    public ИсточникГлубины источникГлубины = ИсточникГлубины.Датчик;
    [Tooltip("Постоянная времени T комплементарного фильтра, с. Меньше — оценка ближе к датчику " +
             "давления (больше его шума в команде); больше — дольше опирается на акселерометр " +
             "(медленнее снимает его смещение). 2–5 с — типично (ArduPilot ~3 с).")]
    public float ПостояннаяВремениОценки_с = 3f;

    [Header("Модель акселерометра (вертикальный канал)")]
    [Tooltip("Смещение нуля акселерометра, м/с². Фильтр оценивает и вычитает его сам (b̂).")]
    public float СмещениеАкселерометра = 0.02f;
    [Tooltip("СКО шума акселерометра, м/с² (MEMS-датчик: 0.01–0.05)")]
    public float ШумАкселерометраСКО = 0.03f;

    [Header("Гашение сноса")]
    [Tooltip("ДоплеровскийЛаг — скорость над дном от DVL (RovSpeedSensor), как у реального аппарата: " +
             "без захвата дна снос гасить нечем, и аппарат дрейфует. Истина — скорость из движка, только для сравнения.")]
    public ИсточникСноса источникСноса = ИсточникСноса.ДоплеровскийЛаг;
    [Tooltip("Измерение лага старше этого, с, считается потерянным (лаг молчит — тормозить нечем).")]
    public float УстареваниеЛага_с = 0.6f;
    [Tooltip("Коэффициент торможения ПРОДОЛЬНОЙ скорости. Меньше = допускает лёгкий снос/покачивание.")]
    public float surgeBrakeGain = 0.8f;
    [Tooltip("Коэффициент торможения БОКОВОЙ скорости (лаг). Без него течение под углом к курсу " +
             "сносит аппарат вбок, и парировать это нечем — продольная тяга тут не помогает.")]
    // Команда — доля тяги оси, а лагом «Марлин» тянет 56 Н против 125 Н вперёд. При равных
    // коэффициентах вбок тормозил бы вдвое слабее: в течении 0,25 м/с оставался снос 0,1 м/с
    // против 0,05 м/с по курсу. 1,8 = 0,8·125/56 — та же сила на 1 м/с сноса, что по курсу.
    public float swayBrakeGain = 1.8f;

    [Header("Живое удержание (зона, а не точка)")]
    [Tooltip("Мёртвая зона по ГЛУБИНЕ, м. В пределах ±этого автопилот не давит на вертикаль — " +
             "аппарат свободно покачивается в узком слое, как настоящий ROV, а не висит намертво. " +
             "0 — жёсткое удержание в точку (выглядит неживо, «как будто гравитацию выключили»). " +
             "ВАЖНО: зона не должна быть шире миллиметров-сантиметра — внутри неё И-звено ПИД " +
             "не видит ошибку и не может скомпенсировать постоянную плавучесть, поэтому большая " +
             "зона = аппарат всплывает к её верхней кромке и «сводится наверх». " +
             "0.002 = ±2 мм: держит плотно, лёгкое покачивание в вихрях остаётся.")]
    public float depthDeadband_m = 0.002f;
    [Tooltip("Мёртвая зона по СНОСУ, м/с: ниже этой скорости автопилот не тормозит горизонталь. " +
             "Даёт аппарату лениво дрейфовать в вихрях, парируя только заметный снос. " +
             "0 — гасит любое, даже мельчайшее движение.")]
    public float driftDeadband_mps = 0.008f;

    [Header("Выход на режим при включении")]
    [Tooltip("За сколько секунд автопилот выходит на полную власть после нажатия кнопки. " +
             "0 — сразу (рывок). Реальные движители тоже раскручиваются не мгновенно.")]
    public float времяВыходаНаРежим = 2.5f;

    [Header("Мягкость отклика (глубина/снос)")]
    [Range(0.05f, 1f)]
    [Tooltip("Максимум команды тяги (доля полной). Меньше = мягче доводит.")]
    public float maxAuthority = 0.55f;
    [Tooltip("Скорость нарастания команды. Меньше = плавнее восстановление, без рывка.")]
    public float responseSmoothing = 2.5f;

    public bool Engaged { get; private set; }

    // Удержание курса: уставка и ошибка (по ПОКАЗАНИЮ курсоуказателя), град.
    public float TargetHeading_deg => _курсУставка;
    public float HeadingError_deg { get; private set; }

    // --- Телеметрия контура регулирования (для графиков на втором мониторе) ---
    // Классическая тройка ТАУ: уставка, ошибка регулирования, управляющее воздействие.
    // Уставка глубины, м (то, что держим).
    public float TargetDepth_m => _targetDepth_m;
    // Ошибка регулирования e = уставка − факт, м. e > 0 — аппарат всплыл выше уставки.
    // «Факт» — то, что видит регулятор (отфильтрованное показание датчика), а не истина.
    public float DepthError_m { get; private set; }
    // Глубина, по которой работает регулятор (после фильтра), м — для графика
    // «истина / показание датчика / вход регулятора».
    public float ГлубинаРегулятора_m => _глубинаФильтр_m;
    // Оценка вертикальной скорости, м/с (+ = погружается) и смещения акселерометра.
    public float ВертСкоростьОценка_mps => _вертСкорость;
    public float СмещениеОценка => _смещение;
    // Управляющее воздействие u на вертикальную тягу, доля −1..1.
    public float VerticalCommand => _appliedVert;
    // Разложение выхода ПИД глубины на звенья (в тех же единицах, что и u).
    public float ВкладП => depthPid.ВкладП;
    public float ВкладИ => depthPid.ВкладИ;
    public float ВкладД => depthPid.ВкладД;

    private Rigidbody _rb;
    private float _targetDepth_m;
    private float _глубинаФильтр_m;
    private bool  _фильтрГотов;
    private float _вертСкорость, _смещение;
    private float _прошлаяVy; private bool _естьПрошлаяVy;
    private float _appliedVert, _appliedFwd, _appliedLat, _appliedYaw;
    private float _курсУставка, _курсПрошлый;
    private bool _естьКурсПрошлый;
    private float _рампа;   // 0..1, плавный ввод автопилота в работу после включения
    private int _шаговДоОценки; // после переноса аппарата: столько шагов оценка = показанию датчика

    // Аппарат мгновенно перенесли (испытательный стенд ставит его в исходную точку).
    // Фильтр «помнит» старое место: без сброса он несколько секунд считал бы прежнюю
    // глубину, а медленная поправка смещения акселерометра (масштаб T³ ≈ 27 с) сбилась
    // бы от скачка — и каждый опыт начинался бы в разных условиях. Сбрасываем как при
    // включении питания; 0,3 с ждём свежего опроса датчика давления (он 5 Гц).
    public void СброситьОценку()
    {
        _фильтрГотов = false;
        _естьПрошлаяVy = false;
        _вертСкорость = 0f; _смещение = 0f;
        _шаговДоОценки = Mathf.CeilToInt(0.3f / Time.fixedDeltaTime);
    }

    void Awake()
    {
        Instance = this;
        _rb = GetComponent<Rigidbody>();
        // Статика переживает вход в Play Mode, если отключён Domain Reload — сбрасываем явно.
        RovSystems.depthHoldActive = false;
        НастройкаМарлина();
        ЗагрузитьНастройку();
    }

    // Базовая настройка под «Марлин-350» (60 кг) — из кода, поверх значений в сцене
    // (там остались коэффициенты условного аппарата 10 кг). Как MarlinSpec для движка.
    void НастройкаМарлина()
    {
        depthPid.kp = 3f; depthPid.ki = 0.25f; depthPid.kd = 3f;
        depthPid.integralClamp = 4f; depthPid.антиНасыщение = true;
        maxAuthority = 0.55f;
        surgeBrakeGain = 0.8f; swayBrakeGain = 1.8f;
    }

    // Настройка регулятора глубины, подобранная оператором на стенде испытаний
    // (RovManeuverTests, «Настройка автопилота») и запомненная кнопкой «ЗАПОМНИТЬ».
    // Если сохранённой нет — работает НастройкаМарлина. Сохранение помечено аппаратом:
    // запомненное до «Марлина» (без метки, под 10 кг) не подхватывается.
    const string Kkp = "ap_kp", Kki = "ap_ki", Kkd = "ap_kd", Kaw = "ap_aw", Kmax = "ap_max";
    const string Kаппарат = "ap_rov", Аппарат = "marlin350";
    public static bool ЕстьСохранённаяНастройка => PlayerPrefs.HasKey(Kkp) && PlayerPrefs.GetString(Kаппарат, "") == Аппарат;

    void ЗагрузитьНастройку()
    {
        if (!ЕстьСохранённаяНастройка) return;
        depthPid.kp = PlayerPrefs.GetFloat(Kkp, depthPid.kp);
        depthPid.ki = PlayerPrefs.GetFloat(Kki, depthPid.ki);
        depthPid.kd = PlayerPrefs.GetFloat(Kkd, depthPid.kd);
        depthPid.антиНасыщение = PlayerPrefs.GetInt(Kaw, depthPid.антиНасыщение ? 1 : 0) == 1;
        maxAuthority = PlayerPrefs.GetFloat(Kmax, maxAuthority);
        Debug.Log($"[RovAutopilot] Настройка со стенда: Kp={depthPid.kp} Ki={depthPid.ki} Kd={depthPid.kd} " +
                  $"защита={(depthPid.антиНасыщение ? "вкл" : "выкл")} предел={maxAuthority}");
    }

    public void ЗапомнитьНастройку()
    {
        PlayerPrefs.SetFloat(Kkp, depthPid.kp); PlayerPrefs.SetFloat(Kki, depthPid.ki); PlayerPrefs.SetFloat(Kkd, depthPid.kd);
        PlayerPrefs.SetInt(Kaw, depthPid.антиНасыщение ? 1 : 0); PlayerPrefs.SetFloat(Kmax, maxAuthority);
        PlayerPrefs.SetString(Kаппарат, Аппарат);
        PlayerPrefs.Save();
    }

    public static void ЗабытьНастройку()
    {
        foreach (var k in new[] { Kkp, Kki, Kkd, Kaw, Kmax, Kаппарат }) PlayerPrefs.DeleteKey(k);
        PlayerPrefs.Save();
    }

    void OnDestroy() { if (Instance == this) Instance = null; }

    public void Toggle() { if (Engaged) Disengage(); else Engage(); }

    public void Engage()
    {
        Engaged = true;
        // Держим текущую глубину — ту, что ПОКАЗЫВАЕТ прибор (фильтр крутится и при
        // выключенном автопилоте, поэтому уставка берётся не с одиночного шумного отсчёта).
        ОценитьГлубину(0f);
        _targetDepth_m = _глубинаФильтр_m;
        // Публикуем режим в RovSystems — оттуда его читает UI пульта (SystemStatusDisplay).
        RovSystems.depthHoldActive   = true;
        RovSystems.depthHoldTarget_m = _targetDepth_m;
        depthPid.Reset();
        _рампа = 0f;                        // власть автопилота нарастает с нуля
        _appliedVert = DroneInput.vertical; // подхватываем текущее положение рычагов
        _appliedFwd = DroneInput.forward;
        _appliedLat = DroneInput.lateral;
        _appliedYaw = DroneInput.yaw;
        _курсУставка = RovSystems.heading_deg;   // держим тот курс, что ПОКАЗЫВАЕТ прибор
        _естьКурсПрошлый = false;

        Debug.Log($"[RovAutopilot] ВКЛ. Выравниваю горизонт (тангаж={NormalizeAngle(transform.eulerAngles.x):F1}°, " +
                  $"крен={NormalizeAngle(transform.eulerAngles.z):F1}°), держу курс={_курсУставка:F1}° ({(держатьКурс ? "вкл" : "выкл")}), держим глубину={_targetDepth_m:F2} м ({источникГлубины})");
    }

    // Продолжение сохранённой миссии: включить удержание на СОХРАНЁННОЙ глубине,
    // а не на текущем показании (фильтр глубины после загрузки ещё не установился).
    public void ВосстановитьУдержание(float глубина_м)
    {
        Engage();
        _targetDepth_m = глубина_м;
        RovSystems.depthHoldTarget_m = глубина_м;
    }

    // Новая уставка глубины без перезапуска регулятора (ступенчатое воздействие
    // в испытаниях: переходная характеристика контура глубины).
    public void ЗадатьГлубину(float глубина_м)
    {
        _targetDepth_m = глубина_м;
        RovSystems.depthHoldTarget_m = глубина_м;
    }

    public void Disengage()
    {
        Engaged = false;
        RovSystems.depthHoldActive = false;
        DepthError_m = 0f;
        DroneInput.lateral = 0f;
        DroneInput.forward = 0f;
        DroneInput.vertical = 0f;
        DroneInput.yaw = 0f;
    }

    void FixedUpdate()
    {
        float dt = Time.fixedDeltaTime;
        ОценитьГлубину(dt);   // всегда: к моменту включения оценка уже установилась
        if (!Engaged) return;

        // Плавный ввод в работу. SmoothStep, а не линейный рост: начало и конец
        // разгона получаются мягкими, без ступеньки в момент выхода на полную власть.
        if (времяВыходаНаРежим > 0.01f)
            _рампа = Mathf.Clamp01(_рампа + dt / времяВыходаНаРежим);
        else
            _рампа = 1f;
        float k = Mathf.SmoothStep(0f, 1f, _рампа);

        // --- Выравнивание крена И тангажа прямым моментом (курс не трогаем) ---
        // Cross(up, worldUp): вектор коррекции наклона (|.| = sin наклона), не
        // содержит рыскания. Раскладываем его на две оси корпуса:
        //   вдоль носа (forward) -> крен (заваленный вбок горизонт),
        //   вдоль правого борта (right) -> тангаж (нос вверх/вниз, верт. плоскость),
        // и рулим каждую своим коэффициентом.
        Vector3 axisWorld = Vector3.Cross(transform.up, Vector3.up);
        float rollComp  = Vector3.Dot(axisWorld, transform.forward);
        float pitchComp = Vector3.Dot(axisWorld, transform.right);
        Vector3 levelTorque = transform.forward * (rollComp  * rollStrength)
                            + transform.right   * (pitchComp * pitchStrength);

        // Демпфируем только скорость наклона (тангаж/крен), убрав из угловой
        // скорости вертикальную (рыскание) составляющую — иначе гасили бы поворот.
        Vector3 angVel = _rb.angularVelocity;
        Vector3 tiltRate = angVel - Vector3.Project(angVel, Vector3.up);
        levelTorque -= tiltRate * levelDamping;
        _rb.AddTorque(levelTorque * k, ForceMode.Acceleration);

        // --- Глубина -> _targetDepth_m (ПИД) ---
        // Ошибку для ПИД считаем в «вертикальных» знаках (+ = нужно вверх): аппарат
        // глубже уставки → ошибка > 0 → тяга вверх. Глубина — по прибору (см. шапку).
        float yError = _глубинаФильтр_m - _targetDepth_m;
        // В телеметрию пишем ошибку в терминах глубины (уставка − факт) без мёртвой
        // зоны — чтобы на графике было видно живое покачивание около уставки.
        DepthError_m = -yError;
        // В ПИД подаём ошибку с мёртвой зоной: в пределах ±depthDeadband_m аппарату
        // разрешено свободно покачиваться в вихрях, ПИД молчит. Держим слой, не точку.
        float yErrorCtl = ApplyDeadband(yError, depthDeadband_m);
        // Д-звено: d(yError)/dt = dĥ/dt = v̂ (уставка постоянна).
        float vertCmd = Mathf.Clamp(depthPid.Update(yErrorCtl, _вертСкорость, dt, maxAuthority), -maxAuthority, maxAuthority) * k;

        // --- Гашение сноса по обеим горизонтальным осям ---
        // Течение почти никогда не идёт точно вдоль курса, поэтому гасить только
        // продольную составляющую недостаточно: боковая уводит аппарат вбок.
        // Мёртвая зона driftDeadband_mps: мелкий снос от вихрей не трогаем (аппарат
        // лениво дрейфует), парируем лишь заметный уход — это и есть «дрейф с ПИД».
        // Скорость над дном — от доплеровского лага (по прибору, а не из движка).
        // Нет захвата дна или лаг давно молчит — гасить снос нечем: команды ноль,
        // аппарат дрейфует с течением, как реальный ROV без DVL.
        float fwdCmd = 0f, latCmd = 0f;
        if (СкоростьНадДном(out float surgeVel, out float swayVel))
        {
            fwdCmd = Mathf.Clamp(-surgeBrakeGain * ApplyDeadband(surgeVel, driftDeadband_mps), -maxAuthority, maxAuthority) * k;
            latCmd = Mathf.Clamp(-swayBrakeGain  * ApplyDeadband(swayVel,  driftDeadband_mps), -maxAuthority, maxAuthority) * k;
        }

        // --- Курс -> _курсУставка (ПД по показанию курсоуказателя) ---
        // Ошибка — кратчайший угол до уставки (−180…180). Д-звено — скорость поворота по
        // тому же прибору (его выход сглажен фильтром: на коротких интервалах это гироскоп).
        float курс = RovSystems.heading_deg;
        float скоростьКурса = _естьКурсПрошлый && dt > 0f ? Mathf.DeltaAngle(_курсПрошлый, курс) / dt : 0f;
        _курсПрошлый = курс; _естьКурсПрошлый = true;
        float ошибкаКурса = Mathf.DeltaAngle(курс, _курсУставка);
        HeadingError_deg = ошибкаКурса;
        float yawCmd = 0f;
        if (держатьКурс)
            yawCmd = Mathf.Clamp(курсKp * ApplyDeadband(ошибкаКурса, курсМёртваяЗона_град) - курсKd * скоростьКурса,
                                 -курсПредел, курсПредел) * k;

        // --- Плавное подведение команд тяги ---
        float s = 1f - Mathf.Exp(-responseSmoothing * dt);
        _appliedVert = Mathf.Lerp(_appliedVert, vertCmd, s);
        _appliedFwd = Mathf.Lerp(_appliedFwd, fwdCmd, s);
        _appliedLat = Mathf.Lerp(_appliedLat, latCmd, s);
        _appliedYaw = Mathf.Lerp(_appliedYaw, yawCmd, s);

        DroneInput.vertical = _appliedVert;
        DroneInput.forward = _appliedFwd;
        DroneInput.lateral = _appliedLat;
        DroneInput.yaw = _appliedYaw;
    }

    // Есть ли снос гасить по лагу (для HUD/телеметрии): false — нет захвата дна.
    public bool СносГасится { get; private set; }

    // Продольная и боковая скорость над дном в осях аппарата для гашения сноса.
    bool СкоростьНадДном(out float продольная, out float боковая)
    {
        продольная = боковая = 0f;
        var лаг = RovSpeedSensor.Instance;
        if (источникСноса == ИсточникСноса.Истина)
        {
            // Режим сравнения на графике: идеальный прибор (скорость из движка).
            продольная = Vector3.Dot(_rb.linearVelocity, transform.forward);
            боковая    = Vector3.Dot(_rb.linearVelocity, transform.right);
            return СносГасится = true;
        }
        if (лаг == null || !лаг.isActiveAndEnabled)
        {
            // Лаг не установлен (серийный «Марлин-350»): скорость над дном мерить нечем,
            // снос не гасится — автопилот держит только курс и глубину, как в паспорте.
            if (СносГасится && Engaged) Debug.Log("[RovAutopilot] Доплеровского лага нет — снос не гашу, держу курс и глубину");
            return СносГасится = false;
        }
        bool есть = лаг.ЗахватДна && Time.time - лаг.ВремяИзмерения <= УстареваниеЛага_с;
        if (есть != СносГасится && Engaged)
            Debug.Log(есть ? "[RovAutopilot] Лаг захватил дно — гашу снос по DVL"
                           : "[RovAutopilot] Лаг потерял дно — снос гасить нечем, аппарат дрейфует");
        СносГасится = есть;
        if (!есть) return false;
        Vector3 v = лаг.СкоростьНадДном;   // оси аппарата: x вправо, z вперёд
        продольная = v.z; боковая = v.x;
        return true;
    }

    // Оценка глубины ĥ и вертикальной скорости v̂ для регулятора (см. шапку файла).
    // Показание датчика давления берётся из RovSystems.depth_m (пишет RovDepthSensor;
    // без датчика там истина). Автопилот исполняется раньше датчика (порядок −50
    // против 50), поэтому видит отсчёт прошлого шага — задержка на такт, как у
    // реального контура. dt = 0 — только инициализация (при включении).
    void ОценитьГлубину(float dt)
    {
        // Истинная вертикальная скорость (+ = вниз, т.к. глубина = −Y) и ускорение —
        // из движка: акселерометр меряет ИСТИННОЕ ускорение, портит его сам прибор.
        float vy = _rb.linearVelocity.y;
        float aИстина = (_естьПрошлаяVy && dt > 0f) ? -(vy - _прошлаяVy) / dt : 0f;
        if (dt > 0f) { _прошлаяVy = vy; _естьПрошлаяVy = true; }

        if (источникГлубины == ИсточникГлубины.Истина)
        {
            _глубинаФильтр_m = RovSystems.depthTrue_m;
            _вертСкорость = -vy;
            _смещение = 0f;
            _фильтрГотов = true;
            return;
        }

        float h = RovSystems.depth_m;
        if (_шаговДоОценки > 0) { _шаговДоОценки--; _фильтрГотов = false; }
        if (!_фильтрГотов || !RovSystems.telemetryValid)
        {
            _глубинаФильтр_m = h;
            _вертСкорость = 0f;
            _смещение = 0f;
            _фильтрГотов = RovSystems.telemetryValid;
            return;
        }
        if (dt <= 0f) return;

        // Показание акселерометра: истина + смещение нуля + гауссов шум.
        float aИзм = aИстина + СмещениеАкселерометра + ГауссовШум() * ШумАкселерометраСКО;

        float T  = Mathf.Max(0.1f, ПостояннаяВремениОценки_с);
        float k1 = 3f / T, k2 = 3f / (T * T), k3 = 1f / (T * T * T);

        float невязка = h - _глубинаФильтр_m;
        _смещение       += k3 * невязка * dt;
        _вертСкорость   += (aИзм + _смещение + k2 * невязка) * dt;
        _глубинаФильтр_m += (_вертСкорость + k1 * невязка) * dt;
    }

    // Гауссов шум (Бокс—Мюллер), σ = 1.
    static float ГауссовШум()
    {
        float u1 = Mathf.Max(1e-6f, Random.value);
        float u2 = Random.value;
        return Mathf.Sqrt(-2f * Mathf.Log(u1)) * Mathf.Cos(2f * Mathf.PI * u2);
    }

    static float NormalizeAngle(float a)
    {
        a %= 360f;
        if (a > 180f) a -= 360f;
        return a;
    }

    // Мёртвая зона: в пределах ±band возвращает 0, за ней — плавно растущее от нуля
    // значение (без ступеньки на границе, иначе движители «стучали» бы туда-сюда на
    // самой кромке). Благодаря ей автопилот держит НЕ точку, а узкую зону: аппарат
    // свободно покачивается в вихрях внутри неё и парирует лишь заметный уход.
    static float ApplyDeadband(float x, float band)
    {
        if (band <= 0f) return x;
        if (Mathf.Abs(x) <= band) return 0f;
        return x - Mathf.Sign(x) * band;
    }
