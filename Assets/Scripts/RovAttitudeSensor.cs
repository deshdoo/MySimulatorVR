// =============================================================================
// RovAttitudeSensor.cs
// -----------------------------------------------------------------------------
// Датчик тангажа и крена НПА (инклинометр), смоделированный как реальный
// ТРЁХОСНЫЙ АКСЕЛЕРОМЕТР, а не чтение углов Эйлера из движка.
//
// ГЛАВНАЯ ИДЕЯ. Акселерометр НЕ меряет угол. Он меряет ВЕКТОР КАЖУЩЕГОСЯ
// УСКОРЕНИЯ (удельную силу) — то, с какой силой и в какую сторону «прижимает»
// пробную массу внутри прибора. В покое единственная такая сила — реакция на
// гравитацию: прибор чувствует, что его тянет «вниз» с ускорением g. По тому,
// КУДА в осях прибора направлен этот вектор, и вычисляют наклон:
//
//        тангаж = atan2(a_прод, a_верт),   крен = atan2(a_борт, a_верт)
//
// (a_прод/a_борт/a_верт — продольная/бортовая/вертикальная проекции вектора
// удельной силы в осях аппарата). Если аппарат стоит ровно, вектор смотрит
// строго вниз по корпусу → углы 0. Наклонили — вектор «завалился» вбок → углы
// выросли. Это и есть измерение наклона по гравитации.
//
// В ЧЁМ ПОДВОХ (аналог дрейфа у курса). Акселерометр НЕ РАЗЛИЧАЕТ гравитацию и
// собственное ускорение аппарата — для него это одна и та же удельная сила
// (принцип эквивалентности). Когда аппарат РАЗГОНЯЕТСЯ, к вектору гравитации
// добавляется реакция на линейное ускорение, и вектор «наклоняется», хотя
// аппарат по-настоящему не наклонился. Прибор принимает разгон за наклон:
//
//        Δугол ≈ atan(a_линейное / g)
//
// Разгон вперёд 1 м/с² даёт ложный тангаж ≈ atan(1/9.81) ≈ 5.8°. Этот эффект
// НЕЛЬЗЯ изобразить простым шумом — он появляется только при манёврах и зависит
// от ускорения. Именно он делает датчик наклона по акселерометру «наивным»: в
// реальных ИНС его лечат сведением с гироскопом (комплементарный фильтр, как у
// курса) — здесь мы это НЕ делаем сознательно, чтобы эффект был виден на графике
// «истина vs показание» и о нём было что рассказать на защите.
//
// Кроме этого — обычные погрешности прибора: смещение нуля (bias), шум,
// квантование (АЦП), частота опроса и СГЛАЖИВАНИЕ. Акселерометр очень шумный,
// поэтому его показания всегда пропускают через фильтр нижних частот; фильтр
// давит шум, но добавляет ЗАПАЗДЫВАНИЕ — наклон «догоняет» реальность не мгновенно.
//
// Три величины для наглядного графика (тангаж и крен раздельно):
//   • pitchTrue_deg / rollTrue_deg — истина (движок),
//   • pitch_deg / roll_deg         — показание прибора (шум + ложный наклон от
//                                     ускорения + запаздывание фильтра).
// На графике во время разгона показание «клюёт» в сторону, а истина — нет: вот
// он, эффект неразличимости гравитации и ускорения, своими глазами.
//
// DefaultExecutionOrder(50): считается ПОСЛЕ RovSystemsSimulator — сначала
// движок кладёт истинные углы, потом прибор их измеряет. Без этого компонента
// симулятор оставляет pitch_deg/roll_deg = истине (обратная совместимость).
//
// Настройка: повесить на объект НПА (там же, где RovSystemsSimulator и Rigidbody).
// =============================================================================

using UnityEngine;

[DisallowMultipleComponent]
[DefaultExecutionOrder(50)]
public class RovAttitudeSensor : MonoBehaviour
{
    [Header("Ускорение среды")]
    [Tooltip("Ускорение свободного падения, м/с². Задаёт масштаб «наклон от ускорения»: " +
             "чем меньше g, тем сильнее разгон подделывает наклон (Δ ≈ atan(a/g)).")]
    public float g = 9.81f;

    [Header("Погрешности прибора")]
    [Tooltip("Смещение нуля по тангажу, град. Постоянный сдвиг из-за неидеальной установки/калибровки прибора.")]
    public float СмещениеТангажа_град = 0.2f;
    [Tooltip("Смещение нуля по крену, град.")]
    public float СмещениеКрена_град = 0.2f;
    [Tooltip("СКО шума наклона, град (дрожание показаний угла). Акселерометр шумный — до фильтра дрожь заметная.")]
    public float ШумСКО_град = 1.5f;
    [Tooltip("Разрешение АЦП по углу, град: показание округляется до кратного этому шагу. 0 — без округления.")]
    public float Разрешение_град = 0.1f;

    [Header("Ложный наклон от ускорения (главный эффект)")]
    [Tooltip("Учитывать ли собственное линейное ускорение аппарата: разгон добавляет " +
             "кажущийся наклон Δ≈atan(a/g). Выкл — идеальный инклинометр без этого эффекта " +
             "(для сравнения на графике).")]
    public bool УчитыватьУскорение = true;
    [Tooltip("Доля учёта ускорения, 0..1 (реализм эффекта). 1 — полностью физично; " +
             "меньше — приглушить, если качает слишком сильно.")]
    [Range(0f, 1f)] public float ДоляУскорения = 1f;

    [Header("Сглаживание (фильтр нижних частот)")]
    [Tooltip("Постоянная времени сглаживания, с. Давит шум акселерометра, но добавляет " +
             "запаздывание: показание догоняет истину примерно за это время. 0 — без сглаживания.")]
    public float ПостояннаяСглаживания_с = 0.25f;

    [Header("Опрос")]
    [Tooltip("Частота опроса датчика, Гц. Между опросами показание удерживается. 0 — каждый FixedUpdate.")]
    public float ЧастотаОпроса_Гц = 20f;

    private Rigidbody _rb;
    private Vector3 _прошлаяСкорость;     // для оценки линейного ускорения (мир)
    private bool  _естьПрошлаяСкорость;
    private float _следующийОпрос_с;
    private float _показаниеТангажа_град; // держится между опросами
    private float _показаниеКрена_град;
    private bool  _иниц;

    void Awake()
    {
        _rb = GetComponent<Rigidbody>();
        if (_rb == null) _rb = GetComponentInParent<Rigidbody>();
    }

    void FixedUpdate()
    {
        float dt = Time.fixedDeltaTime;
        if (dt <= 0f) return;

        float тангажИстина = RovSystems.pitchTrue_deg;
        float кренИстина   = RovSystems.rollTrue_deg;

        // Инициализация: прибор стартует «на истине», без наката шума.
        if (!_иниц)
        {
            _показаниеТангажа_град = тангажИстина;
            _показаниеКрена_град   = кренИстина;
            _иниц = true;
            RovSystems.pitch_deg = _показаниеТангажа_град;
            RovSystems.roll_deg  = _показаниеКрена_град;
            if (_rb != null) { _прошлаяСкорость = _rb.linearVelocity; _естьПрошлаяСкорость = true; }
            return;
        }

        // 1. ЛИНЕЙНОЕ УСКОРЕНИЕ аппарата (мир) — из разности скоростей за шаг.
        //    Именно оно подделывает наклон: акселерометр не отличает его от гравитации.
        Vector3 aМир = Vector3.zero;
        if (_rb != null)
        {
            Vector3 v = _rb.linearVelocity;
            if (_естьПрошлаяСкорость) aМир = (v - _прошлаяСкорость) / dt;
            _прошлаяСкорость = v;
            _естьПрошлаяСкорость = true;
        }

        // 2. ЛОЖНЫЙ НАКЛОН ОТ УСКОРЕНИЯ. Считаем угловую ошибку как разность двух
        //    декомпозиций ОДНИМ методом (atan2): вектор удельной силы с ускорением
        //    против вектора чистой гравитации. Одинаковый метод → расхождение самой
        //    декомпозиции сокращается, остаётся ЧИСТО эффект ускорения. Прибавляем
        //    его к истинным углам Эйлера — показание согласовано с истиной в покое.
        float Δтангаж = 0f, Δкрен = 0f;
        if (УчитыватьУскорение && ДоляУскорения > 0.0001f && g > 0.001f)
        {
            // Реакция на гравитацию направлена ВВЕРХ (вектор удельной силы в покое),
            // из ускорения аппарата вычитается его вклад (принцип эквивалентности).
            Vector3 гравМир = Vector3.up * g;
            Vector3 удельнаяСМир = гравМир - aМир;

            Vector3 гравТело    = transform.InverseTransformDirection(гравМир);
            Vector3 удельнаяТело = transform.InverseTransformDirection(удельнаяСМир);

            float тангажЧистый = УголТангажа(гравТело);
            float кренЧистый   = УголКрена(гравТело);
            float тангажСУскор = УголТангажа(удельнаяТело);
            float кренСУскор   = УголКрена(удельнаяТело);

            Δтангаж = Mathf.DeltaAngle(тангажЧистый, тангажСУскор) * ДоляУскорения;
            Δкрен   = Mathf.DeltaAngle(кренЧистый,   кренСУскор)   * ДоляУскорения;
        }

        // 3. Опрос не мгновенный: пересчитываем «сырое» показание не чаще частоты опроса.
        bool опрашиваем = ЧастотаОпроса_Гц <= 0f || Time.time >= _следующийОпрос_с;
        if (опрашиваем)
        {
            if (ЧастотаОпроса_Гц > 0f) _следующийОпрос_с = Time.time + 1f / ЧастотаОпроса_Гц;

            // Сырое показание = истина + ложный наклон + смещение нуля + шум.
            float тангажСырое = тангажИстина + Δтангаж + СмещениеТангажа_град + ГауссовШум() * ШумСКО_град;
            float кренСырое   = кренИстина   + Δкрен   + СмещениеКрена_град   + ГауссовШум() * ШумСКО_град;

            // 4. СГЛАЖИВАНИЕ (фильтр нижних частот): давит шум, добавляет запаздывание.
            //    α = dt/(τ+dt) — доля свежего значения. τ=0 → берём сырое как есть.
            float шагОпроса = ЧастотаОпроса_Гц > 0f ? 1f / ЧастотаОпроса_Гц : dt;
            float α = ПостояннаяСглаживания_с > 1e-4f
                    ? шагОпроса / (ПостояннаяСглаживания_с + шагОпроса)
                    : 1f;
            _показаниеТангажа_град += α * Mathf.DeltaAngle(_показаниеТангажа_град, тангажСырое);
            _показаниеКрена_град   += α * Mathf.DeltaAngle(_показаниеКрена_град,   кренСырое);

            // 5. КВАНТОВАНИЕ (АЦП): округляем до кратного разрешению.
            if (Разрешение_град > 1e-6f)
            {
                _показаниеТангажа_град = Mathf.Round(_показаниеТангажа_град / Разрешение_град) * Разрешение_град;
                _показаниеКрена_град   = Mathf.Round(_показаниеКрена_град   / Разрешение_град) * Разрешение_град;
            }
        }

        // Публикуем ПОКАЗАНИЯ — их видят приборы и графики.
        RovSystems.pitch_deg = _показаниеТангажа_град;
        RovSystems.roll_deg  = _показаниеКрена_град;
    }

    // Тангаж из вектора удельной силы в осях аппарата: наклон «нос вверх/вниз».
    // В Unity местные оси: +Z — нос, +Y — верх. Проекция вектора на плоскость
    // «нос-верх» даёт угол между ним и осью «верх».
    static float УголТангажа(Vector3 fТело)
        => Mathf.Atan2(-fТело.z, Mathf.Max(1e-4f, fТело.y)) * Mathf.Rad2Deg;

    // Крен из вектора удельной силы: наклон «борт вправо/влево» (+X — правый борт).
    static float УголКрена(Vector3 fТело)
        => Mathf.Atan2(fТело.x, Mathf.Max(1e-4f, fТело.y)) * Mathf.Rad2Deg;

    // Гауссов (нормальный) шум методом Бокса—Мюллера — как в RovDepthSensor.
    static float ГауссовШум()
    {
        float u1 = Mathf.Max(1e-6f, Random.value);
        float u2 = Random.value;
        return Mathf.Sqrt(-2f * Mathf.Log(u1)) * Mathf.Cos(2f * Mathf.PI * u2);
    }
}
