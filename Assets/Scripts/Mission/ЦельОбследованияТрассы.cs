using UnityEngine;

// Вторая цель миссии «Обследование трубопровода»: пройти вдоль трубы, чтобы осмотром была
// покрыта нужная доля трассы (MissionStats.ДоляПокрытия — ячейки по 1 м вдоль оси трубы,
// отмечаются, когда труба в поле зрения бортовой камеры на дистанции осмотра). Так обследование
// заканчивается не на «нашёл N трещин», а на проходе трассы, как в реальном отчёте инспекции:
// журнал дефектов с KP и долей осмотренной длины. Ставит MissionBootstrap.
public class ЦельОбследованияТрассы : MonoBehaviour
{
    public int ИндексЦели = 1;
    [Range(0.3f, 1f)] public float НужноеПокрытие = 0.8f;
    int _показано = -1;

    void Update()
    {
        var m = MissionManager.Instance; var st = MissionStats.Instance;
        if (m == null || st == null || !st.ЕстьТруба || ИндексЦели >= m.Цели.Count) return;
        if (!m.ЦельАктивна(ИндексЦели)) return;
        int проц = Mathf.FloorToInt(st.ДоляПокрытия * 100f);
        if (проц != _показано)
        {
            _показано = проц;
            m.УстановитьПрогресс(ИндексЦели, $"Осмотрено {проц} % трассы из {Mathf.RoundToInt(НужноеПокрытие * 100f)} %");
        }
        if (st.ДоляПокрытия >= НужноеПокрытие) m.ЗавершитьЦель(ИндексЦели);
    }
}
