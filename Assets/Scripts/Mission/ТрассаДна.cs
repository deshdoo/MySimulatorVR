using UnityEngine;

// Трасса магистрали в плане и естественный рельеф дна под ней (для ПостроительДна).
public static class ТрассаДна
{
    // Трасса в плане: начало, направление и длина (высота не важна).
    public struct Трасса
    {
        public Vector2 Начало, Ось, Поперёк;
        public float Длина;

        public Трасса(Vector3 начало, Vector3 конец)
        {
            Начало = new Vector2(начало.x, начало.z);
            Vector2 d = new Vector2(конец.x, конец.z) - Начало;
            Длина = d.magnitude;
            Ось = Длина > 1e-4f ? d / Длина : Vector2.right;
            Поперёк = new Vector2(-Ось.y, Ось.x);
        }

        public float Вдоль(Vector2 p) => Vector2.Dot(p - Начало, Ось);
        public float Поперёк_м(Vector2 p) => Vector2.Dot(p - Начало, Поперёк);
    }

    // Мир вокруг трассы — по образцу: посередине ровная илистая полоса с трубой,
    // справа, недалеко от неё, — глубокий извилистый каньон с крутыми стенками, за
    // ним — снова подъём; слева — каменистые холмы и бугры 3–8 м; вдали — пологие волны.
    // Трассу прокладывают по ровному месту между ними: у трубы только мелкая неровность,
    // крупные формы плавно затухают к ней (без резкой «полосы»).
    public static float Естественный(Трасса т, Vector2 p)
    {
        float a = т.Вдоль(p), c = т.Поперёк_м(p);
        float вдалеке = Гладко((Mathf.Abs(c) - 10f) / 20f);
        Vector2 w = p + 25f * new Vector2(Фрактал(p / 90f, 2, 61) - 0.5f, Фрактал(p / 90f, 2, 67) - 0.5f) * 2f;
        Vector2 w2 = p + 3f * new Vector2(Фрактал(p / 9f, 2, 71) - 0.5f, Фрактал(p / 9f, 2, 73) - 0.5f) * 2f;

        float h = 0.3f * (Фрактал(w / 120f, 3, 11) - 0.5f) * 2f;
        h += вдалеке * 1.2f * (Фрактал(w / 45f, 3, 23) - 0.5f) * 2f;
        h += (0.12f + 0.15f * вдалеке) * (Фрактал(w2 / 10f, 3, 37) - 0.5f) * 2f;
        h += 0.05f * (Фрактал(w2 / 3f, 2, 41) - 0.5f) * 2f;

        // Слева — холмы: «гребенчатый» шум даёт острые каменистые вершины и сёдла.
        float левее = Гладко((-c - 14f) / 18f);
        float гребни = 1f - Mathf.Abs(Фрактал(w / 38f, 3, 81) * 2f - 1f);
        h += левее * (2.5f + 6f * гребни * гребни) * Фрактал(w / 70f, 2, 83);

        // Справа — каньон: ось виляет в 22–30 м от трубы, стенки крутые, дно неровное,
        // глубина 10–15 м; за каньоном местность снова поднимается.
        float ось = 30f + 5f * Mathf.Sin(a / 35f) + 4f * (Фрактал(new Vector2(a / 25f, 1.7f), 2, 91) - 0.5f) * 2f;
        float q = Mathf.Abs(c - ось);
        float глубина = 10f + 5f * Фрактал(new Vector2(a / 30f, 5.3f), 2, 93);
        float стенка = 1f - Гладко((q - 3f - 2f * Фрактал(w2 / 6f, 2, 95)) / 7f);
        h -= глубина * стенка * стенка * (3f - 2f * стенка);
        h += 0.8f * Mathf.Exp(-(q - 11f) * (q - 11f) / 5f);                         // бровка у края
        h += Гладко((c - ось - 12f) / 25f) * (2f + 3f * Фрактал(w / 40f, 2, 97));      // подъём за каньоном
        return h;
    }

    // Насколько место каменистое (0..1): холмы слева, стенки и бровка каньона.
    public static float Каменистость(Трасса т, Vector2 p, float уклон)
    {
        float c = т.Поперёк_м(p);
        float холмы = Гладко((-c - 18f) / 15f);
        return Mathf.Clamp01(Гладко((уклон - 0.35f) / 0.4f) + холмы * 0.35f);
    }

    // Доля ила на поверхности (0..1): на 100–200 м дно в основном илистое, песок — пятнами.
    public static float Ил(Vector2 p) =>
        Mathf.Lerp(0.55f, 1f, Mathf.SmoothStep(0f, 1f, Mathf.InverseLerp(0.4f, 0.65f, Фрактал(p / 25f, 3, 53))));

    // Пятна тёмного ила на ровном (0..1).
    public static float ТёмныйИл(Vector2 p) =>
        Mathf.SmoothStep(0f, 1f, Mathf.InverseLerp(0.45f, 0.7f, Фрактал(p / 14f, 3, 57)));

    public static float Гладко(float x) { x = Mathf.Clamp01(x); return x * x * (3f - 2f * x); }

    static float Фрактал(Vector2 p, int октав, int seed)
    {
        float s = 0f, амп = 0.5f, норма = 0f, f = 1f;
        for (int o = 0; o < октав; o++)
        {
            s += Mathf.PerlinNoise(p.x * f + seed * 13.1f + o * 7.3f, p.y * f + seed * 5.7f - o * 3.9f) * амп;
            норма += амп; амп *= 0.5f; f *= 2f;
        }
        return s / норма;
    }
}
