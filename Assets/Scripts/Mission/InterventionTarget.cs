using UnityEngine;
using UnityEngine.Events;

// Точка вмешательства манипулятором: аварийный вентиль, который надо ЗАКРЫТЬ.
// Поддерживает два режима:
//
//   1) РЕЖИМ ПРОВОРОТА (РежимПроворота = true) — «настоящий» хват штурвала:
//      клешня подводится к кругу штурвала и СЖИМАЕТСЯ (RovSystems.grabberClosed),
//      после чего аппарат ДЕРЖИТСЯ за вентиль. ОБЛЁТ дрона вокруг центра руля (клешня
//      ведёт обод по дуге) проворачивает штурвал; полное закрытие
//      на УголЗакрытия (по умолчанию 30°). Пока держимся — снос аппарата гасится
//      (он «зацеплен» за вентиль). На полном закрытии течь прекращается (гаснут
//      пузыри утечки), трещины при этом НЕ трогаются.
//
//   2) СТАРЫЙ РЕЖИМ (РежимПроворота = false) — «навести кончик манипулятора и
//      удержать»: засчитывается по близости кончика к цели в течение ВремяУдержания
//      (для утечек/хомутов, где хват необязателен). Оставлен как простой fallback.
//
// В обоих режимах вентиль засчитывается только когда его цель миссии активна
// (осмотр уже завершён) — шаг нельзя проскочить. По завершении меняет вид цели
// (меш «вентиль закрыт»), гасит пузыри и закрывает цель миссии.
[DisallowMultipleComponent]
public class InterventionTarget : MonoBehaviour
{
    [Header("Условие выполнения")]
    [Tooltip("Трансформ кончика манипулятора (клешни) НПА")]
    public Transform КончикМанипулятора;
    [Tooltip("Радиус, в котором кончик манипулятора считается «на цели», м (старый режим удержания)")]
    public float РадиусРаботы = 0.5f;
    [Tooltip("Сколько секунд удерживать манипулятор на цели (старый режим удержания)")]
    public float ВремяУдержания_с = 2f;
    [Tooltip("Требовать, чтобы аппарат почти не двигался во время работы (старый режим удержания)")]
    public bool ТребоватьНеподвижность = true;
    [Tooltip("Порог скорости для «неподвижности», м/с")]
    public float ПорогСкорости = 0.15f;

    [Header("Хват и проворот вентиля")]
    [Tooltip("ВКЛ — настоящий хват штурвала: зажать клешню на круге и провернуть боковым движением. " +
             "ВЫКЛ — старый режим «навести кончик и удержать».")]
    public bool РежимПроворота = false;
    [Tooltip("ЦЕНТР штурвала — точка, вокруг которой всё крутится и центр зоны захвата. " +
             "Обычно пустой объект (empty), поставленный ровно в центр колеса. Пусто — сам объект вентиля.")]
    public Transform Штурвал;
    [Tooltip("ВИДИМЫЙ меш штурвала (красный круг), который реально вращается. Пусто — крутится сам Штурвал. " +
             "Кручу через RotateAround вокруг центра (Штурвал), поэтому кривой пивот меша не важен — " +
             "колесо крутится на месте, а не уходит по орбите.")]
    public Transform МешШтурвала;
    [Tooltip("Ось проворота штурвала в МИРОВЫХ осях (направление штока). Вертикальный шток = (0,1,0). " +
             "Кручение идёт вокруг этой оси, поэтому вентиль не заваливается набок, как бы ни были " +
             "повёрнуты локальные оси модели.")]
    public Vector3 ОсьПроворота = Vector3.up;
    [Tooltip("Полный угол закрытия вентиля, град — на столько провернуть штурвал.")]
    public float УголЗакрытия = 30f;
    [Tooltip("Скорость облёта: ГРАД/СЕК проворота штурвала при полном отклонении рычага Turn (lever 3). " +
             "Схватил → двигаешь Turn влево/вправо → дрон орбитит вокруг руля (поворот+смещение) и крутит " +
             "вентиль с этой скоростью. 60 = закрыть 30° за 0.5 с. Знак минус — сменить сторону закрытия.")]
    public float СкоростьОблёта = 60f;
    [Header("Хитбокс захвата — только ОБОД (кольцо), не центр/спицы")]
    [Tooltip("Радиус кольца обода от центра штурвала, м. 0 = вычислить автоматически по габаритам штурвала.")]
    public float РадиусОбода = 0f;
    [Tooltip("Толщина зоны захвата вокруг кольца обода, м — насколько близко к линии обода должен быть " +
             "кончик клешни, чтобы зацепиться. Центр и спицы в зону не попадают.")]
    public float РадиусЗахвата = 0.15f;
    [Tooltip("ПРОСТОЙ хитбокс (рекомендуется): зона захвата = СФЕРА вокруг центра штурвала радиусом " +
             "РадиусОбода+РадиусЗахвата. НЕ зависит от ОсьПроворота и плоскости колеса — клешня где угодно " +
             "рядом с колесом цепляется. Настраивать надо только центр (Штурвал) и один радиус. " +
             "ВЫКЛ — точный тор только по ободу (сложнее: нужны верные ось и радиус).")]
    public bool ПростойХитбокс = true;
    [Tooltip("Отключить столкновение с вентилем ТОЛЬКО у клешни (чтобы она легла на штурвал, не отскакивая). " +
             "Корпус дрона сквозь вентиль при этом НЕ проходит.")]
    public bool ОтключитьСтолкновениеСНПА = true;
    [Tooltip("Корень манипулятора (клешни) — только ЕГО коллайдеры перестают толкать вентиль. " +
             "Пусто — найдётся по кончику клешни (по имени grip/claw/jaw/клешн/захват).")]
    public Transform КореньКлешни;
    [Tooltip("Печатать в консоль, что мешает захвату (дистанция, сжата ли клешня, активна ли цель).")]
    public bool Диагностика = true;

    [Header("Удержание аппарата на вентиле (снос → минимум)")]
    [Tooltip("Корпус НПА (Rigidbody). Пусто — берётся объект с RovController.")]
    public Rigidbody КорпусНПА;
    [Tooltip("Гашение сноса, пока держимся за вентиль (демпфирование скорости). Больше = спокойнее орбитить, " +
             "течение не крутит руль само. Клешня свободно ходит вокруг руля — жёсткой привязки к точке нет.")]
    public float ГашениеСноса = 6f;
    [Tooltip("После закрытия вентиля клешня РАСКРЫВАЕТСЯ и аппарат отходит от руля с этой скоростью, м/с. " +
             "0 — не толкать (просто раскрыть клешню).")]
    public float СкоростьОтхода = 0.6f;

    [Header("Подсветка (зацеп клешни)")]
    [Tooltip("Меш, который подсвечивается, когда клешня в зоне захвата. ПУСТО — подсвечиваются ВСЕ " +
             "рендереры вентиля (надёжнее: не надо угадывать нужный суб-меш).")]
    public Renderer Подсветка;
    [Tooltip("Цвет подсветки — мягкий зелёный, «сюда можно зацепиться / держим».")]
    public Color ЦветПодсветки = new Color(0.6f, 1f, 0.6f);
    [Range(0f, 6f), Tooltip("Яркость эмиссии подсветки. 0.15-0.25 — мягкое свечение, как у рычагов.")]
    public float ЯркостьПодсветки = 0.15f;

    [Header("Реакция на выполнение")]
    [Tooltip("Показать после выполнения (напр. меш «задвижка закрыта»)")]
    public GameObject ВключитьПриВыполнении;
    [Tooltip("Скрыть после выполнения (напр. партиклы утечки, красная метка)")]
    public GameObject ВыключитьПриВыполнении;
    [Tooltip("Погасить ВСЕ утечки (пузыри) при выполнении — закрыли вентиль, течь прекратилась. " +
             "Трещины (осмотр) при этом НЕ трогаются.")]
    public bool ГаситьУтечкиПриВыполнении = true;
    [Tooltip("Доп. реакция — звук, анимация (вешай в инспекторе)")]
    public UnityEvent ПриВыполнении;

    [Header("Связь с миссией")]
    [Tooltip("Индекс цели вмешательства в MissionManager. −1 = текущая активная.")]
    public int ИндексЦели = -1;

    public bool Выполнено { get; private set; }
    private float _выдержка;

    // --- проворот/хват ---
    private bool _захвачен;
    private float _угол;              // текущий проворот штурвала, 0..УголЗакрытия
    private Vector3 _дронОтносЦентра;   // позиция дрона в кадре колеса на момент зацепа (жёсткая привязка)
    private Quaternion _дронОриентация; // ориентация дрона в кадре колеса на момент зацепа
    private bool _былКинематик;         // isKinematic дрона до хвата — вернуть при отпускании
    private float _радиусОбода;       // радиус кольца обода (auto или из поля)
    private float _приложенныйУгол;   // уже применённый к мешу угол — крутим инкрементами (RotateAround)
    private Rigidbody _rov;
    private Collider[] _колВентиля;   // коллайдеры вентиля — для гашения столкновений клешни

    // --- подсветка (может быть несколько мешей) ---
    private Material[] _mats;
    private bool[] _былаЭмиссия;
    private Color[] _исходнаяЭмиссия;

    // Start, а не Awake: MissionBootstrap добавляет этот компонент через AddComponent и
    // настраивает поля (РежимПроворота, Штурвал, КорпусНПА…) уже ПОСЛЕ Awake. К Start
    // все ссылки проставлены — поэтому и базу штурвала, и гашение столкновений берём тут.
    void Start()
    {
        if (Штурвал == null) Штурвал = transform;
        if (МешШтурвала == null) МешШтурвала = Штурвал;   // если видимый меш не задан — крутим сам центр
        _радиусОбода = РадиусОбода > 0.001f ? РадиусОбода : АвтоРадиусОбода();

        _rov = КорпусНПА != null ? КорпусНПА : НайтиКорпусНПА();

        // Коллайдеры вентиля (не-триггеры) — для гашения столкновений с клешнёй.
        var все = GetComponentsInChildren<Collider>(true);
        var список = new System.Collections.Generic.List<Collider>();
        foreach (var c in все) if (c != null && !c.isTrigger) список.Add(c);
        _колВентиля = список.ToArray();

        // Столкновение с вентилем гасим ТОЛЬКО у клешни — она ложится на обод без отскока,
        // а корпус дрона в вентиль по-прежнему упирается (сквозь не проходит).
        if (ОтключитьСтолкновениеСНПА && _rov != null && РежимПроворота)
            ОтключитьСтолкновения(_rov);

        // Что подсвечивать (по приоритету): явный рендерер Подсветка → он; иначе рендереры
        // видимого меша штурвала; иначе — рендереры всего вентиля. КАЖДЫЙ вариант проверяем
        // на «есть ли вообще рендереры» — иначе, если МешШтурвала оказался пустым объектом
        // (центром), красить было бы нечего и подсветки не видно.
        Renderer[] ренды = null;
        if (Подсветка != null) ренды = new[] { Подсветка };
        if ((ренды == null || ренды.Length == 0) && МешШтурвала != null)
            ренды = МешШтурвала.GetComponentsInChildren<Renderer>(true);
        if (ренды == null || ренды.Length == 0)
            ренды = GetComponentsInChildren<Renderer>(true);
        var mats = new System.Collections.Generic.List<Material>();
        var было = new System.Collections.Generic.List<bool>();
        var исх  = new System.Collections.Generic.List<Color>();
        foreach (var r in ренды)
        {
            if (r == null) continue;
            var m = r.material;
            mats.Add(m);
            было.Add(m.IsKeywordEnabled("_EMISSION"));
            исх.Add(m.HasProperty("_EmissionColor") ? m.GetColor("_EmissionColor") : Color.black);
        }
        _mats = mats.ToArray();
        _былаЭмиссия = было.ToArray();
        _исходнаяЭмиссия = исх.ToArray();

        if (_mats.Length == 0)
            Debug.LogWarning($"[Вентиль:{name}] ПОДСВЕТКА: не найдено ни одного меша для подсветки. " +
                             "Задай поле МешШтурвала (красный круг) или Подсветка — иначе гореть нечему.");
        else
            Debug.Log($"[Вентиль:{name}] Подсветка готова: {_mats.Length} материал(ов).");
    }

    // Старый режим удержания — по кадрам (без физики).
    void Update()
    {
        if (РежимПроворота || Выполнено || КончикМанипулятора == null) return;

        if (!ЦельАктивна())
        {
            _выдержка = 0f;
            Подсветить(false);
            return;
        }

        bool наЦели = Vector3.Distance(КончикМанипулятора.position, transform.position) <= РадиусРаботы;
        bool стабилен = !ТребоватьНеподвижность || RovSystems.speed_mps <= ПорогСкорости;

        Подсветить(наЦели);

        if (наЦели && стабилен)
        {
            _выдержка += Time.deltaTime;
            if (_выдержка >= ВремяУдержания_с) Выполнить();
        }
        else _выдержка = 0f;
    }

    // Режим проворота — в физике (гасим снос силами на Rigidbody).
    void FixedUpdate()
    {
        if (!РежимПроворота || Выполнено) return;

        if (КончикМанипулятора == null || _rov == null)
        {
            Диаг($"нет ссылки: КончикКлешни={(КончикМанипулятора != null)}, КорпусНПА={(_rov != null)} — хват невозможен");
            Отпустить();
            return;
        }

        if (!ЦельАктивна())
        {
            Диаг("цель вентиля ещё не активна — сначала заверши осмотр трубы");
            Отпустить();
            return;
        }

        // Зацеп только за ОБОД (кольцо руля): кончик клешни у линии обода (тор-хитбокс),
        // не за центр/спицы. Либо уже держим — тогда не срываемся сразу, если чуть отошли,
        // пока клешня сжата.
        bool вЗоне = КончикНаОбоде(КончикМанипулятора.position);
        bool держим = RovSystems.grabberClosed && (_захвачен || вЗоне);

        if (держим && !_захвачен) { Схватить(); Диаг("СХВАЧЕНО за обод руля"); }
        else if (!держим && _захвачен) { Отпустить(); Диаг("отпущено"); }
        else if (!_захвачен && !вЗоне)
            Диаг("клешня не на ободе руля — подведи кончик к оранжевому кольцу (не к центру)");
        else if (!_захвачен && !RovSystems.grabberClosed)
            Диаг("клешня на ободе — СОЖМИ КЛЕШНЮ (Grab), чтобы схватить");

        Подсветить(вЗоне || _захвачен);

        if (_захвачен) ПроворотИУдержание();
    }

    // Печатает диагностику не чаще, чем при СМЕНЕ сообщения (чтобы не заспамить консоль).
    private string _последнДиаг;
    void Диаг(string сообщение)
    {
        if (!Диагностика || сообщение == _последнДиаг) return;
        _последнДиаг = сообщение;
        Debug.Log($"[Вентиль:{gameObject.name}] {сообщение}");
    }

    Vector3 ТочкаШтурвала() => Штурвал != null ? Штурвал.position : transform.position;
    Vector3 ОсьМир() => ОсьПроворота.sqrMagnitude > 1e-6f ? ОсьПроворота.normalized : Vector3.up;

    // Радиальный вектор точки в ПЛОСКОСТИ обода (перпендикулярно оси штока), от центра руля.
    Vector3 РадиусВПлоскости(Vector3 p, out float высотаВдольОси)
    {
        Vector3 ось = ОсьМир();
        Vector3 r = p - ТочкаШтурвала();
        высотаВдольОси = Vector3.Dot(r, ось);
        return r - ось * высотаВдольОси;
    }

    // Хитбокс захвата = ТОР вокруг обода: точка близка к КОЛЬЦУ радиуса _радиусОбода
    // (а не к центру и не к спицам). Расстояние до кольца = √((ρ−R)² + h²), где ρ —
    // радиус точки в плоскости обода, h — её смещение вдоль оси. У центра ρ≈0 → далеко от
    // кольца → не зацепить; у спиц то же самое. Только сам обод попадает в зону.
    bool КончикНаОбоде(Vector3 p)
    {
        // Простой хитбокс: обычная СФЕРА вокруг центра штурвала — не зависит от оси и
        // плоскости колеса. Клешня где угодно рядом с колесом (в пределах обод+зазор) →
        // зацеп. Так настройка сводится к «центр (Штурвал) + один радиус».
        if (ПростойХитбокс)
            return Vector3.Distance(p, ТочкаШтурвала()) <= _радиусОбода + РадиусЗахвата;

        // Точный тор-хитбокс: расстояние до КОЛЬЦА обода (нужны верные ось и радиус).
        Vector3 rПерп = РадиусВПлоскости(p, out float h);
        float ρ = rПерп.magnitude;
        float доКольца = Mathf.Sqrt((ρ - _радиусОбода) * (ρ - _радиусОбода) + h * h);
        return доКольца <= РадиусЗахвата;
    }

    // Кадр колеса на угле a: поворот вокруг оси штока через центр руля.
    Quaternion КадрКолеса(float a) => Quaternion.AngleAxis(a, ОсьМир());

    void Схватить()
    {
        _захвачен = true;

        // Жёстко «привязываем» дрон к колесу: запоминаем его позу В КАДРЕ КОЛЕСА (относительно
        // центра руля, с поправкой на текущий угол). Дальше, когда угол меняется, пересчитываем
        // позу дрона из этого кадра — он орбитит вокруг центра вместе с колесом, как ручка на руле.
        Quaternion Rinv = Quaternion.Inverse(КадрКолеса(_угол));
        _дронОтносЦентра = Rinv * (_rov.position - ТочкаШтурвала());
        _дронОриентация  = Rinv * _rov.rotation;

        // Кинематик на время хвата: дрон ведём мы (MovePosition/MoveRotation), физика его не
        // толкает — не бьётся о трубу/вентиль и не трясётся. Скорости обнуляем.
        _былКинематик = _rov.isKinematic;
        _rov.linearVelocity = Vector3.zero;
        _rov.angularVelocity = Vector3.zero;
        _rov.isKinematic = true;
    }

    void Отпустить()
    {
        if (!_захвачен) return;
        _захвачен = false;
        ВернутьФизикуДрона();
        // Штурвал остаётся на достигнутом угле (вентиль не «отпружинивает» сам).
    }

    void ВернутьФизикуДрона()
    {
        if (_rov != null) _rov.isKinematic = _былКинематик;
    }

    // Мягкий отход аппарата ОТ руля после закрытия: толкаем по горизонтали прочь от центра.
    void ОтойтиОтРуля()
    {
        if (_rov == null || _rov.isKinematic || СкоростьОтхода <= 0f) return;
        Vector3 отРуля = _rov.position - ТочкаШтурвала();
        отРуля.y = 0f;   // без вертикали — просто отплыть в сторону
        Vector3 напр = отРуля.sqrMagnitude > 1e-4f ? отРуля.normalized : -_rov.transform.forward;
        _rov.linearVelocity = напр * СкоростьОтхода;
    }

    void OnDisable() { if (_захвачен) ВернутьФизикуДрона(); }

    void ПроворотИУдержание()
    {
        // Проворот ОБЛЁТОМ: нос закреплён клешнёй на ободе, а рычагом TURN (lever 3) ты
        // орбитишь весь дрон вокруг центра руля — он одновременно ПОВОРАЧИВАЕТ и СМЕЩАЕТСЯ
        // в ту же сторону (жёсткая привязка = вращение вокруг центра), и штурвал крутится с ним.
        float ввод = Mathf.Clamp(DroneInput.yaw, -1f, 1f);   // −1..1 с рычага Turn (lever 3)
        _угол = Mathf.Clamp(_угол + ввод * СкоростьОблёта * Time.fixedDeltaTime, 0f, УголЗакрытия);
        ПрименитьУгол();

        // Жёстко переставляем дрон по новому углу колеса — он «висит» на ободе и орбитит.
        Quaternion R = КадрКолеса(_угол);
        _rov.MovePosition(ТочкаШтурвала() + R * _дронОтносЦентра);
        _rov.MoveRotation(R * _дронОриентация);

        // Полное закрытие — засчитываем.
        if (_угол >= УголЗакрытия - 0.05f) Выполнить();
    }

    // Радиус кольца обода: из поля или авто — по габаритам штурвала в плоскости,
    // перпендикулярной оси (для вертикального штока это горизонтальный размах руля /2).
    float АвтоРадиусОбода()
    {
        var rend = Штурвал != null ? Штурвал.GetComponentInChildren<Renderer>() : GetComponentInChildren<Renderer>();
        if (rend == null) return 0.5f;
        Vector3 ось = ОсьМир();
        Vector3 e = rend.bounds.extents;   // полугабариты в мире
        // Убираем составляющую вдоль оси — остаётся размах в плоскости обода.
        Vector3 eПерп = new Vector3(
            e.x * (1f - Mathf.Abs(ось.x)),
            e.y * (1f - Mathf.Abs(ось.y)),
            e.z * (1f - Mathf.Abs(ось.z)));
        return Mathf.Max(eПерп.x, Mathf.Max(eПерп.y, eПерп.z));
    }

    void ПрименитьУгол()
    {
        Transform меш = МешШтурвала != null ? МешШтурвала : Штурвал;
        if (меш == null) return;
        // Крутим ИНКРЕМЕНТАМИ через RotateAround вокруг ЦЕНТРА (Штурвал.position) и мировой
        // оси штока: колесо вращается «вокруг себя», а не вокруг собственного (возможно
        // кривого) пивота — поэтому не уходит по орбите. Применяем только разницу углов.
        float d = _угол - _приложенныйУгол;
        if (Mathf.Abs(d) < 0.0001f) return;
        меш.RotateAround(ТочкаШтурвала(), ОсьМир(), d);
        _приложенныйУгол = _угол;
    }

    bool ЦельАктивна()
    {
        var m = MissionManager.Instance;
        return !(m != null && ИндексЦели >= 0 && !m.ЦельАктивна(ИндексЦели));
    }

    void Выполнить()
    {
        Выполнено = true;
        _захвачен = false;
        ВернутьФизикуДрона();   // вернуть дрону обычную физику — хват завершён
        Подсветить(false);

        if (РежимПроворота)
        {
            _угол = УголЗакрытия; ПрименитьУгол();   // штурвал строго в «закрыто»
            RovSystems.grabberClosed = false;        // раскрываем клешню — хват отпущен
            ОтойтиОтРуля();                          // и аппарат отходит от руля
        }

        if (ВключитьПриВыполнении != null) ВключитьПриВыполнении.SetActive(true);
        if (ВыключитьПриВыполнении != null) ВыключитьПриВыполнении.SetActive(false);
        if (ГаситьУтечкиПриВыполнении) PipelineLeakEmitter.ПогаситьВсе();   // закрыли вентиль — течь прекратилась (трещины не трогаем)

        Debug.Log($"[Вмешательство] Вентиль закрыт на {gameObject.name}");
        ПриВыполнении?.Invoke();

        var m = MissionManager.Instance;
        if (m != null)
        {
            if (ИндексЦели < 0) m.ЗавершитьТекущую();
            else                m.ЗавершитьЦель(ИндексЦели);
        }
    }

    // Включает/выключает эмиссию подсветки. globalIlluminationFlags обязателен —
    // без него URP часто игнорирует эмиссию, заданную в рантайме.
    void Подсветить(bool вкл)
    {
        if (_mats == null) return;
        for (int i = 0; i < _mats.Length; i++)
        {
            var m = _mats[i];
            if (m == null) continue;
            if (вкл)
            {
                m.EnableKeyword("_EMISSION");
                m.globalIlluminationFlags = MaterialGlobalIlluminationFlags.RealtimeEmissive;
                if (m.HasProperty("_EmissionColor"))
                    m.SetColor("_EmissionColor", ЦветПодсветки * ЯркостьПодсветки);
            }
            else
            {
                if (!_былаЭмиссия[i]) m.DisableKeyword("_EMISSION");
                if (m.HasProperty("_EmissionColor"))
                    m.SetColor("_EmissionColor", _исходнаяЭмиссия[i]);
            }
        }
    }

    static Rigidbody НайтиКорпусНПА()
    {
        var rc = FindObjectsByType<RovController>(FindObjectsSortMode.None);
        return rc.Length > 0 ? rc[0].GetComponent<Rigidbody>() : null;
    }

    // Гасит столкновение коллайдеров вентиля с коллайдерами КЛЕШНИ (не всего НПА) — чтобы
    // клешня не отскакивала от обода при подводе, а корпус в вентиль упирался. Триггеры не трогаем.
    void ОтключитьСтолкновения(Rigidbody нпа)
    {
        // Гасим столкновение с вентилем ТОЛЬКО у клешни — тогда её можно положить на
        // штурвал без отскока, а КОРПУС дрона по-прежнему упирается в вентиль (не проходит сквозь).
        Transform корень = КореньКлешни != null ? КореньКлешни : НайтиКореньКлешни(нпа);
        var клешня = корень != null
            ? корень.GetComponentsInChildren<Collider>(true)
            : нпа.GetComponentsInChildren<Collider>(true);   // запас: если клешню не нашли, гасим весь НПА

        foreach (var a in _колВентиля)
        {
            if (a == null || a.isTrigger) continue;
            foreach (var b in клешня)
            {
                if (b == null || b.isTrigger) continue;
                Physics.IgnoreCollision(a, b, true);
            }
        }
    }

    // Корень клешни: идём вверх от кончика, ищем узел с «grip/claw/jaw/клешн/захват» в имени.
    // Не нашли — берём ближайший узел над кончиком (хотя бы челюсти), но не весь корпус НПА.
    Transform НайтиКореньКлешни(Rigidbody нпа)
    {
        if (КончикМанипулятора == null) return null;
        string[] ключи = { "grip", "claw", "jaw", "клешн", "захват", "manip" };
        Transform корпус = нпа != null ? нпа.transform : null;
        for (Transform t = КончикМанипулятора; t != null && t != корпус; t = t.parent)
        {
            string имя = t.name.ToLowerInvariant();
            foreach (var k in ключи) if (имя.Contains(k)) return t;
        }
        return КончикМанипулятора.parent;
    }

    void OnDrawGizmosSelected()
    {
        if (!РежимПроворота)
        {
            Gizmos.color = new Color(0.3f, 0.8f, 1f, 0.5f);
            Gizmos.DrawWireSphere(transform.position, РадиусРаботы);
            return;
        }

        Vector3 центр = ТочкаШтурвала();
        Vector3 ось = ОсьМир();
        float R = РадиусОбода > 0.001f ? РадиусОбода : АвтоРадиусОбода();

        // Простой хитбокс — рисуем СФЕРУ зоны захвата (радиус обод+зазор) вокруг центра.
        if (ПростойХитбокс)
        {
            Gizmos.color = new Color(1f, 0.6f, 0.1f, 0.9f);
            Gizmos.DrawWireSphere(центр, R + РадиусЗахвата);
            return;
        }

        // Кольцо-хитбокс обода: где именно можно зацепиться клешнёй (тор радиуса R,
        // толщина = РадиусЗахвата). Помогает выставить РадиусОбода/Штурвал/Ось в редакторе.
        Vector3 x = Vector3.Cross(ось, Mathf.Abs(Vector3.Dot(ось, Vector3.up)) > 0.95f ? Vector3.right : Vector3.up).normalized;
        Vector3 y = Vector3.Cross(ось, x).normalized;

        Gizmos.color = new Color(1f, 0.6f, 0.1f, 0.9f);   // оранжевый — как обод
        Vector3 prev = центр + x * R;
        for (int i = 1; i <= 48; i++)
        {
            float a = i / 48f * Mathf.PI * 2f;
            Vector3 p = центр + (x * Mathf.Cos(a) + y * Mathf.Sin(a)) * R;
            Gizmos.DrawLine(prev, p);
            prev = p;
        }
        Gizmos.color = new Color(1f, 0.6f, 0.1f, 0.35f);
        Gizmos.DrawWireSphere(центр + x * R, РадиусЗахвата);   // толщина зоны захвата у обода
    }
