using System.Collections.Generic;
using UnityEngine;

// Сканер осмотра трубопровода. Ставится на НПА. Цель для снимка — необнаруженный дефект,
// который ВИДЕН НА МОНИТОРЕ: ближе ДальностьСканирования к камере, попадает в кадр и не
// закрыт трубой или грунтом. Смотреть прямо на него не нужно — достаточно, чтобы он
// был в кадре; выше или ниже — неважно, считается расстояние в пространстве.
// Когда такой дефект есть, горит ободок кнопки «ФОТО».
// Зачёт:
//   • СканироватьПоКнопке (по умолчанию) — по кнопке «ФОТО» (ButtonScan → Просканировать):
//     засчитываются все видимые дефекты, у каждого вспыхивает контур повреждённого места
//     (PipelineDefect, контур строит МагистральныйТрубопровод);
//   • иначе — автоматически, продержав дефект в кадре ВремяУдержания секунд.
// Нужны включённые прожекторы и ясная вода (в мути камера ничего не видит).
//
// Когда обнаружено ТребуетсяОбнаружить дефектов (0 = все) — закрывается цель миссии
// ИндексЦелиОсмотра. Кнопка дёргает сканер через статический Instance (кросс-сцена).
[DisallowMultipleComponent]
public class RovScanner : MonoBehaviour
{
    [Header("Камера осмотра")]
    [Tooltip("Трансформ бортовой камеры (ту, что на мониторе) — от неё считается, виден ли дефект")]
    public Transform Камера;

    [Header("Параметры сканирования")]
    [Tooltip("Дальность осмотра от камеры, м")]
    public float ДальностьСканирования = 4f;
    [Tooltip("Не используется: раньше — полуугол конуса наведения. Теперь достаточно, чтобы дефект был в кадре.")]
    public float ПолуголКонусаГрад = 25f;
    [Tooltip("Сколько секунд держать дефект в кадре для зачёта (режим без кнопки)")]
    public float ВремяУдержания_с = 1.5f;
    [Tooltip("Требовать включённые прожекторы (реалистично: без света не осмотреть)")]
    public bool ТребоватьСвет = true;
    [Tooltip("Проверять, что дефект не закрыт преградой (труба, грунт, камень) — луч от камеры.")]
    public bool ПроверятьПрепятствия = true;

    [Header("Режим осмотра")]
    [Tooltip("Не используется: дефект засчитывается, если он виден в кадре монитора.")]
    public bool ТребоватьНаведение = false;
    [Tooltip("Засчитывать дефект по нажатию кнопки «ФОТО» (Просканировать). " +
             "ВЫКЛ — автоматически, продержав дефект в кадре ВремяУдержания секунд.")]
    public bool СканироватьПоКнопке = true;

    [Header("Связь с миссией")]
    [Tooltip("Индекс цели «обследовать трубопровод» в MissionManager. −1 = текущая активная.")]
    public int ИндексЦелиОсмотра = -1;
    [Tooltip("Сколько дефектов надо найти. 0 = все, что есть в сцене.")]
    public int ТребуетсяОбнаружить = 0;
    [Tooltip("В мути (поднята движителями со дна) дефект не разглядеть — осмотр невозможен, пока вода не очистится.")]
    public bool ТребоватьЯснуюВоду = true;
    [Tooltip("Мутность у камеры (0..1), выше которой осмотр невозможен.")]
    [Range(0f, 1f)] public float ПорогМутности = 0.5f;
    bool _вМути;

    public int ОбнаруженоДефектов { get; private set; }
    public int ВсегоДефектов { get; private set; }

    // Есть ли сейчас в кадре дефект, готовый к снимку (для индикатора кнопки).
    public bool ЕстьКандидат => _видимые.Count > 0 && !_цельЗакрыта;

    private PipelineDefect[] _дефекты;
    private readonly List<PipelineDefect> _видимые = new List<PipelineDefect>();
    private readonly HashSet<PipelineDefect> _былиВидны = new HashSet<PipelineDefect>();   // для лога «появился в кадре»
    private PipelineDefect _цель;       // режим удержания: дефект, который держим в кадре
    private float _выдержка;            // накоплено времени на текущей цели
    private bool _цельЗакрыта;
    private Camera _кам;

    public static RovScanner Instance { get; private set; }

    void Awake() { Instance = this; }
    void OnDestroy() { if (Instance == this) Instance = null; }

    void Start()
    {
        _дефекты = FindObjectsByType<PipelineDefect>(FindObjectsSortMode.None);
        ВсегоДефектов = _дефекты.Length;
        if (Камера == null && Camera.main != null) Камера = Camera.main.transform;
        Debug.Log($"[RovScanner] Готов на «{name}»: дефектов в сцене {ВсегоДефектов}, " +
                  $"радиус осмотра {ДальностьСканирования:F1} м от камеры, дефект должен быть виден на мониторе.", this);
    }

    void Update()
    {
        _видимые.Clear();
        if (_цельЗакрыта || _дефекты == null) return;
        if (МожноСнимать(out _)) СобратьВидимые(_видимые);

        // Муть у камеры — ничего не видно: подсказка в HUD, осмотр ждёт.
        bool муть = ТребоватьЯснуюВоду && RovSystems.turbidity > ПорогМутности;
        if (муть != _вМути)
        {
            _вМути = муть;
            var m = MissionManager.Instance;
            if (муть) m?.УстановитьПрогресс(ИндексЦелиОсмотра, "Вода мутная — отойдите от дна и подождите, пока муть осядет");
            else if (ОбнаруженоДефектов > 0) ОбновитьПрогресс();
            else m?.УстановитьПрогресс(ИндексЦелиОсмотра, "");
        }

        foreach (var d in _видимые)
            if (_былиВидны.Add(d))
                Debug.Log($"[RovScanner] В кадре дефект ({Vector3.Distance(КамераПоз, d.transform.position):F1} м): {d.name} — жми «ФОТО».", d);
        _былиВидны.RemoveWhere(d => !_видимые.Contains(d));

        // Режим удержания: дефект засчитывается, если продержать его в кадре.
        if (СканироватьПоКнопке) return;
        var лучшая = _видимые.Count > 0 ? _видимые[0] : null;
        if (лучшая != _цель)
        {
            if (_цель != null) _цель.ПодсветитьНаведение(0f);
            _цель = лучшая;
            _выдержка = 0f;
        }
        if (_цель == null) return;
        _выдержка += Time.deltaTime;
        _цель.ПодсветитьНаведение(_выдержка / ВремяУдержания_с);
        if (_выдержка >= ВремяУдержания_с) { var ц = _цель; _цель = null; Зачесть(ц); }
    }

    // Свет и ясная вода — без них камера дефект не покажет.
    bool МожноСнимать(out string почему)
    {
        почему = null;
        if (ТребоватьСвет && !RovSystems.lightsOn) почему = "Фото: сначала включите прожекторы — без света дефект не разглядеть";
        else if (ТребоватьЯснуюВоду && RovSystems.turbidity > ПорогМутности) почему = "Фото: вода мутная, камера ничего не видит — подождите, пока муть осядет";
        return почему == null;
    }

    // Продолжение сохранённой миссии: дефект уже был найден раньше.
    public void ВосстановитьНайденный(PipelineDefect d)
    {
        if (d == null || d.Обнаружен) return;
        d.Обнаружить();
        ОбнаруженоДефектов++;
        ОбновитьПрогресс();
        ПроверитьЗавершение();
    }

    // Снимок по красной кнопке «ФОТО» (ButtonScan) через Instance: засчитываются все
    // дефекты, видные сейчас на мониторе, — каждый со своим снимком кадра монитора.
    // Если снимать нечего — короткая подсказка в задании HUD, почему.
    public void Просканировать()
    {
        if (_цельЗакрыта) return;
        if (!МожноСнимать(out string почему)) { Подсказать(почему); return; }
        _видимые.Clear();
        СобратьВидимые(_видимые);
        if (_видимые.Count > 0)
        {
            foreach (var d in _видимые.ToArray())
            {
                Зачесть(d);
                if (_цельЗакрыта) break;
            }
            return;
        }
        float рядом = БлижайшаяДистанция(out bool вРадиусе);
        if (вРадиусе)
            Подсказать($"Фото: дефект рядом ({рядом:0} м), но его не видно на мониторе — разверните аппарат к нему");
        else
            Подсказать($"Фото: в радиусе {ДальностьСканирования:0} м дефектов нет" +
                       (рядом < float.MaxValue ? $" (ближайший — {рядом:0} м)" : " — все уже сняты"));
    }

    // Подсказка держится несколько секунд под счётчиком задания, потом убирается.
    string _подсказка = "";
    float _подсказкаДо = -1f;

    void Подсказать(string текст)
    {
        Debug.Log("[RovScanner] " + текст);
        _подсказка = "\n" + текст;
        _подсказкаДо = Time.time + 4f;
        ОбновитьПрогресс();
    }

    void LateUpdate()
    {
        if (_подсказкаДо < 0f || Time.time < _подсказкаДо) return;
        _подсказкаДо = -1f; _подсказка = "";
        if (ОбнаруженоДефектов > 0) ОбновитьПрогресс();
        else MissionManager.Instance?.УстановитьПрогресс(ИндексЦелиОсмотра, "");
    }

    Vector3 КамераПоз => Камера != null ? Камера.position : transform.position;

    float БлижайшаяДистанция(out bool вРадиусе)
    {
        float best = float.MaxValue;
        вРадиусе = false;
        if (_дефекты == null) return best;
        foreach (var d in _дефекты)
        {
            if (d == null || d.Обнаружен) continue;
            float дист = Vector3.Distance(КамераПоз, d.transform.position);
            if (дист < best) best = дист;
            if (дист <= ДальностьСканирования + Протяжённость(d)) вРадиусе = true;
        }
        return best;
    }

    void Зачесть(PipelineDefect d)
    {
        if (d == null || d.Обнаружен) return;
        ЗапомнитьКоординаты(d.transform.position);
        d.Обнаружить();
        ОбнаруженоДефектов++;
        ОбновитьПрогресс();
        ПроверитьЗавершение();
    }

    // Пишет в HUD живой счётчик «Обнаружено X/N дефектов» на цели осмотра (+ подсказка кнопки «ФОТО»).
    void ОбновитьПрогресс()
    {
        var m = MissionManager.Instance;
        if (m == null) return;
        int нужно = ТребуетсяОбнаружить > 0 ? ТребуетсяОбнаружить : ВсегоДефектов;
        m.УстановитьПрогресс(ИндексЦелиОсмотра, $"Обнаружено {ОбнаруженоДефектов}/{нужно} дефектов" + _последнееСообщение + _подсказка);
    }

    // Передача координат: положение по трассе (KP) и глубина по датчику аппарата — как
    // «событие» в журнале инспекции, которое оператор отправляет на судно.
    string _последнееСообщение = "";
    void ЗапомнитьКоординаты(Vector3 p)
    {
        var st = MissionStats.Instance;
        string kp = st != null && st.ЕстьТруба ? MissionStats.ФорматKP(st.KP(p)) : "KP —";
        _последнееСообщение = $"\nпередано на судно: {kp}, глубина {RovSystems.depth_m:F1} м";
    }

    // ---------------- Что видно на мониторе ----------------

    // Насколько дефект протянулся от своей метки, м: провис — на пол-пролёта, остальное ~1 м.
    static float Протяжённость(PipelineDefect d) => d.Тип == PipelineDefect.ТипДефекта.Провис ? Mathf.Max(0f, d.РадиусОбнаружения - 1f) : 0.5f;

    Camera Кам()
    {
        if (_кам == null || _кам.transform != Камера) _кам = Камера != null ? Камера.GetComponent<Camera>() : null;
        return _кам;
    }

    // Все необследованные дефекты, видные на мониторе: хотя бы одна их точка — метка или
    // точка контура повреждения — ближе ДальностьСканирования к камере, попадает в кадр и
    // не закрыта. Так дефект засчитывается и «боковым зрением», когда в кадре только его
    // край, и сверху, когда центр метки за изгибом трубы. Ближние — первыми.
    readonly Vector3[] _точки = new Vector3[48];
    readonly float[] _допуск = new float[48];

    void СобратьВидимые(List<PipelineDefect> куда)
    {
        var кам = Кам();
        Vector3 глаз = КамераПоз;
        foreach (var d in _дефекты)
        {
            if (d == null || d.Обнаружен) continue;
            if (Vector3.Distance(глаз, d.transform.position) > ДальностьСканирования + Протяжённость(d) + 2f) continue;
            int n = ТочкиДефекта(d);
            for (int i = 0; i < n; i++)
            {
                Vector3 p = _точки[i];
                float дист = Vector3.Distance(глаз, p);
                if (дист > ДальностьСканирования) continue;
                if (кам != null)
                {
                    Vector3 vp = кам.WorldToViewportPoint(p);
                    if (vp.z < 0.05f || vp.x < 0f || vp.x > 1f || vp.y < 0f || vp.y > 1f) continue;
                }
                if (ПроверятьПрепятствия && Закрыт(глаз, p, дист, _допуск[i])) continue;
                куда.Add(d);
                break;
            }
        }
        куда.Sort((a, b) => (a.transform.position - глаз).sqrMagnitude.CompareTo((b.transform.position - глаз).sqrMagnitude));
    }

    // Метка (на поверхности трубы, у провиса — на оси: допуск чуть больше радиуса трубы)
    // и ~12 точек каждого кольца контура (лежат на поверхности: допуск маленький).
    int ТочкиДефекта(PipelineDefect d)
    {
        int n = 0;
        _точки[n] = d.transform.position; _допуск[n++] = 0.9f;
        if (d.Контур == null) return n;
        foreach (var lr in d.Контур)
        {
            if (lr == null || lr.name.EndsWith("ореол")) continue;
            int всего = lr.positionCount, шаг = Mathf.Max(1, всего / 12);
            for (int i = 0; i < всего && n < _точки.Length; i += шаг) { _точки[n] = lr.GetPosition(i); _допуск[n++] = 0.3f; }
        }
        return n;
    }

    // Луч от камеры к точке: закрыта, если упёрся во что-то заметно раньше и вдали от
    // самой точки (дальний бок трубы, грунт, камень). Свой корпус и кабель не мешают.
    bool Закрыт(Vector3 глаз, Vector3 p, float дист, float допуск)
    {
        Vector3 dir = (p - глаз) / Mathf.Max(0.001f, дист);
        if (!DvlJanus.ЛучДоДна(transform, GetComponent<Rigidbody>(), глаз, dir, дист, out float R)) return false;
        if (R >= дист - 0.25f) return false;
        return Vector3.Distance(глаз + dir * R, p) > допуск;
    }

    void ПроверитьЗавершение()
    {
        int нужно = ТребуетсяОбнаружить > 0 ? ТребуетсяОбнаружить : ВсегоДефектов;
        if (ОбнаруженоДефектов < нужно) return;

        _цельЗакрыта = true;
        var m = MissionManager.Instance;
        if (m == null) return;
        if (ИндексЦелиОсмотра < 0) m.ЗавершитьТекущую();
        else                       m.ЗавершитьЦель(ИндексЦелиОсмотра);
    }

    // Радиус осмотра в Scene — чтобы видеть, докуда ловятся дефекты.
    void OnDrawGizmosSelected()
    {
        Gizmos.color = new Color(0.3f, 0.8f, 1f, 0.5f);
        Gizmos.DrawWireSphere(КамераПоз, ДальностьСканирования);
    }
}
