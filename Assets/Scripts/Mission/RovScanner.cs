using UnityEngine;

// Сканер осмотра трубопровода. Ставится на НПА. Кандидат на осмотр — необнаруженный
// дефект в радиусе (ДальностьСканирования) при включённых прожекторах; он подсвечивается.
// Зачёт кандидата:
//   • СканироватьПоКнопке (по умолчанию) — по нажатию кнопки ButtonScan (Просканировать);
//   • иначе — автоматически, продержав наведение ВремяУдержания секунд.
// ТребоватьНаведение добавляет условие «камера смотрит на дефект» (конус + прямая
// видимость) — пока выключено, т.к. нет наклона камеры вверх/вниз.
//
// Когда обнаружено ТребуетсяОбнаружить дефектов (0 = все) — закрывается цель миссии
// ИндексЦелиОсмотра. Кнопка дёргает сканер через статический Instance (кросс-сцена).
[DisallowMultipleComponent]
public class RovScanner : MonoBehaviour
{
    [Header("Камера осмотра")]
    [Tooltip("Трансформ бортовой камеры — от неё считается направление осмотра")]
    public Transform Камера;

    [Header("Параметры сканирования")]
    [Tooltip("Дальность осмотра, м")]
    public float ДальностьСканирования = 4f;
    [Tooltip("Полуугол конуса осмотра, град (насколько точно надо навести камеру)")]
    public float ПолуголКонусаГрад = 25f;
    [Tooltip("Сколько секунд удерживать дефект в прицеле для зачёта")]
    public float ВремяУдержания_с = 1.5f;
    [Tooltip("Требовать включённые прожекторы (реалистично: без света не осмотреть)")]
    public bool ТребоватьСвет = true;
    [Tooltip("Проверять, что дефект не закрыт преградой (рейкаст от камеры). " +
             "Требует коллайдеров на трубе/рельефе.")]
    public bool ПроверятьПрепятствия = true;

    [Header("Режим осмотра")]
    [Tooltip("Требовать наведения камеры на дефект (конус). ВЫКЛ — осмотр по близости, " +
             "куда бы ни смотрел аппарат (пока нет наклона камеры вверх/вниз).")]
    public bool ТребоватьНаведение = false;
    [Tooltip("Засчитывать дефект по нажатию кнопки сканирования (Просканировать). " +
             "ВЫКЛ — автоматически, продержав наведение ВремяУдержания секунд.")]
    public bool СканироватьПоКнопке = true;

    [Header("Связь с миссией")]
    [Tooltip("Индекс цели «обследовать трубопровод» в MissionManager. −1 = текущая активная.")]
    public int ИндексЦелиОсмотра = -1;
    [Tooltip("Сколько дефектов надо найти. 0 = все, что есть в сцене.")]
    public int ТребуетсяОбнаружить = 0;

    public int ОбнаруженоДефектов { get; private set; }
    public int ВсегоДефектов { get; private set; }

    // Есть ли сейчас подсвеченный кандидат, готовый к зачёту по кнопке (для её индикатора).
    public bool ЕстьКандидат => _цель != null && !_цельЗакрыта;

    private PipelineDefect[] _дефекты;
    private PipelineDefect _цель;       // текущая цель в прицеле
    private float _выдержка;            // накоплено времени на текущей цели
    private bool _цельЗакрыта;

    public static RovScanner Instance { get; private set; }

    void Awake() { Instance = this; }
    void OnDestroy() { if (Instance == this) Instance = null; }

    void Start()
    {
        _дефекты = FindObjectsByType<PipelineDefect>(FindObjectsSortMode.None);
        ВсегоДефектов = _дефекты.Length;
        if (Камера == null && Camera.main != null) Камера = Camera.main.transform;
        Debug.Log($"[RovScanner] Готов на «{name}»: трещин в сцене {ВсегоДефектов}, " +
                  $"радиус осмотра {ДальностьСканирования:F1} м, режим {(ТребоватьНаведение ? "наведение (конус)" : "близость")}.", this);
    }

    void Update()
    {
        if (_цельЗакрыта || _дефекты == null) return;

        // Свет — обязательное условие осмотра.
        if (ТребоватьСвет && !RovSystems.lightsOn) { Сбросить(); return; }

        PipelineDefect лучшая = ЛучшаяЦель();

        // Сменился кандидат (или потеряли).
        if (лучшая != _цель)
        {
            // В режиме удержания гасим прежнюю подсветку наведения (в режиме кнопки её нет).
            if (!СканироватьПоКнопке && _цель != null) _цель.ПодсветитьНаведение(0f);
            _цель = лучшая;
            _выдержка = 0f;
            if (_цель != null)
                Debug.Log($"[RovScanner] Трещина в радиусе ({Vector3.Distance(transform.position, _цель.transform.position):F1} м): {_цель.name} — жми кнопку осмотра.", _цель);
        }

        if (_цель == null) return;

        // В режиме по кнопке заранее НЕ подсвечиваем — трещина вспыхнет по нажатию
        // (Обнаружить). В режиме удержания метка разгорается по мере наведения.
        if (!СканироватьПоКнопке)
        {
            _выдержка += Time.deltaTime;
            _цель.ПодсветитьНаведение(_выдержка / ВремяУдержания_с);
            if (_выдержка >= ВремяУдержания_с) РегистрироватьЦель();
        }
    }

    void Сбросить()
    {
        if (_цель != null) _цель.ПодсветитьНаведение(0f);
        _цель = null;
        _выдержка = 0f;
    }

    // Зачесть текущий подсвеченный кандидат — вызывается кнопкой ButtonScan через Instance.
    public void Просканировать()
    {
        if (_цельЗакрыта) return;
        if (ТребоватьСвет && !RovSystems.lightsOn)
        {
            Debug.Log("[RovScanner] Осмотр: сначала включи прожекторы.");
            return;
        }
        if (_цель != null)
        {
            РегистрироватьЦель();
        }
        else
        {
            float d = БлижайшаяДистанция();
            Debug.Log($"[RovScanner] Осмотр: нет трещины в радиусе {ДальностьСканирования:F1} м" +
                      (d < float.MaxValue ? $" (ближайшая необследованная — {d:F1} м)." : " (необследованных трещин нет)."));
        }
    }

    float БлижайшаяДистанция()
    {
        float best = float.MaxValue;
        if (_дефекты == null) return best;
        foreach (var d in _дефекты)
        {
            if (d == null || d.Обнаружен) continue;
            float дист = Vector3.Distance(transform.position, d.transform.position);
            if (дист < best) best = дист;
        }
        return best;
    }

    void РегистрироватьЦель()
    {
        if (_цель == null) return;
        _цель.Обнаружить();
        ОбнаруженоДефектов++;
        _цель = null;
        _выдержка = 0f;
        ОбновитьПрогресс();
        ПроверитьЗавершение();
    }

    // Пишет в HUD живой счётчик «Обнаружено X/N трещин» на цели осмотра.
    void ОбновитьПрогресс()
    {
        var m = MissionManager.Instance;
        if (m == null) return;
        int нужно = ТребуетсяОбнаружить > 0 ? ТребуетсяОбнаружить : ВсегоДефектов;
        m.УстановитьПрогресс(ИндексЦелиОсмотра, $"Обнаружено {ОбнаруженоДефектов}/{нужно} трещин");
    }

    // Кандидат на осмотр: ближайший необнаруженный дефект в радиусе. В режиме
    // ТребоватьНаведение — ещё и в конусе камеры с прямой видимостью.
    PipelineDefect ЛучшаяЦель()
    {
        PipelineDefect best = null;
        bool наведение = ТребоватьНаведение && Камера != null;
        Vector3 базаПоз = наведение ? Камера.position : transform.position;

        float bestDot = Mathf.Cos(ПолуголКонусаГрад * Mathf.Deg2Rad); // минимальный косинус угла
        float bestDist = float.MaxValue;

        foreach (var d in _дефекты)
        {
            if (d == null || d.Обнаружен) continue;

            Vector3 к = d.transform.position - базаПоз;
            float дист = к.magnitude;
            if (дист > ДальностьСканирования) continue;
            if (дист < 0.001f) continue;

            if (наведение)
            {
                float dot = Vector3.Dot(Камера.forward, к / дист);
                if (dot < bestDot) continue;                          // вне конуса или хуже
                if (ПроверятьПрепятствия && ЗакрытПреградой(базаПоз, d)) continue;
                bestDot = dot; best = d;
            }
            else if (дист < bestDist)                                  // режим близости: ближайший в радиусе
            {
                bestDist = дист; best = d;
            }
        }
        return best;
    }

    bool ЗакрытПреградой(Vector3 камПоз, PipelineDefect d)
    {
        Vector3 dir = d.transform.position - камПоз;
        float дист = dir.magnitude;
        // Если рейкаст упёрся во что-то заметно ближе самого дефекта — обзор закрыт.
        if (Physics.Raycast(камПоз, dir.normalized, out RaycastHit hit, дист - 0.2f))
        {
            // Коллайдер самого дефекта (если есть) преградой не считаем.
            if (hit.collider.GetComponentInParent<PipelineDefect>() != d) return true;
        }
        return false;
    }

    void ПроверитьЗавершение()
    {
        int нужно = ТребуетсяОбнаружить > 0 ? ТребуетсяОбнаружить : ВсегоДефектов;
        if (ОбнаруженоДефектов < нужно) return;

        _цельЗакрыта = true;
        var m = MissionManager.Instance;
        if (m == null) return;
        if (ИндексЦелиОсмотра < 0) m.ЗавершитьТекущую();
        else                       m.ЗавершитьЦель(ИндексЦелиОсмотра);
    }

    // Радиус осмотра в Scene — чтобы видеть, докуда ловятся трещины.
    void OnDrawGizmosSelected()
    {
        Gizmos.color = new Color(0.3f, 0.8f, 1f, 0.5f);
        Gizmos.DrawWireSphere(transform.position, ДальностьСканирования);
    }
}
