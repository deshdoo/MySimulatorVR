using System.Collections.Generic;
using UnityEngine;

// Авто-сборка миссии «Обследование трубопровода» прямо в коде — один компонент на
// пустом объекте в сцене Main, чтобы не собирать всё вручную в редакторе.
//
// В Awake:
//   1) находит/создаёт MissionManager и, если целей ещё нет, заполняет их
//      (осмотреть N трещин → [если задан вентиль] закрыть вентиль);
//   2) вешает и настраивает RovScanner на НПА (камеру вида находит сам — это камера,
//      что рендерит в RenderTexture, т.е. бортовой вид, который показывает монитор);
//   3) если задан Вентиль — вешает на него InterventionTarget с кончиком клешни.
//
// HUD чеклиста живёт ОТДЕЛЬНО в сцене кабины: повесь MissionHudDisplay на UI-объект
// под Canvas свободного монитора — поле он построит сам и возьмёт MissionManager.Instance
// по статике во время игры (сцены Main и Cabin грузятся аддитивно).
//
// Что стоит задать в инспекторе (по именам сцена не ищется):
//   • Вентиль — объект задвижки на трубе. Пусто = миссия только из осмотра.
//   • КончикКлешни — нос манипулятора НПА. Пусто — попробует найти по имени.
//   • НПА / КамераОсмотра — обычно находятся сами.
[DefaultExecutionOrder(-100)]
[DisallowMultipleComponent]
public class MissionBootstrap : MonoBehaviour
{
    [Header("Осмотр")]
    public string НазваниеМиссии = "Обследование трубопровода";
    [Tooltip("Сколько трещин надо осмотреть для зачёта")]
    public int СколькоТрещинНайти = 2;
    [Tooltip("Радиус осмотра, м — на скольки метрах от НПА трещина подсвечивается и её можно осмотреть кнопкой.")]
    public float РадиусОсмотра_м = 8f;
    [Tooltip("Полуугол конуса осмотра, град (насколько точно надо навести камеру)")]
    public float ПолуголКонусаГрад = 25f;
    [Tooltip("Сколько секунд держать трещину в прицеле для зачёта")]
    public float ВремяУдержанияОсмотра_с = 1.2f;

    [Header("Вмешательство (вентиль) — необязательно")]
    [Tooltip("Объект аварийного вентиля на трубе — точка работы клешнёй. Пусто = миссия без этого шага.")]
    public Transform Вентиль;
    [Tooltip("Кончик клешни манипулятора НПА. Пусто — поиск по имени в иерархии НПА.")]
    public Transform КончикКлешни;
    [Tooltip("Показать после закрытия (напр. меш «вентиль закрыт»). Необязательно.")]
    public GameObject ПоказатьПриЗакрытии;

    [Header("Вентиль: настоящий хват + проворот")]
    [Tooltip("ВКЛ — клешню зажать на штурвале и провернуть боковым ходом аппарата. ВЫКЛ — старый режим «навести и удержать».")]
    public bool ХватПроворотом = true;
    [Tooltip("ЦЕНТР штурвала — точка вращения и центр зоны захвата. Обычно пустой объект в центре колеса. " +
             "Пусто — сам объект вентиля.")]
    public Transform Штурвал;
    [Tooltip("ВИДИМЫЙ меш штурвала (красный круг), который реально крутится. Пусто — крутится сам Штурвал " +
             "(если Штурвал — пустой объект, визуально ничего не повернётся). Задай сюда меш колеса.")]
    public Transform МешШтурвала;
    [Tooltip("Ось проворота штурвала в МИРОВЫХ осях (направление штока). Вертикальный шток = (0,1,0).")]
    public Vector3 ОсьПроворота = Vector3.up;
    [Tooltip("Полный угол закрытия вентиля, град.")]
    public float УголЗакрытия = 30f;
    [Tooltip("Скорость облёта: град/сек проворота штурвала при полном отклонении рычага Turn (lever 3). " +
             "60 = закрыть 30° за 0.5 с. Знак минус — сменить сторону.")]
    public float СкоростьОблёта = 60f;
    [Tooltip("Зазор от кончика клешни до поверхности вентиля для зацепа, м.")]
    public float РадиусЗахвата = 0.15f;
    [Tooltip("Радиус кольца обода от центра штурвала, м. 0 = вычислить автоматически по габаритам штурвала. " +
             "Авто врёт, если Штурвал не задан или его bounds захватывают трубу — тогда задай радиус вручную " +
             "и смотри на оранжевое кольцо-гизмо в Play Mode, пока оно не ляжет на обод.")]
    public float РадиусОбода = 0f;
    [Tooltip("ПРОСТОЙ хитбокс (рекомендуется): зона захвата = сфера вокруг центра штурвала, без учёта оси/плоскости. " +
             "Настраивать надо только Штурвал (центр) и РадиусОбода. ВЫКЛ — точный тор по ободу.")]
    public bool ПростойХитбокс = true;

    [Header("Вентиль: старый режим удержания")]
    public float РадиусРаботы_м = 0.6f;
    public float ВремяУдержанияВентиля_с = 2f;

    [Header("Ссылки (обычно находятся сами)")]
    [Tooltip("Корпус НПА. Пусто — берётся объект с RovController.")]
    public Transform НПА;
    [Tooltip("Камера бортового вида. Пусто — берётся камера, рендерящая в RenderTexture.")]
    public Transform КамераОсмотра;

    void Awake()
    {
        var менеджер = НайтиИлиСоздатьМенеджер();
        ЗаполнитьЦели(менеджер);
        НастроитьСканер();
        НастроитьВентиль();
    }

    MissionManager НайтиИлиСоздатьМенеджер()
    {
        var m = ПервыйВСцене<MissionManager>();
        if (m == null) m = gameObject.AddComponent<MissionManager>();
        return m;
    }

    void ЗаполнитьЦели(MissionManager m)
    {
        m.НазваниеМиссии = НазваниеМиссии;
        // Список уже собран (вручную или другим бутстрапом) — не перестраиваем.
        if (m.Цели != null && m.Цели.Count > 0)
        {
            // Самопочинка гонки: если у НАС задан вентиль, а цели вентиля в списке нет
            // (её собрал дубль-бутстрап без вентиля — напр. лишний экземпляр в префабе),
            // дочиним — добавим недостающую цель, чтобы задача вентиля не пропала.
            if (Вентиль != null && !m.Цели.Exists(ц => ц.Заголовок == ЗаголовокВентиля))
            {
                m.Цели.Add(СоздатьЦельВентиля());
                Debug.LogWarning("[MissionBootstrap] Список уже был собран другим бутстрапом без вентиля — " +
                                 "добавил недостающую цель «Закройте вентиль». Убери лишний MissionBootstrap " +
                                 "(скорее всего он в префабе вентиля), чтобы не зависеть от порядка Awake.");
            }
            return;
        }

        m.Цели = new List<MissionObjective>
        {
            new MissionObjective
            {
                Заголовок = "Осмотрите трубу",
                Подсказка = "Включите прожекторы и осмотрите трубопровод. В случае повреждений нажмите специальную кнопку осмотра."
            }
        };

        if (Вентиль != null)
            m.Цели.Add(СоздатьЦельВентиля());

        Debug.Log($"[MissionBootstrap] Цели собраны: {m.Цели.Count} шт. " +
                  $"(Вентиль {(Вентиль != null ? "задан → цель «Закройте вентиль» добавлена" : "НЕ задан → только осмотр")}).");
    }

    const string ЗаголовокВентиля = "Закройте вентиль";

    MissionObjective СоздатьЦельВентиля() => new MissionObjective
    {
        Заголовок = ЗаголовокВентиля,
        Подсказка = "Проверните манипулятором вентиль для остановки протечки."
    };

    void НастроитьСканер()
    {
        Transform корпус = НПА != null ? НПА : ТрансформКомпонента<RovController>();
        if (корпус == null)
        {
            Debug.LogWarning("[MissionBootstrap] Не найден НПА (RovController) — сканер осмотра не настроен. Задай поле НПА.");
            return;
        }

        var scanner = корпус.GetComponent<RovScanner>();
        if (scanner == null) scanner = корпус.gameObject.AddComponent<RovScanner>();

        scanner.Камера = КамераОсмотра != null ? КамераОсмотра : НайтиКамеруВида();
        scanner.ДальностьСканирования = РадиусОсмотра_м;
        scanner.ПолуголКонусаГрад = ПолуголКонусаГрад;
        scanner.ВремяУдержания_с = ВремяУдержанияОсмотра_с;
        scanner.ТребуетсяОбнаружить = СколькоТрещинНайти;
        scanner.ИндексЦелиОсмотра = 0;
        scanner.ТребоватьНаведение = false;   // пока нет наклона камеры — осмотр по близости
        scanner.СканироватьПоКнопке = true;   // зачёт по кнопке ButtonScan

        if (scanner.Камера == null)
            Debug.LogWarning("[MissionBootstrap] Не найдена камера вида НПА — задай КамераОсмотра вручную, иначе осмотр не работает.");
    }

    void НастроитьВентиль()
    {
        if (Вентиль == null) return;

        var it = Вентиль.GetComponent<InterventionTarget>();
        if (it == null) it = Вентиль.gameObject.AddComponent<InterventionTarget>();

        it.КончикМанипулятора = КончикКлешни != null ? КончикКлешни : НайтиКончикКлешни();
        it.ИндексЦели = 1;   // вторая цель (после осмотра)
        it.ВключитьПриВыполнении = ПоказатьПриЗакрытии;
        it.ГаситьУтечкиПриВыполнении = true;

        // Режим настоящего хвата с проворотом.
        it.РежимПроворота = ХватПроворотом;
        it.Штурвал = Штурвал != null ? Штурвал : Вентиль;
        it.МешШтурвала = МешШтурвала;
        it.ОсьПроворота = ОсьПроворота;
        it.УголЗакрытия = УголЗакрытия;
        it.СкоростьОблёта = СкоростьОблёта;
        it.РадиусЗахвата = РадиусЗахвата;
        it.РадиусОбода = РадиусОбода;
        it.ПростойХитбокс = ПростойХитбокс;
        it.КорпусНПА = (НПА != null ? НПА : ТрансформКомпонента<RovController>())?.GetComponent<Rigidbody>();

        // Старый режим удержания (если ХватПроворотом выключен).
        it.РадиусРаботы = РадиусРаботы_м;
        it.ВремяУдержания_с = ВремяУдержанияВентиля_с;

        if (it.КончикМанипулятора == null)
            Debug.LogWarning("[MissionBootstrap] Не найден кончик клешни — задай КончикКлешни в инспекторе, иначе вентиль не закрыть.");
    }

    // Камера бортового вида НПА = та, что рендерит в RenderTexture (её показывает монитор).
    Transform НайтиКамеруВида()
    {
        foreach (var c in FindObjectsByType<Camera>(FindObjectsSortMode.None))
            if (c.targetTexture != null) return c.transform;
        return Camera.main != null ? Camera.main.transform : null;
    }

    // Кончик клешни ищем по имени в иерархии НПА (эвристика — на случай, если ссылку не задали).
    Transform НайтиКончикКлешни()
    {
        Transform корпус = НПА != null ? НПА : ТрансформКомпонента<RovController>();
        if (корпус == null) return null;

        string[] ключи = { "tip", "claw", "jaw", "grip", "grabber", "клешн", "захват" };
        foreach (var t in корпус.GetComponentsInChildren<Transform>(true))
        {
            string имя = t.name.ToLowerInvariant();
            foreach (var k in ключи)
                if (имя.Contains(k)) return t;
        }
        return null;
    }

    static Transform ТрансформКомпонента<T>() where T : Component
    {
        var arr = FindObjectsByType<T>(FindObjectsSortMode.None);
        return arr.Length > 0 ? arr[0].transform : null;
    }

    static T ПервыйВСцене<T>() where T : Object
    {
        var arr = FindObjectsByType<T>(FindObjectsSortMode.None);
        return arr.Length > 0 ? arr[0] : null;
    }
}
