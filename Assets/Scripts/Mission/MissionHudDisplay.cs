using UnityEngine;
using TMPro;

// HUD миссии: последовательный показ целей + таймер в ОДНО TMP-поле рич-текстом.
//
// Показывается ОДИН шаг за раз, а не весь список: видна текущая активная цель
// (циан ►); выполнил — она загорается зелёным (•) и держится, затем плавно гаснет
// и исчезает, и только после этого появляется следующая цель. Когда все цели
// закрыты и последняя догорела — остаётся финальная фраза «ВЫПОЛНЕНО». Ожидающие
// цели намеренно скрыты до своей очереди — так HUD читается как пошаговый сценарий.
// (Значки настраиваются в инспекторе; экзотику вроде ✔ шрифт может не тянуть.)
//
// Одно текстовое поле — сознательный выбор ради минимума настройки в сцене:
// не нужно создавать префаб-строку и инстанцировать по объекту на цель.
//
// Настройка: TMP-поле на канвасе (лучше моноширинный или обычный шрифт с рич-текстом),
// перетащить его в «Поле», перетащить объект с MissionManager в «Менеджер» (или
// оставить пустым — возьмёт MissionManager.Instance).
[DisallowMultipleComponent]
public class MissionHudDisplay : MonoBehaviour
{
    [Tooltip("Текстовое поле для всего чеклиста (одно на список целей)")]
    public TMP_Text Поле;

    [Tooltip("Менеджер миссии. Пусто — возьмётся MissionManager.Instance")]
    public MissionManager Менеджер;

    [Header("Шрифт")]
    [Tooltip("Шрифт HUD. Пусто — дефолтный TMP-шрифт. Поставь тот же ofont, что на мониторе систем, " +
             "чтобы монитор задания был в одном стиле с первым монитором.")]
    public TMP_FontAsset шрифт;

    // Палитра приведена к гамме первого монитора (SystemStatusDisplay):
    // циан «активно/работает», зелёный OK, серый «выкл», красный «авария».
    [Header("Цвета строк")]
    public Color ЦветАктивной   = new Color(0.30f, 0.85f, 1.00f);
    public Color ЦветВыполненной = new Color(0.30f, 1.00f, 0.45f);
    public Color ЦветОжидания   = new Color(0.50f, 0.50f, 0.50f);
    public Color ЦветПровала    = new Color(1.00f, 0.30f, 0.30f);
    [Tooltip("Второстепенный текст — таймер, разделитель")]
    public Color ЦветВторостепенный = new Color(0.60f, 0.65f, 0.70f);

    [Header("Значки статуса")]
    [Tooltip("ВАЖНО: символ должен быть в шрифте, иначе TMP рисует пустой квадрат □. " +
             "В LiberationSans SDF галочки ✔/✓ НЕТ — доступны только • ○ ► × □. " +
             "Если добавишь шрифт-фолбэк с галочкой — можешь вписать сюда ✔.")]
    public string ЗначокВыполнено = "•";
    public string ЗначокАктивна   = "►";
    public string ЗначокОжидание  = "○";
    public string ЗначокПровал    = "×";

    [Header("Поведение — последовательный показ")]
    [Tooltip("Сколько секунд выполненная цель горит зелёным, прежде чем начать гаснуть.")]
    public float ДержатьЗелёную_с = 1.2f;
    [Tooltip("За сколько секунд зелёная цель плавно гаснет и исчезает; только после этого появляется следующая цель.")]
    public float Угасание_с = 0.8f;
    [Tooltip("Если Поле не задано — построить текстовое поле самому (компонент должен висеть на UI-объекте канваса).")]
    public bool СтроитьПолеСам = true;
    [Tooltip("ФИКСИРОВАННЫЙ размер основного текста (название миссии и заголовок цели). " +
             "Автоподбора нет — кегль одинаков во всех состояниях. Не влезает по высоте — уменьши.")]
    public float размерШрифта = 26f;
    [Tooltip("Фиксированный размер подсказки/прогресса под активной целью (обычно чуть меньше основного).")]
    public float размерПодсказки = 22f;
    [Tooltip("Фиксированный размер таймера (счётчика времени) под названием миссии.")]
    public float размерТаймера = 36f;
    [Tooltip("Приподнять текст: добавляет отступ снизу, из-за чего центрированный блок смещается выше (единицы канваса). Больше — выше.")]
    public float поднятьТекст = 24f;

    private readonly System.Text.StringBuilder _sb = new System.Text.StringBuilder();

    void Start()
    {
        if (Поле == null && СтроитьПолеСам) ПостроитьПоле();
        // Тот же шрифт, что на первом мониторе — и для построенного поля, и для
        // назначенного вручную.
        if (шрифт != null && Поле != null) Поле.font = шрифт;
    }

    // Строит TMP-поле на всю площадь своего RectTransform — чтобы не создавать его
    // вручную в сцене (тот же приём, что у TelemetryPanel). Требует, чтобы компонент
    // висел на UI-объекте под Canvas.
    void ПостроитьПоле()
    {
        var rt = transform as RectTransform;
        if (rt == null)
        {
            Debug.LogWarning("[MissionHudDisplay] Нет RectTransform и не задано Поле — HUD не построен. " +
                             "Повесь компонент на UI-объект под Canvas или задай Поле вручную.", this);
            return;
        }
        var go = new GameObject("MissionText", typeof(RectTransform));
        var trt = (RectTransform)go.transform;
        trt.SetParent(rt, false);
        trt.anchorMin = Vector2.zero; trt.anchorMax = Vector2.one;
        // Отступ снизу = 8 + поднятьТекст: у центрированного по вертикали блока это
        // поднимает текст вверх (нижний край поля выше → центр выше).
        trt.offsetMin = new Vector2(8f, 8f + поднятьТекст); trt.offsetMax = new Vector2(-8f, -8f);

        var t = go.AddComponent<TextMeshProUGUI>();
        t.alignment = TextAlignmentOptions.Center;   // абзац по центру монитора
        t.enableWordWrapping = true;
        // размерШрифта — ЖЕЛАЕМЫЙ размер (верхний предел). Автоподбор только ВНИЗ:
        // короткие экраны стоят на размерШрифта и НЕ распухают крупнее (роста вверх
        // нет — «дыхания», как раньше, не будет), а длинная подсказка ужимается
        // ровно настолько, чтобы влезть по высоте монитора и не уехать за край.
        t.enableAutoSizing = true;
        t.fontSizeMax = размерШрифта;
        t.fontSizeMin = Mathf.Max(6f, размерШрифта * 0.4f);
        t.fontSize = размерШрифта;
        t.raycastTarget = false;
        Поле = t;
    }

    void Update()
    {
        if (Поле == null) return;

        var m = Менеджер != null ? Менеджер : MissionManager.Instance;
        if (m == null) { Поле.text = ""; return; }

        Поле.text = Построить(m);
    }

    string Построить(MissionManager m)
    {
        _sb.Clear();

        // --- Шапка: название миссии + таймер отдельной строкой ---
        _sb.Append("<b>").Append(m.НазваниеМиссии).Append("</b>\n");
        _sb.Append('\n');   // пустая строка перед таймером

        int сек = Mathf.Max(0, Mathf.FloorToInt(m.ВремяМиссии_с));
        float процентТаймера = размерТаймера / Mathf.Max(1f, размерШрифта) * 100f;
        _sb.Append("<size=").Append(процентТаймера.ToString("0.#", System.Globalization.CultureInfo.InvariantCulture))
           .Append("%><color=#").Append(Hex8(ЦветВторостепенный)).Append('>')
           .AppendFormat("{0:00}:{1:00}", сек / 60, сек % 60).Append("</color></size>\n");
        _sb.Append('\n');   // пустая строка после таймера

        // Последовательный показ: на экране один шаг за раз.
        //  1) активная цель ждёт выполнения (циан);
        //  2) выполнил — она загорается зелёным и держится (ДержатьЗелёную_с),
        //     затем плавно гаснет (Угасание_с); пока гаснет — следующую НЕ показываем,
        //     чтобы вышло «загорелось → исчезло → появилась следующая»;
        //  3) когда все цели закрыты и последняя догорела — остаётся «ВЫПОЛНЕНО».

        // Цель, которую сейчас «празднуем»: самая свежая выполненная, ещё не догоревшая.
        MissionObjective празднуем = null;
        float dtПраздник = 0f;
        float окноПраздника = Mathf.Max(0.01f, ДержатьЗелёную_с) + Mathf.Max(0.01f, Угасание_с);
        foreach (var ц in m.Цели)
        {
            if (ц.Состояние != MissionObjectiveState.Completed || ц.ВремяЗавершения_с < 0f) continue;
            float dt = m.ВремяМиссии_с - ц.ВремяЗавершения_с;
            if (dt < 0f || dt >= окноПраздника) continue;
            if (празднуем == null || ц.ВремяЗавершения_с > празднуем.ВремяЗавершения_с)
            {
                празднуем = ц;
                dtПраздник = dt;
            }
        }

        if (празднуем != null)
        {
            // Держим ярко ДержатьЗелёную_с, затем гасим до нуля за Угасание_с.
            float альфа = dtПраздник <= ДержатьЗелёную_с
                ? 1f
                : 1f - Mathf.Clamp01((dtПраздник - ДержатьЗелёную_с) / Mathf.Max(0.01f, Угасание_с));
            Color цвет = ЦветВыполненной; цвет.a = альфа;
            _sb.Append("<color=#").Append(Hex8(цвет)).Append('>')
               .Append(ЗначокВыполнено).Append("  ").Append(празднуем.Заголовок).Append("</color>\n");
            return _sb.ToString();
        }

        // Никого не празднуем — показываем текущую активную цель (или, если миссия
        // застряла, проваленную). Ожидающие цели намеренно скрыты до своей очереди.
        MissionObjective активная = null;
        MissionObjective проваленная = null;
        foreach (var ц in m.Цели)
        {
            if (ц.Состояние == MissionObjectiveState.Active && активная == null) активная = ц;
            if (ц.Состояние == MissionObjectiveState.Failed) проваленная = ц;
        }

        if (активная != null)
        {
            string hex = Hex8(ЦветАктивной);
            _sb.Append("<color=#").Append(hex).Append('>')
               .Append(ЗначокАктивна).Append("  ").Append(активная.Заголовок).Append("</color>\n");

            // Под активной целью — живой прогресс (напр. «Обнаружено 1/2 трещин»), а
            // пока его нет — подсказка. Мельче основного текста, как подпункт.
            string суб = !string.IsNullOrEmpty(активная.Прогресс) ? активная.Прогресс : активная.Подсказка;
            if (!string.IsNullOrEmpty(суб))
            {
                // Размер подсказки задаём ДОЛЕЙ от основного (14 из 16 ≈ 87,5%), чтобы
                // при автоподборе вниз она ужималась вместе со всем текстом и тоже влезала.
                float процентПодсказки = размерПодсказки / Mathf.Max(1f, размерШрифта) * 100f;
                _sb.Append("<size=")
                   .Append(процентПодсказки.ToString("0.#", System.Globalization.CultureInfo.InvariantCulture))
                   .Append("%><color=#").Append(hex).Append('>')
                   .Append(суб).Append("</color></size>\n");
            }
        }
        else if (m.Завершена)
        {
            // Все цели закрыты и последняя (зелёная) догорела — остаётся финальная
            // надпись насовсем. Название миссии сверху при этом сохраняется.
            _sb.Append("<b><color=#").Append(Hex8(ЦветВыполненной)).Append('>')
               .Append(ЗначокВыполнено).Append(" Миссия закончена</color></b>\n");
        }
        else if (проваленная != null)
        {
            _sb.Append("<color=#").Append(Hex8(ЦветПровала)).Append('>')
               .Append(ЗначокПровал).Append("  ").Append(проваленная.Заголовок).Append("</color>\n");
        }

        return _sb.ToString();
    }

    // 8-значный HEX (RRGGBBAA) — с альфой, чтобы TMP гасил выполненные строки.
    static string Hex8(Color c) => ColorUtility.ToHtmlStringRGBA(c);
}
