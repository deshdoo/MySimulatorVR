using UnityEngine;
using UnityEngine.Events;

// Маркер дефекта на трубопроводе. Ставится пустым объектом (или на видимой
// метке дефекта) в нужной точке трубы. Сам факт обнаружения выставляет RovScanner
// (осмотр = близость + линия визирования + свет + выдержка) — этот компонент
// только хранит тип/описание дефекта и реагирует на обнаружение: подсвечивается,
// дёргает UnityEvent (звук/партиклы/подпись — что повесишь в инспекторе).
//
// Настройка: пустой объект в точке дефекта; при желании — дочерний меш-метка
// (пятно/трещина) в поле «Подсветка», чтобы обнаружение было видно.
[DisallowMultipleComponent]
public class PipelineDefect : MonoBehaviour
{
    // Новые типы — только в конец: в сохранённых миссиях тип хранится числом.
    // Последние пять — повреждения магистрали в бетоне (МагистральныйТрубопровод).
    public enum ТипДефекта { Утечка, Трещина, Коррозия, Провис, СколБетона, ПовреждениеСтыка, Анод, ПостороннийПредмет, СледЯкоря }

    // Название для журнала и отчёта.
    public static string Название(ТипДефекта т) => т switch
    {
        ТипДефекта.Утечка => "Утечка газа",
        ТипДефекта.Трещина => "Трещина",
        ТипДефекта.Коррозия => "Коррозия",
        ТипДефекта.Провис => "Провис",
        ТипДефекта.СколБетона => "Скол бетона",
        ТипДефекта.ПовреждениеСтыка => "Повреждён стык",
        ТипДефекта.Анод => "Анод",
        ТипДефекта.ПостороннийПредмет => "Посторонний предмет",
        ТипДефекта.СледЯкоря => "Удар якоря",
        _ => т.ToString()
    };

    [Header("Дефект")]
    public ТипДефекта Тип = ТипДефекта.Трещина;
    [Tooltip("Пояснение для журнала/HUD (необязательно). Пусто — берётся название типа.")]
    public string Описание = "";
    [Tooltip("Радиус, в котором сканер вообще «видит» этот дефект, м")]
    public float РадиусОбнаружения = 3f;

    [Header("Подсветка при обнаружении")]
    [Tooltip("Меш-метка дефекта: загорится, когда дефект обнаружен. Необязательно.")]
    public Renderer Подсветка;
    public Color ЦветОбнаружения = new Color(1f, 0.4f, 0.2f);
    [Range(0f, 3f)] public float ЯркостьПодсветки = 1.2f;
    [Tooltip("Сколько секунд трещина вспыхивает при осмотре, затем плавно гаснет.")]
    public float ВремяВспышки = 2f;
    [Tooltip("Светящийся контур по границе повреждённого места — вспыхивает при снимке. " +
             "У повреждений магистрали его строит МагистральныйТрубопровод (своего меша у метки нет).")]
    [HideInInspector] public LineRenderer[] Контур;

    [Tooltip("Доп. реакция на обнаружение — звук, партиклы, подпись (вешай в инспекторе)")]
    public UnityEvent ПриОбнаружении;

    public bool Обнаружен { get; private set; }

    // Человекочитаемая метка для журнала/HUD.
    public string Метка => string.IsNullOrEmpty(Описание) ? Название(Тип) : $"{Название(Тип)}: {Описание}";

    private Material _mat;
    private float _вспышкаОсталось;   // сек до конца вспышки осмотра
    private float _задержка;          // контур загорается чуть позже снимка — на фото его нет

    void Awake()
    {
        Мат();   // попытка взять материал сразу; при необходимости добёрём лениво
    }

    // Лениво получает материал метки подсветки. Если поле Подсветка пустое — берём
    // собственный рендерер дефекта (у квада-трещины он и есть), поэтому подсветка
    // работает без ручной привязки. Рендерер может появиться после Awake — отсюда лень.
    Material Мат()
    {
        if (_mat != null) return _mat;
        if (Подсветка == null)
            foreach (var r in GetComponentsInChildren<Renderer>())
                if (!(r is LineRenderer)) { Подсветка = r; break; }   // линии контура — не метка
        if (Подсветка != null) _mat = Подсветка.material;
        return _mat;
    }

    void ПрименитьЭмиссию(Color c)
    {
        var m = Мат();
        if (m == null) return;
        m.EnableKeyword("_EMISSION");
        // БЕЗ этого флага URP часто игнорирует эмиссию, заданную в рантайме — самая
        // частая причина «поставил _EmissionColor в коде, а трещина не светится».
        m.globalIlluminationFlags = MaterialGlobalIlluminationFlags.RealtimeEmissive;
        if (m.HasProperty("_EmissionColor")) m.SetColor("_EmissionColor", c);
    }

    // Подсветка НАВЕДЕНИЯ: разгорается по мере того, как сканер держит дефект в
    // прицеле (доля 0..1) — наглядная обратная связь «сканирую это место». Отдельно
    // от финального Обнаружить(): отвёл камеру, не досчитав — сканер гасит (доля 0).
    public void ПодсветитьНаведение(float доля)
    {
        if (Обнаружен) return;
        ПрименитьЭмиссию(ЦветОбнаружения * (ЯркостьПодсветки * Mathf.Clamp01(доля)));
        ПоказатьКонтур(0.7f * Mathf.Clamp01(доля));
    }

    // Яркость контура 0..1: сердцевина и мягкий ореол вокруг неё.
    void ПоказатьКонтур(float яркость)
    {
        if (Контур == null) return;
        Color c = ЦветОбнаружения;
        for (int i = 0; i < Контур.Length; i++)
        {
            var lr = Контур[i];
            if (lr == null) continue;
            bool ореол = lr.name.EndsWith("ореол");
            c.a = яркость * (ореол ? 0.15f : 0.55f);   // полупрозрачно: видно и контур, и что под ним
            lr.enabled = яркость > 0.01f;
            lr.startColor = lr.endColor = c;
        }
    }

    // Вызывается сканером в момент успешного осмотра — трещина ВСПЫХИВАЕТ на пару
    // секунд (ВремяВспышки) и гаснет, а не горит постоянно.
    public void Обнаружить()
    {
        if (Обнаружен) return;
        Обнаружен = true;
        _вспышкаОсталось = ВремяВспышки;
        _задержка = 0.15f;
        ПоказатьКонтур(0f);
        Debug.Log($"[Осмотр] Обнаружен дефект — {Метка}");
        ПриОбнаружении?.Invoke();
    }

    void Update()
    {
        if (_вспышкаОсталось <= 0f) return;
        _вспышкаОсталось -= Time.deltaTime;
        float доля = ВремяВспышки > 0.01f ? Mathf.Clamp01(_вспышкаОсталось / ВремяВспышки) : 0f;
        ПрименитьЭмиссию(ЦветОбнаружения * (ЯркостьПодсветки * доля));   // ярко → плавно в ноль

        // Контур: после снимка — две быстрые вспышки, затем ровно светится и гаснет.
        if (_задержка > 0f) { _задержка -= Time.deltaTime; ПоказатьКонтур(0f); return; }
        float прошло = ВремяВспышки - _вспышкаОсталось;
        float мигание = прошло < 0.6f ? 0.55f + 0.45f * Mathf.Cos(прошло * Mathf.PI * 2f / 0.3f) : 1f;
        ПоказатьКонтур(Mathf.Clamp01(доля * 1.6f) * мигание);
    }

    // Наглядный радиус в редакторе.
    void OnDrawGizmosSelected()
    {
        Gizmos.color = new Color(1f, 0.5f, 0.2f, 0.5f);
        Gizmos.DrawWireSphere(transform.position, РадиусОбнаружения);
    }
}
