using UnityEngine;
using UnityEngine.Events;

// Маркер дефекта на трубопроводе. Ставится пустым объектом (или на видимой
// метке дефекта) в нужной точке трубы. Сам факт обнаружения выставляет RovScanner
// (осмотр = близость + линия визирования + свет + выдержка) — этот компонент
// только хранит тип/описание дефекта и реагирует на обнаружение: подсвечивается,
// дёргает UnityEvent (звук/партиклы/подпись — что повесишь в инспекторе).
//
// Настройка: пустой объект в точке дефекта; при желании — дочерний меш-метка
// (пятно/трещина) в поле «Подсветка», чтобы обнаружение было видно.
[DisallowMultipleComponent]
public class PipelineDefect : MonoBehaviour
{
    public enum ТипДефекта { Утечка, Трещина, Коррозия, Провис }

    [Header("Дефект")]
    public ТипДефекта Тип = ТипДефекта.Трещина;
    [Tooltip("Пояснение для журнала/HUD (необязательно). Пусто — берётся название типа.")]
    public string Описание = "";
    [Tooltip("Радиус, в котором сканер вообще «видит» этот дефект, м")]
    public float РадиусОбнаружения = 3f;

    [Header("Подсветка при обнаружении")]
    [Tooltip("Меш-метка дефекта: загорится, когда дефект обнаружен. Необязательно.")]
    public Renderer Подсветка;
    public Color ЦветОбнаружения = new Color(1f, 0.4f, 0.2f);
    [Range(0f, 3f)] public float ЯркостьПодсветки = 1.2f;

    [Tooltip("Доп. реакция на обнаружение — звук, партиклы, подпись (вешай в инспекторе)")]
    public UnityEvent ПриОбнаружении;

    public bool Обнаружен { get; private set; }

    // Человекочитаемая метка для журнала/HUD.
    public string Метка => string.IsNullOrEmpty(Описание) ? Тип.ToString() : $"{Тип}: {Описание}";

    private Material _mat;

    void Awake()
    {
        if (Подсветка != null) _mat = Подсветка.material;
    }

    // Вызывается сканером в момент успешного осмотра.
    public void Обнаружить()
    {
        if (Обнаружен) return;
        Обнаружен = true;

        if (_mat != null)
        {
            _mat.EnableKeyword("_EMISSION");
            _mat.SetColor("_EmissionColor", ЦветОбнаружения * ЯркостьПодсветки);
        }

        Debug.Log($"[Осмотр] Обнаружен дефект — {Метка}");
        ПриОбнаружении?.Invoke();
    }

    // Наглядный радиус в редакторе.
    void OnDrawGizmosSelected()
    {
        Gizmos.color = new Color(1f, 0.5f, 0.2f, 0.5f);
        Gizmos.DrawWireSphere(transform.position, РадиусОбнаружения);
    }
}
