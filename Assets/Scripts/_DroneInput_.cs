public static class DroneInput
{
    public static float forward = 0f;   // вперёд/назад  (-1 до 1)
    public static float vertical = 0f;  // вверх/вниз    (-1 до 1)
    public static float yaw = 0f;       // поворот       (-1 до 1)

    // Боковой ход (лаг). У ROV с векторной схемой горизонтальные движители стоят
    // под углом и дают тягу вбок без разворота корпуса. Нужен для удержания
    // позиции в течении: поток редко идёт точно вдоль курса, и боковую
    // составляющую сноса иначе парировать нечем.
    // Рычагами пока не управляется — пишет только автопилот.
    public static float lateral = 0f;   // вправо/влево  (-1 до 1)
}
