// =============================================================================
// RovHeadingSensor.cs
// -----------------------------------------------------------------------------
// Датчик курса НПА (курсоуказатель), смоделированный как реальная связка
// «гироскоп + магнитный компас + комплементарный фильтр», а не чтение угла
// поворота из движка.
//
// ГЛАВНОЕ ОТЛИЧИЕ ОТ ДАТЧИКА ГЛУБИНЫ. Глубину датчик давления получает по
// ОБРАТИМОЙ формуле (P = ρgh), поэтому там показание = истина + погрешность.
// Здесь иначе: гироскоп меряет НЕ угол, а угловую СКОРОСТЬ ω, а курс
// получается ИНТЕГРИРОВАНИЕМ этой скорости по времени:
//
//        θ(t) = θ₀ + ∫ ω dt
//
// Из-за интегрирования ошибка НЕ мгновенная, а НАКАПЛИВАЕТСЯ («имеет память»):
// крошечное постоянное смещение нуля гироскопа b даёт линейно растущий увод
// курса  b·t  — это и есть ДРЕЙФ. Его нельзя воспроизвести добавлением шума к
// истинному курсу — потому что здесь ошибка складывается сама с собой во времени.
//
// ЧЕМ ЛЕЧАТ ДРЕЙФ. Гироскоп гладкий и быстрый, но уползает. Магнитный компас,
// наоборот, даёт АБСОЛЮТНЫЙ курс (не дрейфует), но шумит и врёт вблизи металла
// и при работе движителей. Их объединяет КОМПЛЕМЕНТАРНЫЙ ФИЛЬТР: на быстрых
// изменениях верим гироскопу (плавно), на медленных — подтягиваем к компасу
// (убираем накопленный дрейф):
//
//        θ = α·(θ_пред + ω·dt) + (1−α)·θ_компас,   α = τ/(τ+dt),  α → 1
//
// Три величины для наглядного графика:
//   • headingTrue_deg  — истина (движок),
//   • headingGyro_deg  — курс по ОДНОМУ гироскопу без коррекции (дрейфует, уползает),
//   • heading_deg      — сведённое показание (фильтр держит его у истины).
// На одном графике видно, ЗАЧЕМ нужна коррекция: серая линия гиро уходит, а
// сведённая остаётся рядом с правдой.
//
// DefaultExecutionOrder(50): считается ПОСЛЕ RovSystemsSimulator — сначала
// движок кладёт истинный курс, потом прибор его измеряет. Без этого компонента
// симулятор оставляет heading_deg = истине (обратная совместимость).
//
// Настройка: повесить на объект НПА (там же, где RovSystemsSimulator).
// =============================================================================

using UnityEngine;

[DisallowMultipleComponent]
[DefaultExecutionOrder(50)]
public class RovHeadingSensor : MonoBehaviour
{
    [Header("Гироскоп (меряет угловую скорость)")]
    [Tooltip("Смещение нуля гироскопа (bias), град/с. Прибор показывает ненулевую " +
             "скорость даже в покое → при интегрировании даёт ДРЕЙФ курса b·t. " +
             "0.3 град/с ≈ увод на 18° за минуту без коррекции.")]
    public float СмещениеНуля_градс = 0.3f;
    [Tooltip("СКО шума измерения угловой скорости, град/с. Интегрируется в случайное " +
             "блуждание курса (растёт как σ·√t).")]
    public float ШумСКО_градс = 0.1f;
    [Tooltip("Ошибка масштабного коэффициента (доля): измеренная скорость = (1+ошибка)·истинная. " +
             "0 — идеальный масштаб.")]
    public float ОшибкаМасштаба = 0.0f;

    [Header("Магнитный компас (даёт абсолютный курс)")]
    [Tooltip("Магнитное склонение, град — постоянный сдвиг между магнитным и истинным " +
             "севером в точке работы. Систематическая ошибка компаса.")]
    public float МагнитноеСклонение_град = 0.0f;
    [Tooltip("СКО шума компаса, град. Компас не дрейфует, но зашумлён.")]
    public float ШумСКО_град = 2.0f;
    [Tooltip("Доп. помеха компаса при манёвре, град СКО: магнитное поле искажают " +
             "токи движителей. Домножается на величину команды рысканья (|yaw|).")]
    public float ПомехаОтМанёвра_град = 3.0f;

    [Header("Комплементарный фильтр (сводит гиро и компас)")]
    [Tooltip("Постоянная времени фильтра τ, с. Больше τ — больше доверяем гироскопу " +
             "(глаже, но медленнее убирается дрейф); меньше — быстрее тянем к компасу " +
             "(меньше дрейф, но лезет шум компаса). α = τ/(τ+dt).")]
    public float ПостояннаяФильтра_с = 5.0f;

    private bool  _иниц;
    private float _прошлыйКурсИстина;  // для оценки истинной угловой скорости
    private float _курсГиро;           // интеграл только гироскопа (дрейфует)
    private float _курсФильтр;         // сведённое показание (гиро + компас)

    void FixedUpdate()
    {
        float dt = Time.fixedDeltaTime;
        if (dt <= 0f) return;

        float курсИстина = RovSystems.headingTrue_deg;

        // Инициализация: приборы стартуют «сведёнными» с истиной, дрейф копится с нуля.
        if (!_иниц)
        {
            _курсГиро = курсИстина;
            _курсФильтр = курсИстина;
            _прошлыйКурсИстина = курсИстина;
            _иниц = true;
            RovSystems.heading_deg = _курсФильтр;
            RovSystems.headingGyro_deg = _курсГиро;
            return;
        }

        // 1. Истинная угловая скорость. DeltaAngle корректно обрабатывает переход
        //    через 360°/0° (иначе на «стыке» скорость подскочила бы на ±360/dt).
        float ω_истина = Mathf.DeltaAngle(_прошлыйКурсИстина, курсИстина) / dt;
        _прошлыйКурсИстина = курсИстина;

        // 2. ГИРОСКОП меряет скорость с погрешностями: масштаб, смещение нуля, шум.
        float ω_гиро = (1f + ОшибкаМасштаба) * ω_истина
                     + СмещениеНуля_градс
                     + ГауссовШум() * ШумСКО_градс;

        // 3. Курс по одному гироскопу — ИНТЕГРАЛ скорости. Из-за смещения нуля
        //    он уползает от истины (дрейф). Держим в [0,360).
        _курсГиро = Mathf.Repeat(_курсГиро + ω_гиро * dt, 360f);

        // 4. КОМПАС — абсолютный курс: истина + склонение + шум (+ помеха при манёвре,
        //    когда токи движителей искажают магнитное поле).
        float помеха = ПомехаОтМанёвра_град * Mathf.Clamp01(Mathf.Abs(DroneInput.yaw));
        float курсКомпас = курсИстина + МагнитноеСклонение_град
                         + ГауссовШум() * (ШумСКО_град + помеха);

        // 5. КОМПЛЕМЕНТАРНЫЙ ФИЛЬТР. Прогноз гироскопом (гладко), затем подтяжка к
        //    компасу на долю (1−α) кратчайшим угловым путём (убирает дрейф).
        float α = ПостояннаяФильтра_с / (ПостояннаяФильтра_с + dt);
        float прогноз = _курсФильтр + ω_гиро * dt;
        _курсФильтр = Mathf.Repeat(прогноз + (1f - α) * Mathf.DeltaAngle(прогноз, курсКомпас), 360f);

        // Публикуем показания. heading_deg — сведённое (его видят приборы),
        // headingGyro_deg — только гиро (для наглядного графика «зачем коррекция»).
        RovSystems.heading_deg = _курсФильтр;
        RovSystems.headingGyro_deg = _курсГиро;
    }

    // Гауссов (нормальный) шум методом Бокса—Мюллера — как в RovDepthSensor.
    static float ГауссовШум()
    {
        float u1 = Mathf.Max(1e-6f, Random.value);
        float u2 = Random.value;
        return Mathf.Sqrt(-2f * Mathf.Log(u1)) * Mathf.Cos(2f * Mathf.PI * u2);
    }
}
