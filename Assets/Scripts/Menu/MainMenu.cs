    // Двойное нажатие для необратимых действий: первое — «ТОЧНО?», второе в течение 3 с — выполнить.
    void ПодтверждаемаяКнопка(TMP_Text надпись, string ключ, string обычный, System.Action действие)
    {
        var и = надпись.transform.parent.GetComponent<UnityEngine.XR.Interaction.Toolkit.Interactables.XRSimpleInteractable>();
        if (и == null) return;
        и.selectEntered.RemoveAllListeners();
        и.hoverEntered.RemoveAllListeners();
        void Нажатие()
        {
            if (_чтоПодтверждаем == ключ && Time.unscaledTime < _подтвердитьДо)
            {
                _подтвердитьДо = -1f; _чтоПодтверждаем = null;
                действие();
                return;
            }
            _чтоПодтверждаем = ключ; _подтвердитьДо = Time.unscaledTime + 3f;
            надпись.text = "<b>ТОЧНО? ЕЩЁ РАЗ</b>";
            StartCoroutine(ВернутьНадпись(надпись, обычный, ключ));
        }
        float след = 0f;
        void Защищённо() { if (Time.unscaledTime < след) return; след = Time.unscaledTime + 0.3f; UiSound.Клик(); Нажатие(); }
        и.selectEntered.AddListener(_ => Защищённо());
        и.hoverEntered.AddListener(a => { if (a.interactorObject is UnityEngine.XR.Interaction.Toolkit.Interactors.XRPokeInteractor) Защищённо(); });
    }

    IEnumerator ВернутьНадпись(TMP_Text t, string текст, string ключ)
    {
        yield return new WaitForSecondsRealtime(3f);
        if (t != null && _чтоПодтверждаем == ключ) { t.text = текст; _чтоПодтверждаем = null; }
        else if (t != null && _чтоПодтверждаем == null) t.text = текст;
    }

