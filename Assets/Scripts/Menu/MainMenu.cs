        var к = _повтор.Текущий;
        _состояниеПовтора.text = (_повтор.Пауза ? "пауза" : $"идёт ×{_повтор.Скорость:0}") +
                                 $"   ·   свет {(к.свет ? "вкл" : "выкл")}   ·   клешня {(к.клешня ? "сжата" : "разжата")}";
    }

