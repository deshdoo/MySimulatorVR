    void НачатьМиссию() { MissionResume.Сбросить(); StartCoroutine(ВыйтиВМиссию(null)); }

    // Испытательные манёвры: та же сцена, но вместо миссии — программа опытов
    // (RovManeuverTests), с текущими настройками «Физики»; в архив не пишется.
    void НачатьИспытания() { MissionResume.Сбросить(); StartCoroutine(ВыйтиВМиссию(null, true)); }

    // Продолжить сохранённую незаконченную миссию с того же места.
    void ПродолжитьМиссию(MissionArchive.Запись з) => StartCoroutine(ВыйтиВМиссию(з));

    IEnumerator ВыйтиВМиссию(MissionArchive.Запись продолжить, bool испытания = false)
    {
        yield return Затемнить(true);
        // Новая миссия — с текущими настройками «Физики», продолжение — с физикой из своего
        // сохранения. До восстановления — чтобы не затереть сохранённый заряд.
        if (продолжить != null) PhysicsSettings.Применить(продолжить.физика);
        else PhysicsSettings.Применить();
        if (продолжить != null) MissionResume.ДоСтарта(продолжить);   // сцена ещё заморожена
        ЗакончитьПовторТихо();
        ОсвободитьТекстуры();
        _панель?.Уничтожить(); _панель = null;
        if (_диорама != null) { _диорама.Убрать(); _диорама = null; }
        if (_риг != null) { _риг.transform.SetPositionAndRotation(_ригПоз, _ригПов); ЗаморозитьЛокомоцию(false); }
        СкрытьНастоящийАппарат(false);
        СкрытьДругиеСцены(false);
        if (испытания) TelemetryCsvLogger.ПрефиксСледующего = "испытания";
        _заморозка.Разморозить();
        Открыто = false;
        if (испытания)
        {
            var rov = FindFirstObjectByType<RovController>();
            if (rov != null) rov.gameObject.AddComponent<RovManeuverTests>();
        }
        if (продолжить != null) StartCoroutine(MissionResume.ПослеСтарта());
        yield return null;
        yield return Затемнить(false);
        if (_затемнениеКорень != null) Destroy(_затемнениеКорень);
    }

    void ЗакончитьПовторТихо()
    {
        if (_повтор != null) { _повтор.Убрать(); _повтор = null; }
        if (_пультПовтора != null) { _пультПовтора.Уничтожить(); _пультПовтора = null; }
    }

    void ЗапуститьМиссиюСразу()
    {
        _заморозка.Разморозить();
        Открыто = false;
    }

