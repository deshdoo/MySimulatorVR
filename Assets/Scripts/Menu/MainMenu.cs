// Главное меню симулятора — появляется при запуске, как в играх.
//
// Отдельной сцены меню нет: при загрузке подводной сцены Main она сразу
// замораживается (SceneFreeze — до Start её скриптов, так что миссия ещё не
// началась), а оператор переносится из кабины на дно к трубе — в подводную
// диораму (MenuDiorama). Там висит панель меню:
//   • НАЧАТЬ МИССИЮ — затемнение, возврат в кабину, разморозка: миссия стартует с нуля;
//   • РЕЗУЛЬТАТЫ    — архив пройденных миссий (MissionArchive): список, подробности
//                     со снимками, 3D-повтор на голографическом столе, удаление
//                     одной записи или всего архива (чтобы не засорять папку игры);
//   • НАСТРОЙКИ     — звук; управление: выбор системы (Quest / ПК VR / клавиатура)
//                     карточками с иконками, схема управления и переназначение клавиш;
//                     физика: масса, тяга, плавучесть, батарея, вода и течение (PhysicsSettings);
//   • ВЫХОД.
//
// Компонент создаётся сам при запуске (RuntimeInitializeOnLoadMethod) и живёт
// между перезагрузками сцен. «ЗАНОВО» из окна итогов ставит ПропуститьМенюОдинРаз —
// тогда после перезагрузки миссия начинается сразу, без меню.
public class MainMenu : MonoBehaviour
{
    public static bool ПропуститьМенюОдинРаз;
    public static bool Открыто { get; private set; }

    const string ИмяСценыМиссии = "Main";
    const float W = 1000f, H = 640f;

    enum Экран { Главный, Результаты, Подробно, Настройки, Повтор }
    enum Вкладка { Звук, Управление, Физика }

    readonly SceneFreeze _заморозка = new SceneFreeze();
    Scene _сцена;
    XROrigin _риг;
    Transform _голова;
    Vector3 _ригПоз; Quaternion _ригПов;
    readonly List<(Renderer r, bool был)> _скрытые = new List<(Renderer, bool)>();
    TMP_FontAsset _шрифт;

    MenuDiorama _диорама;
    Texture2D _постер;
    VrPanel _панель;
    RectTransform _экранRt;
    Image _фонПанели;
    Экран _экран;
    Вкладка _вкладка = Вкладка.Звук;
    int _страница;
    List<MissionArchive.Запись> _архив;
    readonly HashSet<string> _выбранные = new HashSet<string>();   // отмеченные для удаления
    MissionArchive.Запись _выбранная;
    readonly List<Texture2D> _загруженные = new List<Texture2D>();
    Key? _ждёмКлавишу;   // исходная клавиша, которой назначаем новую
    int _ждёмСКадра;     // клавиши ловим только со СЛЕДУЮЩЕГО кадра: в эмуляторе само нажатие кнопки — это клавиша T
    string _ждёмКнопку;  // название действия контроллера, которому ждём новую кнопку
    InputActionRebindingExtensions.RebindingOperation _операция;
    float _подтвердитьДо = -1f; string _чтоПодтверждаем;

    MenuReplayTable _повтор;
    VrPanel _пультПовтора;
    TMP_Text _времяПовтора, _состояниеПовтора;
    Image _полосаПовтора;

    Image _затемнение;
    GameObject _затемнениеКорень;

    [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.AfterSceneLoad)]
    static void Создать()
    {
        if (FindFirstObjectByType<MainMenu>() != null) return;
        var go = new GameObject("MainMenu");
        DontDestroyOnLoad(go);
        var меню = go.AddComponent<MainMenu>();
        // Play запущен прямо из сцены Main (она уже загружена) — подхватить её сразу.
        var main = SceneManager.GetSceneByName(ИмяСценыМиссии);
        if (main.IsValid() && main.isLoaded) меню.НаЗагрузку(main, LoadSceneMode.Single);
    }

    void OnEnable() { SceneManager.sceneLoaded += НаЗагрузку; _экземпляр = this; }
    void OnDisable() => SceneManager.sceneLoaded -= НаЗагрузку;

    void НаЗагрузку(Scene сцена, LoadSceneMode режим)
    {
        if (сцена.name != ИмяСценыМиссии) return;
        Debug.Log($"[Меню] Загружена сцена миссии (пропустить меню: {ПропуститьМенюОдинРаз}).");
        if (ПропуститьМенюОдинРаз) { ПропуститьМенюОдинРаз = false; return; }
        _сцена = сцена;
        // Замораживаем СРАЗУ — до Start скриптов сцены: миссия не начнётся, пока в меню.
        _заморозка.Заморозить(сцена);
        Открыто = true;
        StartCoroutine(Войти());
    }

    IEnumerator Войти()
    {
        // Дать XR-ригу кабины проснуться и получить трекинг.
        yield return null; yield return null;
        _риг = FindFirstObjectByType<XROrigin>();
        Debug.Log($"[Меню] Вход в меню: найден XR Origin = {(_риг != null ? _риг.name : "нет")}.");
        if (_риг == null || _риг.Camera == null)
        {
            Debug.LogWarning("[Меню] Не найден XR Origin — меню пропущено, миссия запускается сразу.");
            ЗапуститьМиссиюСразу();
            yield break;
        }
        _голова = _риг.Camera.transform;
        var hud = FindFirstObjectByType<MissionHudDisplay>();
        _шрифт = hud != null ? hud.шрифт : null;

        СоздатьЗатемнение();
        _затемнение.color = Color.black;

        _ригПоз = _риг.transform.position; _ригПов = _риг.transform.rotation;
        СкрытьНастоящийАппарат(true);
        СкрытьДругиеСцены(true);

        var go = new GameObject("Диорама");
        SceneManager.MoveGameObjectToScene(go, _сцена);
        _диорама = go.AddComponent<MenuDiorama>();
        _диорама.Построить(_голова, _шрифт);

        // Переносим оператора: камера — в точку обзора диорамы, лицом к трубе.
        Debug.Log($"[Меню] Риг «{_риг.name}» (сцена {_риг.gameObject.scene.name}), камера «{_голова.name}» в {_голова.position}. " +
                  $"Точка обзора {_диорама.Глаз}, труба {_диорама.ЦентрТрубы}.");
        ЗаморозитьЛокомоцию(true);
        ПеренестиРиг();
        yield return null;
        Debug.Log($"[Меню] После переноса камера в {_голова.position} (до цели {Vector3.Distance(_голова.position, _диорама.Глаз):F2} м).");
        StartCoroutine(СледитьЗаРигом());

        ПостроитьПанель();
        ПоказатьЭкран(Экран.Главный);
        yield return Затемнить(false);
    }

    // Гравитация и перемещение рига на время меню выключаются: в кабине оператор
    // стоит на её полу, а дно подводной сцены (слой Underwater) с телом рига не
    // сталкивается — без этого он проваливался сквозь грунт. При входе в миссию —
    // всё как было.
    readonly List<Behaviour> _локомоция = new List<Behaviour>();
    CharacterController _тело; bool _телоБыло;

    void ЗаморозитьЛокомоцию(bool заморозить)
    {
        if (заморозить)
        {
            foreach (var b in _риг.GetComponentsInChildren<Behaviour>(true))
            {
                if (b == null || !b.enabled) continue;
                string n = b.GetType().Name;
                if (n.Contains("Gravity") || n.Contains("MoveProvider") || n.Contains("TurnProvider") ||
                    n.Contains("Teleportation") || n.Contains("Climb") || n.Contains("BodyTransformer") || n.Contains("Jump"))
                { b.enabled = false; _локомоция.Add(b); }
            }
            _тело = _риг.GetComponentInChildren<CharacterController>();
            if (_тело != null) { _телоБыло = _тело.enabled; _тело.enabled = false; }
            Debug.Log($"[Меню] Выключено на время меню: {_локомоция.Count} компонент(ов) локомоции{(_тело != null ? " + CharacterController" : "")}.");
        }
        else
        {
            foreach (var b in _локомоция) if (b != null) b.enabled = true;
            _локомоция.Clear();
            if (_тело != null) { _тело.enabled = _телоБыло; _тело = null; }
        }
    }

    void ПеренестиРиг()
    {
        _риг.MatchOriginUpCameraForward(Vector3.up, _диорама.Вперёд);
        _риг.MoveCameraToWorldLocation(_диорама.Глаз);
    }

    // Защита: если что-то в риге (локомоция, симулятор, скрипт кабины) возвращает его
    // на место в первые секунды — переставляем снова и пишем в лог, кто мешает.
    IEnumerator СледитьЗаРигом()
    {
        bool сообщили = false;
        for (float t = 0f; t < 3f && Открыто && _диорама != null; t += Time.unscaledDeltaTime)
        {
            if (_экран != Экран.Повтор && Vector3.Distance(_голова.position, _диорама.Глаз) > 0.5f)
            {
                if (!сообщили)
                {
                    var компоненты = new System.Text.StringBuilder();
                    foreach (var mb in _риг.GetComponentsInChildren<MonoBehaviour>())
                        if (mb != null && mb.enabled) компоненты.Append(mb.GetType().Name).Append(", ");
                    Debug.LogWarning($"[Меню] Риг вернули назад (камера в {_голова.position}) — переставляю снова. Компоненты рига: {компоненты}");
                    сообщили = true;
                }
                ПеренестиРиг();
            }
            yield return null;
        }
    }

    // Был ли рендерер аппарата видим ДО того, как меню спрятало аппарат.
    static MainMenu _экземпляр;
    public static bool БылВиден(Renderer r)
    {
        if (_экземпляр != null)
            foreach (var (рр, был) in _экземпляр._скрытые) if (рр == r) return был;
        return r.enabled;
    }

    void СкрытьНастоящийАппарат(bool скрыть)
    {
        if (скрыть)
        {
            var rov = FindFirstObjectByType<RovController>();
            if (rov == null) return;
            foreach (var r in rov.GetComponentsInChildren<Renderer>(true)) { _скрытые.Add((r, r.enabled)); r.enabled = false; }
        }
        else
        {
            foreach (var (r, был) in _скрытые) if (r != null) r.enabled = был;
            _скрытые.Clear();
        }
    }

    // Кабина (и всё из других сцен, кроме самого рига) на время меню прячется:
    // меню стоит в другой точке мира, и кабина иначе виднелась вдали сквозь воду.
    // Всё меню (диорама, панель, повтор) создаётся в сцене миссии — его не трогаем.
    readonly List<(Renderer r, bool был)> _скрытыеСцены = new List<(Renderer, bool)>();
    readonly List<(Canvas c, bool был)> _скрытыеХолсты = new List<(Canvas, bool)>();

    void СкрытьДругиеСцены(bool скрыть)
    {
        if (скрыть)
        {
            for (int i = 0; i < SceneManager.sceneCount; i++)
            {
                var сц = SceneManager.GetSceneAt(i);
                if (!сц.isLoaded || сц == _сцена) continue;
                foreach (var root in сц.GetRootGameObjects())
                {
                    foreach (var r in root.GetComponentsInChildren<Renderer>(true))
                        if (r.enabled && !r.transform.IsChildOf(_риг.transform)) { _скрытыеСцены.Add((r, true)); r.enabled = false; }
                    foreach (var c in root.GetComponentsInChildren<Canvas>(true))
                        if (c.enabled && !c.transform.IsChildOf(_риг.transform)) { _скрытыеХолсты.Add((c, true)); c.enabled = false; }
                }
            }
            Debug.Log($"[Меню] Спрятано из других сцен: {_скрытыеСцены.Count} рендереров, {_скрытыеХолсты.Count} холстов.");
        }
        else
        {
            foreach (var (r, был) in _скрытыеСцены) if (r != null) r.enabled = был;
            foreach (var (c, был) in _скрытыеХолсты) if (c != null) c.enabled = был;
            _скрытыеСцены.Clear(); _скрытыеХолсты.Clear();
        }
    }

    // «Поводок»: в меню оператор может отойти от точки обзора не дальше радиуса —
    // шаг дальше (в комнате или в эмуляторе) возвращает риг обратно на границу.
    // В 3D-повторе радиус больше — чтобы можно было обойти голографический стол.
    const float РадиусМеню = 1.0f, РадиусПовтора = 1.8f;

    void ДержатьУМеню()
    {
        if (!Открыто || _диорама == null || _риг == null || _голова == null) return;
        Vector3 d = _голова.position - _диорама.Глаз;
        float длина = d.magnitude, радиус = _экран == Экран.Повтор ? РадиусПовтора : РадиусМеню;
        if (длина > радиус) _риг.transform.position -= d * (1f - радиус / длина);
    }

    // ---------------- Панель ----------------

    void ПостроитьПанель()
    {
        const float ширина = 1.3f;
        _панель = new VrPanel("ГлавноеМеню", W, H, ширина, _сцена, _шрифт, false);
        Vector3 f = _диорама.Вперёд;
        Vector3 поз = _голова.position + f * 1.55f + Vector3.down * 0.15f;
        var пов = Quaternion.LookRotation(поз - _голова.position, Vector3.up);
        _панель.Корень.transform.SetPositionAndRotation(поз, пов);
        // Логотип — низом над верхним краем рамки, с зазором (раньше налезал на меню).
        float полвысоты = H * (ширина / W) * 0.5f;
        _диорама.ПоставитьЛоготип(поз + пов * Vector3.up * (полвысоты + 0.05f), пов);

        _фонПанели = _панель.Прямоугольник(_панель.Rt, 0, 0, W, H, _панель.ЦветФона);
        _панель.Прямоугольник(_панель.Rt, 0, 0, W, 4, _панель.ЦветАкцент);
        _экранRt = _панель.Контейнер(_панель.Rt, "Экран");
    }

    void ПоказатьЭкран(Экран э, bool сохранитьОжидание = false)
    {
        ОсвободитьТекстуры();
        if (!сохранитьОжидание) ОтменитьОжидание();
        _подтвердитьДо = -1f;
        _экран = э;
        VrPanel.Очистить(_экранRt);
        switch (э)
        {
            case Экран.Главный: ЭкранГлавный(); break;
            case Экран.Результаты: ЭкранРезультаты(); break;
            case Экран.Подробно: ЭкранПодробно(); break;
            case Экран.Настройки: ЭкранНастройки(); break;
        }
    }

    void Шапка(string заголовок, string подзаголовок, bool назад = true)
    {
        var p = _панель;
        p.Текст(_экранRt, 36, 18, 700, 24, 17, p.ЦветВтор, перенос: false).text = подзаголовок;
        var t = p.Текст(_экранRt, 36, 42, 700, 44, 34, p.ЦветТекста, перенос: false);
        t.fontStyle = FontStyles.Bold; t.text = заголовок;
        if (назад) p.Кнопка(_экранRt, W - 206, 26, 170, 50, "<b>В МЕНЮ</b>", p.ЦветВтор, () => ПоказатьЭкран(Экран.Главный), кегль: 22);
        p.Прямоугольник(_экранRt, 36, 100, W - 72, 1, new Color(1f, 1f, 1f, 0.08f));
    }

    void ЭкранГлавный()
    {
        var p = _панель;
        p.Текст(_экранRt, 60, 40, 500, 30, 18, p.ЦветВтор).text = "ГЛАВНОЕ МЕНЮ";
        string[] надписи = { "НАЧАТЬ МИССИЮ", "РЕЗУЛЬТАТЫ", "ИСПЫТАНИЯ", "НАСТРОЙКИ", "ВЫХОД" };
        System.Action[] действия = { НачатьМиссию, () => ПоказатьЭкран(Экран.Результаты), НачатьИспытания, () => ПоказатьЭкран(Экран.Настройки), Выход };
        for (int i = 0; i < надписи.Length; i++)
        {
            Color c = i == 0 ? p.ЦветАкцент : i == надписи.Length - 1 ? p.ЦветВтор : new Color(0.55f, 0.75f, 0.9f);
            p.Кнопка(_экранRt, 60, 86 + i * 78, 420, 66, $"<b>{надписи[i]}</b>", c, действия[i], кегль: 28);
        }

        // Справа — карточка миссии: название и живой «киношный» кадр пролёта над трубой.
        float x = 540, w = W - x - 50;
        p.Прямоугольник(_экранRt, x, 90, w, 380, new Color(1f, 1f, 1f, 0.04f));
        p.Текст(_экранRt, x + 20, 106, w - 40, 28, 20, p.ЦветТекста, перенос: false).text = "<b>Обследование трубопровода</b>";
        // Постер миссии — снимок места работ (Resources/Menu/mission_pipeline), чуть затемнённый.
        if (_постер == null) _постер = Resources.Load<Texture2D>("Menu/mission_pipeline");
        float кадрW = w - 40;
        float кадрH = _постер != null ? кадрW * _постер.height / (float)_постер.width : кадрW * 9f / 16f;
        p.Прямоугольник(_экранRt, x + 18, 144, кадрW + 4, кадрH + 4, new Color(0.3f, 0.85f, 1f, 0.35f));
        if (_постер != null)
        {
            p.Картинка(_экранRt, x + 20, 146, кадрW, кадрH, _постер, new Color(0.85f, 0.88f, 0.9f));   // ровное лёгкое затемнение
        }
        var последний = MissionArchive.Список();
        if (последний.Count > 0)
        {
            var з = последний[0];
            float доля = з.максБалл > 0 ? з.балл / з.максБалл : 0f;
            p.Текст(_экранRt, x + 20, 158 + кадрH, w - 40, 26, 16, p.ЦветВтор, перенос: false).text =
                $"Последний результат: <color=#{VrPanel.Hex(ЦветПоДоле(доля))}><b>{з.балл:0} из {з.максБалл:0}</b></color> · {з.дата}";
            p.Кнопка(_экранRt, x + 20, 428, w - 40, 36, "<b>ПОДРОБНЕЕ</b>", p.ЦветАкцент, () => { _выбранная = з; ПоказатьЭкран(Экран.Подробно); }, кегль: 20);
        }
    }

    // ---------------- Результаты ----------------

    const int НаСтранице = 6;

    void ЭкранРезультаты()
    {
        var p = _панель;
        _архив = MissionArchive.Список();
        Шапка("Результаты", "АРХИВ ПРОЙДЕННЫХ МИССИЙ");
        if (_архив.Count == 0)
        {
            p.Текст(_экранRt, 36, 140, W - 72, 60, 22, p.ЦветВтор).text = "Пока пусто. Пройдите миссию — результат сохранится здесь.";
            return;
        }
        int страниц = Mathf.CeilToInt(_архив.Count / (float)НаСтранице);
        _страница = Mathf.Clamp(_страница, 0, страниц - 1);

        string вт = VrPanel.Hex(p.ЦветВтор);
        p.Текст(_экранRt, 36, 112, W - 72, 22, 15, p.ЦветВтор).text =
            "<pos=8%>ДАТА<pos=35%>БАЛЛ<pos=50%>ВРЕМЯ<pos=63%>ДЕФЕКТЫ<pos=76%>УДАРЫ";
        for (int k = 0; k < НаСтранице; k++)
        {
            int i = _страница * НаСтранице + k;
            if (i >= _архив.Count) break;
            var з = _архив[i];
            float y = 140 + k * 62;

            // Галочка выбора (для выборочного удаления) — отдельно от строки.
            string id = з.id;
            var кв = p.Прямоугольник(_экранRt, 36, y, 54, 54, p.ЦветВтор);
            p.ПодключитьНажатие(кв, 54, 54, p.ЦветВтор, () => { if (!_выбранные.Remove(id)) _выбранные.Add(id); ПоказатьЭкран(Экран.Результаты); },
                                () => _выбранные.Contains(id));
            if (_выбранные.Contains(id)) p.Прямоугольник((RectTransform)кв.transform, 15, 15, 24, 24, p.ЦветАкцент);
            else p.Прямоугольник((RectTransform)кв.transform, 17, 17, 20, 20, new Color(1f, 1f, 1f, 0.12f));

            float rx = 100, rw = W - 36 - rx;
