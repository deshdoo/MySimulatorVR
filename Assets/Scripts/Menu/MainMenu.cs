    void НачатьПовтор(MissionArchive.Запись з)
    {
        var данные = MissionArchive.ЗагрузитьПовтор(з.id);
        if (данные == null) return;
        var go = new GameObject("Повтор");
        SceneManager.MoveGameObjectToScene(go, _сцена);
        _повтор = go.AddComponent<MenuReplayTable>();

        // Стол — перед оператором, на уровне пояса.
        Vector3 f = Vector3.ProjectOnPlane(_голова.forward, Vector3.up).normalized;
        if (f.sqrMagnitude < 0.01f) f = _диорама.Вперёд;
        Vector3 стол = _голова.position + f * 0.85f + Vector3.down * 0.6f;
        if (!_повтор.Построить(з, данные, стол, Quaternion.LookRotation(f, Vector3.up), _шрифт))
        {
            _повтор.Убрать(); _повтор = null;
            return;
        }
        _панель.Корень.SetActive(false);
        _экран = Экран.Повтор;

        // Пульт повтора — небольшая панель над дальним краем стола.
        _пультПовтора = new VrPanel("ПультПовтора", 900, 200, 0.75f, _сцена, _шрифт, false);
        Vector3 поз = стол + f * 0.65f + Vector3.up * 0.55f;
        _пультПовтора.Корень.transform.SetPositionAndRotation(поз, Quaternion.LookRotation(поз - _голова.position, Vector3.up));
        var p = _пультПовтора;
        var rt = p.Rt;
        p.Прямоугольник(rt, 0, 0, 900, 200, p.ЦветФона);
        p.Прямоугольник(rt, 0, 0, 900, 3, p.ЦветАкцент);
        p.Текст(rt, 24, 12, 600, 26, 18, p.ЦветВтор, перенос: false).text = $"3D-ПОВТОР · {з.дата} · {з.балл:0} из {з.максБалл:0}";
        _состояниеПовтора = p.Текст(rt, 24, 40, 600, 26, 18, p.ЦветТекста, перенос: false);
        _времяПовтора = p.Текст(rt, 650, 12, 226, 56, 34, p.ЦветТекста, TextAlignmentOptions.TopRight);
        p.Прямоугольник(rt, 24, 78, 852, 8, new Color(1f, 1f, 1f, 0.1f));
        _полосаПовтора = p.Прямоугольник(rt, 24, 78, 0, 8, p.ЦветАкцент);
        float y = 110;
        p.Кнопка(rt, 24, y, 120, 64, "<b>–30 с</b>", p.ЦветВтор, () => _повтор.Перемотать(-30f), кегль: 22);
        p.Кнопка(rt, 154, y, 180, 64, "<b>ПУСК / ПАУЗА</b>", p.ЦветАкцент, () =>
        {
            if (_повтор.Время >= _повтор.Длительность) { _повтор.ВНачало(); _повтор.Пауза = false; }
            else _повтор.Пауза = !_повтор.Пауза;
        }, кегль: 20);
        p.Кнопка(rt, 344, y, 120, 64, "<b>+30 с</b>", p.ЦветВтор, () => _повтор.Перемотать(30f), кегль: 22);
        foreach (var (ск, x) in new[] { (1f, 494f), (4f, 584f), (16f, 674f) })
        {
            float с = ск;
            p.Кнопка(rt, x, y, 80, 64, $"<b>×{ск:0}</b>", p.ЦветАкцент, () => _повтор.Скорость = с, () => Mathf.Approximately(_повтор.Скорость, с), 22);
        }
        p.Кнопка(rt, 776, y, 100, 64, "<b>ВЫЙТИ</b>", p.ЦветПлохо, ЗакончитьПовтор, кегль: 20);
    }

    void ОбновитьПультПовтора()
    {
        if (_повтор == null) return;
        float д = Mathf.Max(0.01f, _повтор.Длительность);
        _времяПовтора.text = $"<b>{MissionStats.ФорматВремени(_повтор.Время)}</b><size=55%><color=#{VrPanel.Hex(_пультПовтора.ЦветВтор)}> / {MissionStats.ФорматВремени(д)}</color></size>";
