        var д = ControllerBindings.Список();
        if (д.Count == 0)
        {
            _панель.Текст(_экранRt, 36, 300, W - 72, 60, 19, _панель.ЦветВтор).text = "Действия контроллеров не найдены (нет XR-рига с Input Action Manager).";
            return;
        }
        СтрокиНазначений(д.Count,
            i => д[i].Название, i => д[i].Группа,
            i => ControllerBindings.Имя(д[i]),
            i => ControllerBindings.Переназначено(д[i]),
            i => _ждёмКнопку == д[i].Название,
            i =>
            {
                ОтменитьОжидание();
                _ждёмКнопку = д[i].Название;
                _операция = ControllerBindings.Переназначить(д[i], () => { _операция = null; _ждёмКнопку = null; ПоказатьЭкран(Экран.Настройки); });
                ПоказатьЭкран(Экран.Настройки, true);
            },
            "Нажмите новую кнопку на контроллере. Esc на клавиатуре — отмена.",
            "Курок — под указательным пальцем, хват — боковая кнопка под средним. Нажмите справа, чтобы переназначить.",
            ControllerBindings.СброситьВсё);
    }

    void ОтменитьОжидание()
    {
        _ждёмКлавишу = null;
        if (_операция != null) { var o = _операция; _операция = null; _ждёмКнопку = null; o.Cancel(); }
        _ждёмКнопку = null;
    }

    void Update()
    {
        ДержатьУМеню();
        if (_панель != null) _панель.Обновить();
        if (_пультПовтора != null) { _пультПовтора.Обновить(); ОбновитьПультПовтора(); }

        // Режим «нажмите клавишу».
        if (_ждёмКлавишу.HasValue && _экран == Экран.Настройки && Time.frameCount > _ждёмСКадра)
        {
            Key нажата = KeyBindings.НажатаЛюбая();
            if (нажата != Key.None)
            {
                if (нажата != Key.Escape) KeyBindings.Назначить(_ждёмКлавишу.Value, нажата);
                ПоказатьЭкран(Экран.Настройки);   // сбросит ожидание
            }
        }
    }

