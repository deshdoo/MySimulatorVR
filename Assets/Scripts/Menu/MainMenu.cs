    }

    // Затемнение: чёрная плоскость прямо перед глазами, поверх всего.
    void СоздатьЗатемнение()
    {
        if (_затемнениеКорень != null) return;
        _затемнениеКорень = new GameObject("Затемнение", typeof(RectTransform));
        _затемнениеКорень.transform.SetParent(_голова, false);
        _затемнениеКорень.transform.localPosition = new Vector3(0f, 0f, 0.15f);
        var c = _затемнениеКорень.AddComponent<Canvas>();
        c.renderMode = RenderMode.WorldSpace;
        c.sortingOrder = 32000;
        var rt = (RectTransform)_затемнениеКорень.transform;
        rt.sizeDelta = new Vector2(100f, 100f);
        rt.localScale = Vector3.one * 0.01f;
        var img = new GameObject("Ч", typeof(RectTransform)).AddComponent<Image>();
        img.rectTransform.SetParent(rt, false);
        img.rectTransform.anchorMin = Vector2.zero; img.rectTransform.anchorMax = Vector2.one;
        img.rectTransform.offsetMin = img.rectTransform.offsetMax = Vector2.zero;
        var m = new Material(Canvas.GetDefaultCanvasMaterial());
        m.SetInt("unity_GUIZTestMode", (int)CompareFunction.Always);
        img.material = m;
        img.raycastTarget = false;
        _затемнение = img;
    }

    IEnumerator Затемнить(bool вЧёрное)
    {
        if (_затемнение == null) СоздатьЗатемнение();
        float от = вЧёрное ? 0f : 1f, до = вЧёрное ? 1f : 0f;
        for (float t = 0f; t < 1f; t += Time.unscaledDeltaTime / 0.45f)
        {
            _затемнение.color = new Color(0f, 0f, 0f, Mathf.Lerp(от, до, Mathf.SmoothStep(0f, 1f, t)));
            yield return null;
        }
        _затемнение.color = new Color(0f, 0f, 0f, до);
    }

