using TMPro;
using Unity.XR.CoreUtils;
using UnityEngine;

// Настройки во время миссии (Меню → НАСТРОЙКИ): те же вкладки «Звук» и «Управление», что
// в главном меню (ВкладкиНастроек), всё меняется сразу, без перезапуска. «Физики» здесь
// нет: она задаётся до начала миссии. Окно встаёт перед оператором на расстоянии руки —
// жать удобно и лучом, и пальцем — и рисуется поверх кабины. Закрывается крестиком или
// кнопкой «Меню» (Menu левого, B правого, Esc на клавиатуре).
public class НастройкиВИгре : MonoBehaviour
{
    const float Ширина_м = 0.8f, Дальность_м = 0.6f;
    const float W = ВкладкиНастроек.W, H = ВкладкиНастроек.H;

    static НастройкиВИгре _я;
    VrPanel _панель;
    RectTransform _экран;
    ВкладкиНастроек _вкладки;
    bool _управление;   // открыта вкладка «Управление» (иначе «Звук»)

    public static bool Открыто => _я != null && _я._панель != null;
    // Ждём новую кнопку для переназначения: кнопка «Меню» и Esc в это время не закрывают окно.
    public static bool ЖдёмКнопку => Открыто && _я._вкладки.ЖдёмКнопку;

    public static void Открыть()
    {
        if (_я == null) _я = new GameObject("НастройкиВИгре").AddComponent<НастройкиВИгре>();
        _я.Построить();
    }

    public static void Закрыть() { if (_я != null) _я.Убрать(); }

    void Построить()
    {
        Убрать();
        var риг = FindFirstObjectByType<XROrigin>();
        if (риг == null || риг.Camera == null) return;
        var голова = риг.Camera.transform;
        var hud = FindFirstObjectByType<MissionHudDisplay>();
        _панель = new VrPanel("НастройкиВИгре", W, H, Ширина_м, риг.gameObject.scene, hud != null ? hud.шрифт : null, true);
        Vector3 вперёд = Vector3.ProjectOnPlane(голова.forward, Vector3.up);
        вперёд = вперёд.sqrMagnitude > 1e-4f ? вперёд.normalized : Vector3.forward;
        Vector3 поз = голова.position + вперёд * Дальность_м + Vector3.down * 0.12f;
        _панель.Корень.transform.SetPositionAndRotation(поз, Quaternion.LookRotation(поз - голова.position, Vector3.up));
        _панель.Окно();
        _экран = _панель.Контейнер(_панель.Rt, "Экран");
        _вкладки = new ВкладкиНастроек(_панель, _экран, Показать);
        Показать(false);
        VrPanel.ЗаблокироватьНажатия(0.4f);   // окно появилось под лучом/пальцем, которым нажали «Настройки»
    }

    void Показать(bool сохранитьОжидание)
    {
        if (_панель == null) return;
        _вкладки.Очистить(сохранитьОжидание);
        VrPanel.Очистить(_экран);
        var p = _панель;
        var под = p.Текст(_экран, 36, 18, 700, 24, 17, p.ЦветВтор, перенос: false);
        под.characterSpacing = 4f; под.text = "ЗВУК И УПРАВЛЕНИЕ";
        var t = p.Текст(_экран, 36, 42, 700, 44, 34, p.ЦветТекста, перенос: false);
        t.fontStyle = FontStyles.Bold; t.text = "Настройки";
        p.Кнопка(_экран, W - 86, 26, 50, 50, "×", p.ЦветВтор, Закрыть, кегль: 34);
        p.Прямоугольник(_экран, 36, 100, W - 72, 1, new Color(1f, 1f, 1f, 0.08f));
        p.Кнопка(_экран, 36, 112, 200, 48, "<b>ЗВУК</b>", p.ЦветАкцент, () => { _управление = false; Показать(false); }, () => !_управление, 22);
        p.Кнопка(_экран, 246, 112, 240, 48, "<b>УПРАВЛЕНИЕ</b>", p.ЦветАкцент, () => { _управление = true; _вкладки.Страница = 0; Показать(false); }, () => _управление, 22);
        if (_управление) { _вкладки.Управление(); return; }
        _вкладки.Звук();
        p.Текст(_экран, 60, H - 70, W - 120, 40, 15, p.ЦветВтор).text =
            "Меняется сразу. Физика аппарата и воды задаётся в главном меню, до начала миссии.";
    }

    void Update()
    {
        if (_панель == null) return;
        if (MissionManager.Instance == null || MainMenu.Открыто) { Убрать(); return; }   // вышли из миссии
        _панель.Обновить();
        _вкладки.Обновить();
    }

    void Убрать()
    {
        _вкладки?.ОтменитьОжидание();
        if (_панель != null) _панель.Уничтожить();
        _панель = null;
    }

    void OnDestroy() => Убрать();
}
