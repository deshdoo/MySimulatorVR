using UnityEngine;
using UnityEngine.SceneManagement;

// Настройки миссии из меню (вкладка «Физика»), хранятся в PlayerPrefs.
//
// Аппарат — «Марлин-350» (ТТХ в MarlinSpec). Вместо произвольных массы/тяги
// инструктор выбирает то, что меняется у реального аппарата:
//   • комплектация: базовая (паспорт) / поисковая (+ доплеровский лаг) /
//     рабочая (+ лаг, + инструмент закручивания) — от неё масса и оборудование;
//   • тяга движителей 60–100 % — износ/неисправность винтов;
//   • запас плавучести −10…+20 Н — как аппарат отбалластирован перед погружением.
// Вода:
//   • солёность 0 ‰ (озеро) … 40 ‰ (Красное море), температура 0–30 °C;
//   • течение 0–150 % от заданного в сцене.
//
// Солёность и температура меняют ФАКТИЧЕСКИЕ свойства воды: плотность (сопротивление,
// давление на глубиномер, плавучесть) и скорость звука (эхолот, доплеровский лаг,
// гидролокатор). Приборы же откалиброваны на морскую воду (1025 кг/м³, 1500 м/с) и
// это не меняется — поэтому в пресной или тёплой воде они начинают систематически
// ошибаться, как в жизни. Балласт аппарата тоже подобран под морскую воду: в пресной
// он становится тяжелее воды и тонет — реальные ROV перед работой в озере догружают поплавками.
//
// Применяется при загрузке сцены миссии и ещё раз при выходе из меню в миссию.
// Только для НОВЫХ миссий: сохранённая продолжается со снимком из своего сохранения
// (MissionArchive.Запись.физика) — её условия менять нельзя.
public static class PhysicsSettings
{
    public class Параметр
    {
        public string Ключ, Название, Ед, Формат;
        public float Мин, Макс, Шаг, ПоУмолчанию;
        public string[] Варианты;   // для выбора из списка (значение — номер варианта)
        public float Значение
        {
            get => PlayerPrefs.GetFloat(Ключ, ПоУмолчанию);
            set { PlayerPrefs.SetFloat(Ключ, Mathf.Clamp(value, Мин, Макс)); PlayerPrefs.Save(); }
        }
        public string Текст(float v) => Варианты != null
            ? Варианты[Mathf.Clamp(Mathf.RoundToInt(v), 0, Варианты.Length - 1)]
            : v.ToString(Формат) + " " + Ед;
    }

    // Опорные значения сцены: на них откалиброваны приборы и подобран балласт.
    const float ОпорнаяСолёность = 35f, ОпорнаяТемпература = 6f;
    const float ОпорнаяПлотность = 1025f, ОпорнаяСкоростьЗвука = 1500f;

    public static readonly Параметр Комплектация = new Параметр { Ключ = "m350_kit",     Название = "Комплектация «Марлин-350»", Мин = 0f, Макс = 2f, Шаг = 1f, ПоУмолчанию = 2f, Варианты = MarlinSpec.НазванияКомплектаций };
    public static readonly Параметр Тяга         = new Параметр { Ключ = "m350_thrust",  Название = "Тяга движителей (износ)",  Ед = "%", Формат = "0",       Мин = 60f, Макс = 100f, Шаг = 5f, ПоУмолчанию = 100f };
    public static readonly Параметр Плавучесть   = new Параметр { Ключ = "m350_buoy",    Название = "Запас плавучести",        Ед = "Н", Формат = "+0;−0;0", Мин = -10f, Макс = 20f, Шаг = 1f, ПоУмолчанию = 5f };
    public static readonly Параметр Солёность    = new Параметр { Ключ = "phys_salinity", Название = "Солёность воды",         Ед = "‰",  Формат = "0", Мин = 0f, Макс = 40f,  Шаг = 5f,  ПоУмолчанию = 35f };
    public static readonly Параметр Температура  = new Параметр { Ключ = "phys_temp",     Название = "Температура воды",       Ед = "°C", Формат = "0", Мин = 0f, Макс = 30f,  Шаг = 2f,  ПоУмолчанию = 6f };
    public static readonly Параметр Течение      = new Параметр { Ключ = "m350_current",  Название = "Сила течения",           Ед = "%",  Формат = "0", Мин = 0f, Макс = 150f, Шаг = 10f, ПоУмолчанию = 100f };

    // Первые ПараметровАппарата — колонка «аппарат» в меню, остальные — «вода».
    public static readonly Параметр[] Все = { Комплектация, Тяга, Плавучесть, Солёность, Температура, Течение };
    public const int ПараметровАппарата = 3;

    public static MarlinSpec.Комплектация ТекущаяКомплектация =>
        (MarlinSpec.Комплектация)Mathf.Clamp(Mathf.RoundToInt((_действующие ?? Текущие())[0]), 0, 2);
    public static bool ЛагУстановлен => MarlinSpec.ЕстьЛаг(ТекущаяКомплектация);

    public static void СброситьВсё()
    {
        foreach (var п in Все) PlayerPrefs.DeleteKey(п.Ключ);
        PlayerPrefs.Save();
    }

    // Снимок значений в порядке Все[]. Каждая миссия живёт со своим снимком: он
    // пишется в сохранение, и «Продолжить» поднимает миссию с ним, а не с текущими
    // настройками меню. Настройки действуют только на НОВЫЕ миссии.
    public static float[] Текущие()
    {
        var v = new float[Все.Length];
        for (int i = 0; i < v.Length; i++) v[i] = Все[i].Значение;
        return v;
    }
    public static float[] ПоУмолчанию()
    {
        var v = new float[Все.Length];
        for (int i = 0; i < v.Length; i++) v[i] = Все[i].ПоУмолчанию;
        return v;
    }

    // Снимок, с которым идёт текущая миссия, — его сохраняет архив.
    static float[] _действующие;
    public static float[] Действующие => (float[])(_действующие ?? Текущие()).Clone();

    // Плотность морской воды, кг/м³: упрощённое уравнение состояния у поверхности
    // (≈ +0.78 кг/м³ на 1 ‰ солёности, нелинейное убывание с нагревом). Привязана к
    // опорной точке сцены, чтобы при штатных настройках ничего не менялось.
    public static float ПлотностьВоды => ПлотностьПри(Солёность.Значение, Температура.Значение);
    static float ПлотностьПри(float S, float T) => ОпорнаяПлотность + Плотность(S, T) - Плотность(ОпорнаяСолёность, ОпорнаяТемпература);
    static float Плотность(float S, float T) => 999.84f + 0.78f * S - 0.0065f * (T - 4f) * (T - 4f) - 0.0026f * S * (T - 4f);

    // Скорость звука, м/с — формула Медвина (1975), без члена глубины (он одинаков
    // для обеих точек и сокращается). Тоже привязана к опорной точке.
    public static float СкоростьЗвука => СкоростьЗвукаПри(Солёность.Значение, Температура.Значение);
    static float СкоростьЗвукаПри(float S, float T) => ОпорнаяСкоростьЗвука + Медвин(S, T) - Медвин(ОпорнаяСолёность, ОпорнаяТемпература);
    static float Медвин(float S, float T) => 1449.2f + 4.6f * T - 0.055f * T * T + 0.00029f * T * T * T + (1.34f - 0.01f * T) * (S - 35f);

    static float МассаПоМеню => MarlinSpec.Масса((MarlinSpec.Комплектация)Mathf.RoundToInt(Комплектация.Значение));

    // Итоговая плавучесть, Н: запас, выставленный в морской воде, плюс изменение
    // архимедовой силы из-за другой плотности при том же объёме корпуса V = m/ρ₀.
    public static float ИтоговаяПлавучесть => ПлавучестьПри(Плавучесть.Значение, ПлотностьВоды, МассаПоМеню);
    static float ПлавучестьПри(float запас, float ρ, float m) => запас + (ρ - ОпорнаяПлотность) * 9.81f * m / ОпорнаяПлотность;

    [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.BeforeSceneLoad)]
    static void Подписаться() => SceneManager.sceneLoaded += (s, _) => { if (s.name == "Main") Применить(); };

    // Вертикальная тяга с учётом износа, Н, и сможет ли аппарат всплыть, если
    // движители сильно повреждены (тяга режется до ТягаПриТяжёломУроне ≈ 20 %).
    public static float ВертикальнаяТяга => MarlinSpec.ТягаВертикаль_Н * Тяга.Значение / 100f;
    public static bool ТонетПриПоломке => -ИтоговаяПлавучесть > 0.2f * ВертикальнаяТяга;

    // Новая миссия — текущие настройки меню. Продолжение — снимок из сохранения
    // (пустой или старого формата — штатные значения).
    public static void Применить() => Применить(Текущие());

    public static void Применить(float[] снимок)
    {
        var v = ПоУмолчанию();
        if (снимок != null && снимок.Length == v.Length)   // снимок прежнего формата (до «Марлина») — не наш
            for (int i = 0; i < v.Length; i++) v[i] = Mathf.Clamp(снимок[i], Все[i].Мин, Все[i].Макс);
        _действующие = v;
        var кмп = (MarlinSpec.Комплектация)Mathf.Clamp(Mathf.RoundToInt(v[0]), 0, 2);
        float тяга = v[1] / 100f, запас = v[2], S = v[3], T = v[4], течение = v[5] / 100f;
        float масса = MarlinSpec.Масса(кмп);
        float ρ = ПлотностьПри(S, T), c = СкоростьЗвукаПри(S, T);

        var rov = Object.FindFirstObjectByType<RovController>();
        var сим = Object.FindFirstObjectByType<RovSystemsSimulator>();
        MarlinSpec.Применить(rov, сим, кмп, тяга);   // ТТХ «Марлина» поверх значений сцены
        if (rov != null)
        {
            rov.ПлотностьВоды = ρ;
            rov.ЧистаяПоложительнаяПлавучесть_Н = ПлавучестьПри(запас, ρ, масса);
            if (rov.Течение != null) rov.Течение.Множитель = течение;
        }
        if (сим != null)
        {
            сим.ТемператураВоды = T;
            сим.ПлотностьВоды = ρ;
            // Awake симулятора уже выставил температуру движителей по старой воде —
            // миссия ещё не шла, так что просто переставляем.
            RovSystems.thrusterTemp_C = сим.ТемператураВоды + 5f;
        }

        // Фактические свойства воды для датчиков; их собственная калибровка не трогается.
        foreach (var д in Object.FindObjectsByType<RovDepthSensor>(FindObjectsSortMode.None)) д.ПлотностьВодыФакт = ρ;
        foreach (var д in Object.FindObjectsByType<RovAltimeterSensor>(FindObjectsSortMode.None)) д.СкоростьЗвукаФакт_мс = c;
        foreach (var д in Object.FindObjectsByType<RovSonar>(FindObjectsSortMode.None)) д.СкоростьЗвукаФакт_мс = c;
        foreach (var д in Object.FindObjectsByType<RovSpeedSensor>(FindObjectsSortMode.None))
        {
            д.СкоростьЗвукаФакт_мс = c;
            д.enabled = MarlinSpec.ЕстьЛаг(кмп);   // нет лага — прибора на борту нет: ни показаний, ни гашения сноса
        }
    }
}
