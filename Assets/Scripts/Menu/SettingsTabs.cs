using System.Collections.Generic;
using TMPro;
using UnityEngine;
using UnityEngine.InputSystem;
using UnityEngine.XR.Interaction.Toolkit.Interactables;
using UnityEngine.XR.Interaction.Toolkit.Interactors;

// Вкладки «Звук» и «Управление» — общие для главного меню (MainMenu → Настройки) и окна
// настроек в миссии (НастройкиВИгре): вид и поведение одни и те же. Всё действует сразу:
// громкость источники звука читают каждый кадр (RovAudio, UiSound), режим ввода
// переключает РежимВводаРига, переназначение кнопок — штатный Input System.
// Окно 1000×640; вкладки рисуются ниже шапки и кнопок вкладок (y ≥ 160).
public class ВкладкиНастроек
{
    public const float W = 1000f, H = 640f;
    const int КнопокНаСтранице = 6;

    readonly VrPanel _p;
    readonly RectTransform _rt;
    readonly System.Action<bool> _перестроить;   // перерисовать окно; true — не сбрасывать ожидание кнопки

    public int Страница;
    string _ждёмКнопку;   // «название|группа» действия, которому ждём новую кнопку
    InputActionRebindingExtensions.RebindingOperation _операция;
    string _чтоПодтверждаем; float _подтвердитьДо = -1f; TMP_Text _надписьПодтв; string _обычнаяПодтв;

    // Строки списка кнопок и что они подсвечивают на стенде контроллеров (если он есть).
    public readonly List<(XRSimpleInteractable и, int рука, string кнопка)> СтрокиСтенда =
        new List<(XRSimpleInteractable, int, string)>();

    public bool ЖдёмКнопку => _операция != null;

    public ВкладкиНастроек(VrPanel панель, RectTransform экран, System.Action<bool> перестроить)
    {
        _p = панель; _rt = экран; _перестроить = перестроить;
    }

    // Перед перерисовкой окна.
    public void Очистить(bool сохранитьОжидание)
    {
        СтрокиСтенда.Clear();
        if (!сохранитьОжидание) ОтменитьОжидание();
        _чтоПодтверждаем = null;
    }

    public void ОтменитьОжидание()
    {
        if (_операция != null) { var o = _операция; _операция = null; o.Cancel(); }
        _ждёмКнопку = null;
    }

    // Каждый кадр: вернуть надпись кнопки «ТОЧНО? ЕЩЁ РАЗ», если второго нажатия не было.
    public void Обновить()
    {
        if (_чтоПодтверждаем == null || Time.unscaledTime < _подтвердитьДо) return;
        if (_надписьПодтв != null) _надписьПодтв.text = _обычнаяПодтв;
        _чтоПодтверждаем = null;
    }

    // ---------------- Звук ----------------

    public void Звук()
    {
        var p = _p;
        // Звук игры синтезирован кодом (ПроцЗвук): фон воды, гул движителей, удары,
        // сигнал фиксации дефекта; щелчки меню — «интерфейс».
        p.Регулятор(_rt, 60, 180, 620, "Общая громкость", () => GameSettings.Громкость, v => GameSettings.Громкость = v);
        p.Регулятор(_rt, 60, 270, 620, "Окружение и удары", () => GameSettings.ГромкостьОкружения, v => GameSettings.ГромкостьОкружения = v);
        p.Регулятор(_rt, 60, 360, 620, "Движители", () => GameSettings.ГромкостьДвигателей, v => GameSettings.ГромкостьДвигателей = v);
        p.Регулятор(_rt, 60, 450, 620, "Интерфейс", () => GameSettings.ГромкостьИнтерфейса, v => { GameSettings.ГромкостьИнтерфейса = v; UiSound.Клик(); });
    }

    // ---------------- Управление ----------------

    // Чем управлять (РежимВводаРига): контроллерами или руками. Ниже — кнопки
    // контроллеров с переназначением или жесты рук.
    public void Управление()
    {
        var p = _p;
        var режимы = new[] { GameSettings.Ввод.Контроллеры, GameSettings.Ввод.Руки };
        string[] имена = { "Контроллеры", "Руки" };
        string[] подписи = { "кнопки и стики", "без контроллеров, своими руками" };
        for (int i = 0; i < 2; i++)
        {
            var р = режимы[i];
            float x = 36 + i * 470, y = 172, w = 458, h = 104;
            var фон = p.Прямоугольник(_rt, x, y, w, h, p.ЦветАкцент);
            p.ПодключитьНажатие(фон, w, h, p.ЦветАкцент, () => { ОтменитьОжидание(); GameSettings.РежимВвода = р; Страница = 0; _перестроить(false); },
                                () => GameSettings.РежимВвода == р);
            bool выбран = GameSettings.РежимВвода == р;
            p.Картинка((RectTransform)фон.transform, 18, 12, 80, 80, ИконкиВвода.Иконка(р), выбран ? Color.white : new Color(1f, 1f, 1f, 0.7f));
            p.Текст((RectTransform)фон.transform, 116, 22, w - 130, 32, 26, Color.white, перенос: false).text = $"<b>{имена[i]}</b>";
            p.Текст((RectTransform)фон.transform, 116, 58, w - 130, 24, 17, new Color(0.85f, 0.92f, 1f), перенос: false).text = подписи[i];
        }
        if (GameSettings.РежимВвода == GameSettings.Ввод.Руки) ЖестыРук();
        else СписокКнопок();
    }

    // Руки: что каким жестом делается — плитками в рамке, без переназначения (жесты задаёт
    // гарнитура). Это штатные интеракторы рига XR Origin Hands, захват рычага
    // (LeverInteractable) и меню на ладони (МенюНаЛадони).
    void ЖестыРук()
    {
        var p = _p;
        string[,] плитки =
        {
            { "Нажатие кнопки", "коснитесь кнопки кончиком указательного пальца" },
            { "Захват рычага", "сожмите пальцы на рукоятке и ведите руку; раскройте ладонь — рычаг отпущен" },
            { "Подсветка", "кнопка или рычаг загорается, когда палец рядом" },
            { "Меню", "разверните правую ладонь к себе и подержите полсекунды" },
        };
        const float зазор = 16f;
        float w = (W - 72 - зазор) / 2f, h = 118f;
        for (int i = 0; i < 4; i++)
        {
            float x = 36 + (i % 2) * (w + зазор), y = 296 + (i / 2) * (h + зазор);
            p.Прямоугольник(_rt, x, y, w, h, new Color(1f, 1f, 1f, 0.045f), 10f);
            p.Обводка(_rt, x, y, w, h, new Color(p.ЦветАкцент.r, p.ЦветАкцент.g, p.ЦветАкцент.b, 0.45f), 10f, 1.5f);
            p.Прямоугольник(_rt, x + 6, y + 12, 4, h - 24, p.ЦветАкцент, 2f);
            p.Текст(_rt, x + 22, y + 12, w - 36, 28, 21, p.ЦветТекста, перенос: false).text = $"<b>{плитки[i, 0]}</b>";
            p.Текст(_rt, x + 22, y + 44, w - 36, h - 52, 15, p.ЦветВтор).text = плитки[i, 1];
        }
    }

    // Кнопки контроллеров. Переназначение — штатный Input System, действует сразу на
    // рычаги и кнопки пульта и на «Меню».
    void СписокКнопок()
    {
        var p = _p;
        var д = ControllerBindings.Список();
        if (д.Count == 0)
        {
            p.Текст(_rt, 36, 300, W - 72, 60, 19, p.ЦветВтор).text = "Действия контроллеров не найдены (нет XR-рига с Input Action Manager).";
            return;
        }
        int страниц = Mathf.Max(1, Mathf.CeilToInt(д.Count / (float)КнопокНаСтранице));
        Страница = Mathf.Clamp(Страница, 0, страниц - 1);
        string вт = VrPanel.Hex(p.ЦветВтор);
        bool ктоТоЖдёт = false;
        for (int k = 0; k < КнопокНаСтранице; k++)
        {
            int i = Страница * КнопокНаСтранице + k;
            if (i >= д.Count) break;
            var действие = д[i];
            string ключ = действие.Название + "|" + действие.Группа;   // у левой и правой руки названия одинаковые
            float y = 292 + k * 42;
            p.Текст(_rt, 36, y + 7, 640, 30, 19, p.ЦветТекста, перенос: false).text =
                string.IsNullOrEmpty(действие.Группа) ? действие.Название
                    : $"{действие.Название}  <size=75%><color=#{вт}>{действие.Группа}</color></size>";
            bool жд = _ждёмКнопку == ключ;
            ктоТоЖдёт |= жд;
            string надпись = жд ? "<b>нажмите…</b>" : $"<b>{ControllerBindings.Имя(действие)}</b>" + (ControllerBindings.Переназначено(действие) ? " *" : "");
            var кн = p.Кнопка(_rt, W - 276, y, 240, 38, надпись, жд ? p.ЦветСредне : p.ЦветАкцент, () =>
            {
                ОтменитьОжидание();
                _ждёмКнопку = ключ;
                _операция = ControllerBindings.Переназначить(действие, () => { _операция = null; _ждёмКнопку = null; _перестроить(false); });
                _перестроить(true);
            }, () => _ждёмКнопку == ключ, 19);
            var и = кн.transform.parent.GetComponent<XRSimpleInteractable>();
            if (и != null && ControllerBindings.Разобрать(действие, out int рука, out string кнопка))
                СтрокиСтенда.Add((и, рука, кнопка == СтендКонтроллеров.НажатьСтик ? СтендКонтроллеров.Стик : кнопка));
        }
        float ny = H - 76;
        if (Страница > 0) p.Кнопка(_rt, 36, ny, 150, 52, "<b>НАЗАД</b>", p.ЦветВтор, () => { ОтменитьОжидание(); Страница--; _перестроить(false); }, кегль: 22);
        if (Страница < страниц - 1) p.Кнопка(_rt, 196, ny, 150, 52, "<b>ДАЛЕЕ</b>", p.ЦветВтор, () => { ОтменитьОжидание(); Страница++; _перестроить(false); }, кегль: 22);
        p.Текст(_rt, 360, ny + 2, 390, 52, 15, p.ЦветВтор).text = ктоТоЖдёт
            ? "Нажмите новую кнопку на контроллере. Esc на клавиатуре: отмена."
            : $"Стр. {Страница + 1}/{страниц}. Курок (Trigger) под указательным, Захват (Grip) сбоку под средним. Нажмите справа, чтобы переназначить.";
        var кнСброс = p.Кнопка(_rt, W - 236, ny, 200, 52, "<b>СБРОСИТЬ</b>", p.ЦветПлохо, null, кегль: 22);
        Подтверждаемая(кнСброс, "сброс", "<b>СБРОСИТЬ</b>", () => { ОтменитьОжидание(); ControllerBindings.СброситьВсё(); _перестроить(false); });
    }

    // Двойное нажатие для необратимых действий: первое — «ТОЧНО?», второе в течение 3 с — выполнить.
    void Подтверждаемая(TMP_Text надпись, string ключ, string обычный, System.Action действие)
    {
        var и = надпись.transform.parent.GetComponent<XRSimpleInteractable>();
        if (и == null) return;
        и.selectEntered.RemoveAllListeners();
        и.hoverEntered.RemoveAllListeners();
        float след = 0f;
        void Нажатие()
        {
            if (Time.unscaledTime < след) return;
            след = Time.unscaledTime + 0.3f;
            UiSound.Клик();
            if (_чтоПодтверждаем == ключ && Time.unscaledTime < _подтвердитьДо)
            {
                _чтоПодтверждаем = null;
                действие();
                return;
            }
            _чтоПодтверждаем = ключ; _подтвердитьДо = Time.unscaledTime + 3f;
            _надписьПодтв = надпись; _обычнаяПодтв = обычный;
            надпись.text = "<b>ТОЧНО? ЕЩЁ РАЗ</b>";
        }
        и.selectEntered.AddListener(_ => Нажатие());
        и.hoverEntered.AddListener(a => { if (a.interactorObject is XRPokeInteractor) Нажатие(); });
    }
}
